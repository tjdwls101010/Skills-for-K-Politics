종류 = "행정규칙"

# 평평한 문자열에서 조 번호를 뽑는다. 못 뽑으면 NULL 로 둔다 — 장 제목이 그 부류다.
_조 = re.compile(r"^제\s*(\d+)\s*조(?:\s*의\s*(\d+))?\s*(?:\(([^)]*)\))?")


def 조문들(몸통: dict) -> list[dict]:
    """`조문내용` 을 `행정규칙조문` 행으로. **타입이 두 가지다.**

    ⚠️ 배열 원소가 조문이 아닐 수 있다 — `"제1장 총 칙"` 같은 장 제목이 그대로 한 원소로
    온다. 법령의 `조문여부='전문'` 에 해당하는데 **행정규칙에는 그걸 알려주는 필드가 없다.**
    조문번호가 NULL 인 행에 그것들이 모인다.

    ⚠️ **`조문형식여부='N'` 은 "내용이 없다"가 아니라 "조 구조가 없다"다.** 계획 초안은
    그때 `행정규칙조문` 이 0행인 것을 정상으로 봤는데, 실측하니 `조문내용` 에 **평평한
    문자열로 본문이 통째로 들어 있다**(표본 60건 중 10건). 0행으로 두면 그 10%의 본문이
    DB 어디에도 남지 않는다 — `행정규칙` 테이블에는 본문 컬럼이 없다.
    **없는 조 번호를 지어내지 말고, 조문번호 NULL 인 한 행으로 통째로 넣는다.**
    """
    값 = 몸통.get("조문내용")
    if 값 is None:
        조각들: list[str] = []
    elif isinstance(값, str):
        조각들 = [값]
    else:
        조각들 = [정규화.씻는다(x) for x in 값]

    행들 = []
    for i, 조각 in enumerate(조각들):
        내용 = 정규화.씻는다(조각)
        if not 내용:
            continue
        m = _조.match(내용)
        행들.append(
            {
                "순서": i,
                "조문번호": int(m.group(1)) if m else None,
                "조문가지번호": int(m.group(2)) if m and m.group(2) else 0,
                "조문제목": (m.group(3).strip() if m and m.group(3) else None),
                "내용": 내용,
            }
        )
    return 행들


# ⚠️ **별표는 인라인으로 오지만 담지 않는다**(D42). 원천의 `별표` → `별표단위` 배열을
#    파싱하던 `별표들()` 이 여기 있었다 — 75,384행 · 저장 620MiB 였는데 서식류(빈 양식 표지)가
#    60,394행이고, 별표를 가진 규칙 13,183개 중 위임으로 법령에서 닿는 것이 16%뿐이었다.
#    **닿는 경로가 16%인데 지면과 소음은 100% 문다.**
#    실물은 `직결.py 행정규칙별표 --검색 …`(원천 `admbyl`)로 간다.


def 본문파싱(몸통: dict, 목록행: dict) -> tuple[dict, dict]:
    기본 = 몸통.get("행정규칙기본정보") or {}
    행 = {
        "행정규칙일련번호": str(목록행["행정규칙일련번호"]),
        "행정규칙ID": 정규화.씻는다(기본.get("행정규칙ID") or 목록행.get("행정규칙ID")),
        "행정규칙명": 정규화.씻는다(기본.get("행정규칙명") or 목록행.get("행정규칙명")),
        "행정규칙종류": 정규화.씻는다(기본.get("행정규칙종류") or 목록행.get("행정규칙종류")) or None,
        "발령일자": 정규화.날짜(기본.get("발령일자") or 목록행.get("발령일자")),
        # ⚠️ 공동 발령이 쉼표로 온다('2026-8,2026-047'). 단일 값으로 보지 마라.
        "발령번호": 정규화.씻는다(기본.get("발령번호") or 목록행.get("발령번호")) or None,
        "시행일자": 정규화.날짜(기본.get("시행일자") or 목록행.get("시행일자")),
        # ⚠️ 복수 소관이 쉼표로 온다('개인정보보호위원회,산업통상부'). = 로 걸면 놓친다.
        "소관부처명": 정규화.씻는다(기본.get("소관부처명") or 목록행.get("소관부처명")) or None,
        "담당부서기관명": 정규화.씻는다(기본.get("담당부서기관명")) or None,
        # 목록은 `현행연혁구분`, 본문은 `현행여부` 다. 또 이름이 갈린다.
        "현행여부": 정규화.씻는다(기본.get("현행여부") or 목록행.get("현행연혁구분")) or None,
        "제개정구분명": 정규화.씻는다(기본.get("제개정구분명") or 목록행.get("제개정구분명")) or None,
        "조문형식여부": 정규화.씻는다(기본.get("조문형식여부")) or None,
        "제개정이유": 정규화.씻는다(몸통.get("제개정이유")) or None,
        "부칙": 정규화.씻는다(몸통.get("부칙")) or None,
    }
    return 행, {"행정규칙조문": 조문들(몸통)}


def 수집(conn, c: 원천.Client, 로그=print, 표본=None, 전량=False) -> dict[str, int]:
    from 법제처.수집기 import 루프

    행들, 완결 = c.목록전량(종류)
    목록 = {str(r["행정규칙일련번호"]): r for r in 행들}
    로그(f"  목록 {len(목록):,}건{'' if 완결 else ' ⚠️ 불완결 — 정리를 건너뛴다'}")
    # 행정규칙도 개정되면 새 일련번호가 발급된다 → 목록에서 빠진 것을 정리한다.
    # ⚠️ 다만 **목록을 완결로 받았을 때만** — 부분 수신에서 지우면 수집물을 날린다.
    return 루프.수집루프(conn, c, 종류, 목록, 본문파싱, 로그, 표본, 전량, 정리=True, 검증된목록=완결, 진행자=원천.진행자)
