"""행정규칙(고시·훈령·예규·지침) 24,121건.

⚠️ **법령 조문 파서를 재사용하지 마라.** 원천이 `조문단위` 객체 배열이 아니라 **평평한 문자열 배열**이다. 그리고 `조문형식여부='N'`(실측 10%)이면 **타입 자체가 문자열로 바뀐다** — 배열로 알고 순회하면 글자 단위로 돌아 수만 행이 들어간다. 에러 없이.
"""

from __future__ import annotations

import re

from .. import 원천  # noqa: E402
