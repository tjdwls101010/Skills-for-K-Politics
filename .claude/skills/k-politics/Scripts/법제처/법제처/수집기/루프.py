"""수집기 공용 루프 — `수집루프`(목록 → 본문 → 정리를 한 자료종류에 대해 돈다).

개별 수집기(법령·판례·심판례·행정규칙·위임)가 이 모듈을 쓰고, 전체를 조율하는 `실행.py` 가 그 수집기들을 순서대로 부른다 — 이 모듈은 수집기를 import 하지 않는다.
"""

from __future__ import annotations

import sqlite3
from ..연결 import 트랜잭션
from ..저장 import record_failure, 기준선기록, 본문테이블, 없음인것, 잘못붙은없음, 저장, 철회된것
from ..정리 import _복귀대기기록, 정리한다


def 수집루프(
    conn: sqlite3.Connection,
    c,
    종류: str,
    목록: dict[str, dict],
    파싱,
    로그=print,
    표본: int | None = None,
    전량: bool = False,
    정리: bool = False,
    검증된목록: bool = True,
    진행자=None,
) -> dict[str, int]:
    """목록에서 대상을 고르고, 본문을 동시에 받아, 한 건씩 트랜잭션으로 넣는다.

    자료종류마다 다른 것은 **`파싱(몸통, 목록행) -> (행, 자식|None)` 하나뿐**이라 여기 모은다.
    `원천.py` 가 아니라 이 파일에 있는 이유는 DB 를 만지기 때문이다.

    **재개는 DB 가 안다**(D19) — 대상은 "목록에 있는데 본문 테이블에 없고, `없음` 으로
    확정되지도 않은 것"이다. 별도 진행 파일을 두면 DB 와 어긋나는 세 번째 상태가 생긴다.
    """
    테이블, 키컬럼, _ = 본문테이블[종류]
    수치 = {"목록": len(목록), "본문": 0, "실패": 0, "없음": 0, "정리": 0}

    기준선갱신 = 검증된목록
    if 정리:
        # ⚠️ **`목록` 이 비었을 때도 부른다.** 여기서 걸러 버리면 원천이 0건을 준 날
        #    `정리` 단계 기록이 아예 안 남고 옛 '완료' 가 그대로 남는다.
        수치["정리"], 기준선갱신 = 정리한다(
            conn, 종류, 테이블, 키컬럼, 목록, 검증된목록, 로그)

    기준선기록(conn, 종류, len(목록), 기준선갱신, 검증된목록)

    이미 = {r[0] for r in conn.execute(f"SELECT {키컬럼} FROM {테이블}")}
    없음 = 없음인것(conn, 종류)
    # 붙일 자격이 없었던 '없음' 표지. 목록에 있는 것만 되돌린다 — 목록 밖의 것은 물어도
    # 받을 데가 없고, 정리가 언젠가 표지째 치운다.
    되돌릴것 = 잘못붙은없음(conn, 종류) & set(목록)
    없음 = 없음 - 되돌릴것
    # ⚠️ **철회 표지를 목록 복귀만으로 걷지 않는다.** 표지의 뜻이 "본문 API 가 없다고
    #    답했다"이므로, 그 답이 바뀐 것을 확인해야 걷을 수 있다 — 목록에만 돌아오고 본문은
    #    여전히 없는 경우가 있고, 그때 표지를 걷으면 **오래된 본문이 정상 자료로 되돌아온다.**
    #    그래서 목록에 다시 나타난 철회 자료만 다시 묻는다. 목록 밖에 있는 동안은 안 묻는다 —
    #    안 그러면 철회 872건을 매일 다시 두드린다.
    되물을것 = 철회된것(conn, 종류) & set(목록)
    # ⚠️ **되물을 것을 맨 앞에 둔다.** `--표본` 이 걸린 실행에서 뒤에 있으면 매번 표본 밖으로
    #    밀리고, 목록 순서가 같으니 **몇 번을 돌려도 영영 안 묻는다** — 그동안 기준선은
    #    복귀를 반영해 갱신되므로 A1 이 계속 빨갛다.
    # ⚠️ **되돌릴 것도 맨 앞이다.** 뒤에 있으면 `--표본` 실행에서 매번 표본 밖으로 밀려
    #    영영 안 물어진다 — 되물을 것을 앞에 둔 것과 같은 이유다.
    앞 = 되물을것 | 되돌릴것
    대상 = sorted(앞, key=list(목록).index) + [
        k for k in 목록
        if k not in 앞 and (전량 or (k not in 이미 and k not in 없음))]
    if 되물을것:
        로그(f"  목록에 돌아온 철회 자료 {len(되물을것):,}건을 다시 묻는다")
    if 표본:
        대상 = 대상[:표본]
    # ⚠️ **표본으로 자른 뒤에 걷는다.** 이번에 안 물을 것의 표지를 걷으면 그 자료는 본문도
    #    '없음'도 없는 상태가 되고, A1 의 `본문 + 없음 = 목록` 이 **이번 실행이 고칠 수
    #    없는 방향으로** 깨진다. 걷는 자격은 "실제로 다시 묻는다"에서 나온다.
    if 걷을것 := 되돌릴것 & set(대상):
        with 트랜잭션(conn):
            conn.executemany(
                "DELETE FROM 수집실패 WHERE 자료종류=? AND 자료ID=?",
                [(종류, k) for k in 걷을것])
        로그(f"  원천이 '없다'고 한 적 없는 '없음' 표지 {len(걷을것):,}건을 걷고 다시 묻는다")
    로그(f"  본문 대상 {len(대상):,}건 (이미 {len(이미):,} · 없음 {len(없음):,})")
    if not 대상:
        _복귀대기기록(conn, 종류, 목록, 검증된목록)
        return 수치

    # ⚠️ 진행 표시를 **넘겨받는다.** 적재는 DB 계층이라 원천(HTTP)을 import 하지 않는다.
    진행 = 진행자(로그, f"{종류} 본문", len(대상), c) if 진행자 else (lambda _: None)
    처리 = 0
    for 식별값, 몸통, 오류 in c.본문여럿(종류, 대상):
        처리 += 1
        진행(처리)
        if 오류 is not None:
            # 원천에 없는 것은 **확정**이다. 재시도하면 매일 수만 건을 헛되이 두드린다.
            분류 = "없음" if type(오류).__name__ == "원천에없음" else "네트워크"
            # ⚠️ **이미 철회로 표시한 것이 또 '없음'이면 실패 원장에 안 적는다.** 적으면 한
            #    자료가 본문에도 있고 `수집실패(없음)` 에도 있어, A1 이 같은 행을 두 번
            #    기대해 **고칠 수 없는 빨간불**이 된다. 이 답은 표지를 뒤집는 것이 아니라
            #    **확인해 주는 것**이라, 새로 적을 사실이 없다.
            if 분류 == "없음" and 식별값 in 되물을것:
                수치["없음"] += 1
                continue
            record_failure(conn, 종류, 식별값, 분류, str(오류))
            수치["없음" if 분류 == "없음" else "실패"] += 1
            continue
        try:
            행, 자식 = 파싱(몸통, 목록[식별값])
            저장(conn, 종류, 행, 자식)
        except Exception as e:  # noqa: BLE001 — 한 건의 실패로 배치를 버리지 않는다
            # ⚠️ **본문이 왔다는 것만으로 표지는 걷힌다.** 표지의 뜻이 "본문 API 가 없다고
            #    답했다"인데 답이 왔으므로, 우리 파서가 못 읽은 것을 원천이 안 준 것으로
            #    적어 두면 **거짓 표지**가 남아 「원천에서 확인 불가」로 조회된다.
            if 식별값 in 되물을것:
                conn.execute(
                    f"UPDATE {테이블} SET 원천철회일=NULL WHERE {키컬럼}=?", (식별값,))
            record_failure(conn, 종류, 식별값, "파싱", f"{type(e).__name__}: {e}")
            수치["실패"] += 1
            continue
        수치["본문"] += 1
    _복귀대기기록(conn, 종류, 목록, 검증된목록)
    return 수치

