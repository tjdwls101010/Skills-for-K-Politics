# ── 헌재 주문 ────────────────────────────────────────────────
#
# **원천에 결과 필드가 없다**(본문 키 13개를 직접 확인했다). "이 조문이 위헌 판단을
# 받았나"는 이 스킬이 광고하는 질문인데, 답하려면 `전문` 을 파싱하는 수밖에 없다.
#
# ⚠️ **마커가 한 종류가 아니다.** 실측 33,395건:
#      [주 문] 반각 44.9% · 【주 문】 전각 41.2% · 괄호 없는 옛 포맷 나머지
#    반각만 찾으면 **절반이 안 보이고**, 거기 혼인빙자간음죄·낙태죄 같은 가장 유명한
#    위헌 결정이 들어 있다. 공백도 일반 공백과 U+3000 이 섞인다(`【주　　　문】`).
#    그래서 **공백을 전부 지우고 괄호 유무와 무관하게** 찾는다.
_주문시작 = re.compile(r"[\[【]?주문[\]】]?")
_주문끝 = re.compile(r"[\[【]?이유[\]】]?")
# ⚠️ 끝 표지를 못 찾았다고 전문 전체를 담으면 안 된다. `주문 LIKE '%위반된다%'` 가
#    **이유 속 인용까지 걸어 합헌 결정이 위헌으로 잡힌다.** 주문 길이 95%p 가 108자다.
주문상한 = 500


def 주문추출(전문: str | None) -> str | None:
    """전문에서 주문만. **분류하지 않고 원문 그대로 돌려준다.**

    '위헌이다'라는 판단을 여기서 박아 두면 틀렸을 때 조용히 퍼진다 — 주문은
    `…부분은 위헌, 나머지는 기각` 처럼 한 결정에 여럿이 섞이는 일이 흔하다.
    """
    if not 전문:
        return None
    # ⚠️ **경계는 공백을 지운 사본에서 찾되 잘라내기는 원문에서 한다.** 공백을 지운 채로
    #    저장하면 사람이 못 읽고, 무엇보다 `주문 LIKE '%헌법에 위반된다%'` 처럼 자연스럽게
    #    띄어 쓴 질의가 **0건을 준다** — 조용히 "그런 결정이 없다"로 읽힌다.
    민 = [(ch, i) for i, ch in enumerate(전문) if not ch.isspace()]
    s = "".join(ch for ch, _ in 민)
    m = _주문시작.search(s)
    if not m:
        return None
    e = _주문끝.search(s, m.end())
    시작 = 민[m.end()][1] if m.end() < len(민) else len(전문)
    끝 = 민[e.start()][1] if e and e.start() < len(민) else len(전문)
    주문 = re.sub(r"\s+", " ", 전문[시작:끝]).strip()
    return 주문[:주문상한] or None


def 주문재추출(conn) -> int:
    """저장된 `전문` 에서 `주문` 을 다시 만든다. **네트워크를 안 탄다.**

    ⚠️ **이게 없으면 `주문추출` 을 고칠 때마다 헌재 38,672건을 다시 받아야 한다.**
    참조 파싱을 ③단계로 뗀 것과 같은 이유다(D13) — 원문이 DB 에 있으면 다시 받지 않는다.
    """
    행 = conn.execute("SELECT 헌재결정례일련번호, 전문 FROM 헌재결정례").fetchall()
    with 연결.트랜잭션(conn):
        conn.executemany(
            "UPDATE 헌재결정례 SET 주문=? WHERE 헌재결정례일련번호=?",
            [(주문추출(전문), i) for i, 전문 in 행],
        )
    return conn.execute(
        "SELECT COUNT(*) FROM 헌재결정례 WHERE 주문 IS NOT NULL").fetchone()[0]


