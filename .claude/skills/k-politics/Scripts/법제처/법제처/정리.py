# 같은 것의 다른 판본을 묶는 컬럼. **여기 있는 자료종류만 교체와 소멸을 가를 수 있다.**
#
# ⚠️ 판례·헌재결정례·행정심판례·법령해석례에는 판본이 없다 — 한 사건은 한 번 나오고
#    고쳐 나오지 않는다. 그래서 그쪽의 목록 이탈은 전부 소멸로 세어지고 삭제상한이
#    그대로 지킨다. **없는 자료종류를 여기 넣으면 서로 다른 사건이 한 묶음이 되어
#    소멸이 교체로 둔갑한다** — 상한이 조용히 꺼지는 자리다.
판본묶음 = {"법령": "법령ID", "행정규칙": "행정규칙ID"}

def 누락기록(conn: sqlite3.Connection, 종류: str, 사라진: set[str],
           이번시각: str | None = None) -> set[str]:
    """이번 목록에 없는 것을 원장에 쌓고, **연속 상한을 채운 것만** 돌려준다.

    ⚠️ **하루에 몇 번을 돌려도 한 번으로 센다.** 호출 횟수로 세면 워크플로 재시도나 사람이
    손으로 한 번 더 돌린 것만으로 "이틀 연속"이 채워져, **하루짜리 원천 누락을 흡수한다는
    설계가 통째로 우회된다.** 날짜와 간격을 **둘 다** 봐야 하는 이유는 `정리기준` 이 진다.

    ⚠️ **못 센 실행은 `최종누락일시` 도 안 옮긴다.** 옮기면 짧은 간격으로 자주 도는 수집이
    매번 "아직 간격이 안 찼다" 로 판정되어 **연속이 영영 안 차고 진짜 삭제가 멈춘다.**
    기준점은 마지막으로 **센** 시각이다.
    """
    지난 = 이번시각 or 지금()
    간 = ("date(정리후보.최종누락일시) <> date(excluded.최종누락일시) AND"
         " julianday(excluded.최종누락일시) - julianday(정리후보.최종누락일시)"
         f" >= {정리기준['누락간격시간']}/24.0")
    conn.executemany(
        "INSERT INTO 정리후보 (자료종류, 자료ID, 연속누락, 최초누락일시, 최종누락일시)"
        " VALUES (?, ?, 1, ?, ?)"
        " ON CONFLICT(자료종류, 자료ID) DO UPDATE SET"
        # ⚠️ COALESCE 가 없으면 못 읽는 시각 하나가 `연속누락 + NULL` 로 NOT NULL 을 깨서
        #    **정리 전체가 예외로 죽는다.** 못 재면 세지 않되 기준점은 새로 잡아 스스로 낫는다.
        f"   연속누락=정리후보.연속누락 + COALESCE({간}, 0),"
        f"   최종누락일시=CASE WHEN COALESCE({간}, 1)"
        "     THEN excluded.최종누락일시 ELSE 정리후보.최종누락일시 END",
        [(종류, k, 지난, 지난) for k in sorted(사라진)],
    )
    return {
        r[0] for r in conn.execute(
            "SELECT 자료ID FROM 정리후보 WHERE 자료종류=? AND 연속누락>=?",
            (종류, 정리기준["연속누락"]))
    }



def 정리막는것(conn: sqlite3.Connection, 종류: str, 목록건수: int,
             삭제수: int) -> tuple[str, str] | None:
    """정리를 **멈춰야 하는 이유**를 `(갈래, 설명)` 으로. 멈출 게 없으면 `None`.

    ⚠️ 되돌릴 수 없는 DELETE 앞의 마지막 문이라 **판정을 못 하겠으면 멈추는 쪽**이다.

    ⚠️ **갈래를 가르는 이유가 기준선에 있다.** `'이상'` 이면 이번 목록을 새 기준선으로
    삼아서는 안 된다 — 삼으면 다음 실행이 그 낮은 값과 비교해 통과하고, 가드가 삭제를
    **하루 늦추는 것 이상을 못 한다.** 반대로 `'기준선없음'` 은 목록이 이상하다는 뜻이
    아니라 잴 것이 없다는 뜻이므로, 기준선을 세워야 다음 실행이 정상으로 돈다.
    """
    기준선 = conn.execute(
        "SELECT 건수 FROM 수집상태 WHERE 자료종류=? AND 단계='목록' AND 키='전체'"
        " AND 상태='완료' AND 건수 > 0", (종류,)).fetchone()
    if 기준선 is None:
        return ("기준선없음", "직전 목록 건수가 없어 줄었는지 잴 수 없다")
    # ⚠️ **여기서 철회 수를 빼지 마라.** 철회를 확정할 때 기준선을 그때의 목록으로 함께
    #    갱신하므로(`--철회확정`) **기준선은 이미 철회가 빠진 값이다.** 또 빼면 그만큼
    #    가드가 헐거워져, 기준선 180·철회 20·이번 목록 170 이 실제로는 5.6% 추가 감소인데
    #    `160 → 170` 으로 계산돼 통과한다 — 확인되지 않은 감소가 가드를 그냥 지나간다.
    앞 = 기준선[0]
    감소율 = (앞 - 목록건수) / 앞
    if 감소율 > 정리기준["감소율상한"]:
        return ("이상", f"목록이 {앞:,} → {목록건수:,} 로 {감소율:.1%} 줄었다"
                        f" (상한 {정리기준['감소율상한']:.0%})")
    if 삭제수 > 정리기준["삭제상한"]:
        return ("이상", f"삭제 후보가 {삭제수:,}행이다 (상한 {정리기준['삭제상한']:,})")
    return None



def 계류중인정리후보(conn: sqlite3.Connection, 종류: str) -> int:
    """아직 연속 상한을 못 채워 남아 있는 수. **A1 이 이만큼을 더 기대해야 맞는다.**"""
    return conn.execute(
        "SELECT COUNT(*) FROM 정리후보 WHERE 자료종류=?", (종류,)).fetchone()[0]



def 정리한다(conn, 종류: str, 테이블: str, 키컬럼: str, 목록,
            검증된목록: bool, 로그=print) -> tuple[int, bool]:
    def 멈춘다(상태: str, 이유: str, 기준선유지: bool) -> tuple[int, bool]:
        # ⚠️ **`'건너뜀'` 과 `'기준선없음'` 을 한 상태로 묶지 마라.** A25 가 '건너뜀' 만
        #    세는데, 첫 수집(기준선 수립)까지 '건너뜀' 으로 적으면 **새 DB 의 첫 실행이
        #    무조건 빨간불**이고, 늑대를 부르는 게이트는 곧 무시된다.
        상태기록(conn, 종류, "정리", "전체", 상태, len(사라진))
        if 사라진 or 상태 == "건너뜀":
            로그(f"  ⚠️ 정리를 건너뛴다 — {이유} (후보 {len(사라진):,}행)")
        return 0, not 기준선유지

    # ⚠️ **빈 목록에도 여기까지 와야 한다.** 부르는 쪽이 `if 목록:` 으로 걸러 버리면
    #    원천이 0건을 준 날 `정리` 단계 기록이 아예 안 남고, 옛 '완료' 가 그대로 남아
    #    **A1·A25 가 전부 초록인 채 아무것도 안 받은 실행이 정상으로 끝난다.**
    if not 목록:
        사라진 = set()
        return 멈춘다("건너뜀", "목록이 비었다 — 원천이 아무것도 주지 않았다",
                    기준선유지=True)

    # 목록에 다시 나타난 후보는 **덜 받은 목록에서도** 원장에서 지운다. 왜인지는
    # `복귀지우기` 가 진다 — 존재의 증거와 부재의 증거는 대칭이 아니다.
    복귀지우기(conn, 종류, 목록, 완결=검증된목록)

    # ⚠️ IN (?,?,…) 로 하지 마라. 8만 건이면 SQLite 의 변수 상한을 넘는다.
    conn.execute("CREATE TEMP TABLE IF NOT EXISTS _살아있는(키 TEXT PRIMARY KEY)")
    conn.execute("DELETE FROM _살아있는")
    conn.executemany("INSERT OR IGNORE INTO _살아있는 VALUES (?)", [(k,) for k in 목록])
    사라진 = {
        r[0] for r in conn.execute(
            f"SELECT {키컬럼} FROM {테이블} WHERE {키컬럼} NOT IN (SELECT 키 FROM _살아있는)")
    } | {
        r[0] for r in conn.execute(
            "SELECT 자료ID FROM 수집실패 WHERE 자료종류=?"
            " AND 자료ID NOT IN (SELECT 키 FROM _살아있는)", (종류,))
    }
    # ⚠️ **철회로 이름을 준 것은 여기서 빼야 한다.** 안 빼면 매 실행 원장에 다시 올라
    #    연속을 채우고 결국 지워진다 — **남기기로 한 결정이 이틀 뒤에 조용히 뒤집힌다.**
    철회 = 철회된것(conn, 종류)
    사라진 -= 철회

    # ⚠️ **교체와 소멸은 다른 사건인데 삭제상한이 둘을 같은 숫자로 센다.** 법이 개정되면
    #    새 일련번호가 발급되고 옛 것이 목록에서 빠진다 — 코퍼스는 줄지 않고 같은 법의
    #    판본이 갈린 것이다. 실측 2026-08-28, 정리 후보 924건 중 **869건이 이 교체**였는데
    #    상한 100 에 걸려 **반드시 해야 할 갱신까지 멈췄고**, 같은 법령ID 에 '현행' 이 두 행
    #    남았다(A11 111건 · A1 도 함께 어긋난다).
    # ⚠️ **상한을 키우는 것으로는 못 가른다** — 교체 869건을 통과시키려면 상한이 900이
    #    되어야 하고 그러면 진짜 소멸 900건도 함께 통과한다. 가드가 있는 이유가 없어진다.
    # ⚠️ **묶음이 살아 있는지는 DB 가 아니라 목록에서 본다.** 정리는 본문 수집보다 먼저
    #    도므로 그 시점에 새 판본은 아직 DB 에 없다 — DB 로 물으면 모든 교체가 소멸이 된다.
    # ⚠️ 교체도 연속누락 원장은 그대로 거친다. 원천이 그날 옛 판본만 빠뜨렸을 수 있고,
    #    하루 기다리는 비용은 작다. 여기서 빼는 것은 **삭제상한의 계산**뿐이다.
    # ⚠️ **이 판정이 믿는 것은 "같은 ID 가 목록에 있다"뿐이다.** 그래서 원천이 각 ID 의
    #    옛 판본만 대량으로 잘라내는 사고는 상한을 그냥 지난다 — 교차 검토가 짚은 자리다.
    #    **그래도 잃는 것이 없다**: 그 ID 는 목록에 남아 코퍼스에서 안 사라지고, 지워지는
    #    것은 우리가 애초에 담지 않기로 한 옛 판본이다(`현행연혁코드` CHECK 가 현행·
    #    시행예정 둘뿐인 이유). 남은 행이 시행예정뿐이라 현행이 비는 경우만 실제 사건이고,
    #    그것은 **A18(현행 행이 하나도 없는 법령ID)** 이 잡는다.
    교체 = set()
    if (묶음컬럼 := 판본묶음.get(종류)) and 사라진:
        사는묶음 = {str(행[묶음컬럼]) for 행 in 목록.values() if 행.get(묶음컬럼)}
        교체 = {
            r[0] for r in conn.execute(
                f"SELECT {키컬럼}, {묶음컬럼} FROM {테이블}"
                f" WHERE {키컬럼} NOT IN (SELECT 키 FROM _살아있는)")
            if r[0] in 사라진 and str(r[1]) in 사는묶음
        }

    if not 검증된목록:
        # ⚠️ 부분 수신에서 지우면 멀쩡한 수집물을 날린다. **연속 횟수도 세지 않는다** —
        #    네트워크가 이틀 흔들린 것만으로 삭제 조건이 채워지면 이 문이 무력해진다.
        # ⚠️ **이걸 A25(게이트)로 올리지 마라.** 부분 수신은 네트워크가 흔들린 날마다
        #    나는 평범한 사건이라, 게이트로 올리면 흔한 날에 빨개지고 **늑대를 부르는
        #    게이트는 곧 무시된다.** 여기 남긴 상태는 보고값 R22 가 읽는다. 며칠째
        #    이 상태로 멈춰 있는지는 `상태시작일시` 가 진다 — `갱신일시` 는 매 실행 덮인다.
        return 멈춘다("부분수신", "목록을 다 못 받았다", 기준선유지=True)
    if (막는것 := 정리막는것(conn, 종류, len(목록), len(사라진) - len(교체))):
        갈래, 이유 = 막는것
        return 멈춘다("건너뜀" if 갈래 == "이상" else "기준선없음", 이유,
                    기준선유지=(갈래 == "이상"))

    # ⚠️ **원장 갱신·상태 기록·DELETE 가 한 트랜잭션이어야 한다.** 따로 커밋되면 삭제가
    #    실패한 실행이 "후보 2회 · 정리 완료" 를 남기고, 그 조합에서는 A25 도 초록이고
    #    A1 도 남은 본문을 `계류` 가 상쇄해 초록이다 — **실패가 양쪽 게이트에 다 가려진다.**
    지운수 = 0
    with 트랜잭션(conn):
        지울것 = 누락기록(conn, 종류, 사라진)
        상태기록(conn, 종류, "정리", "전체", "완료", len(지울것))
        if not 지울것:
            if 사라진:
                로그(f"  목록에서 빠진 {len(사라진):,}행 — 연속 "
                    f"{정리기준['연속누락']}일을 채우면 지운다")
            return 0, True
        conn.execute("CREATE TEMP TABLE IF NOT EXISTS _지울것(키 TEXT PRIMARY KEY)")
        conn.execute("DELETE FROM _지울것")
        conn.executemany("INSERT OR IGNORE INTO _지울것 VALUES (?)", [(k,) for k in 지울것])
        지운수 = conn.execute(
            f"DELETE FROM {테이블} WHERE {키컬럼} IN (SELECT 키 FROM _지울것)").rowcount
        # ⚠️ **파생 행은 FK 가 없어 부모를 지워도 안 따라 지워진다.** 남으면 `의율조문` 은
        #    A13(고아 의율조문)을 빨갛게 만들고, `인용판례`·`파싱실패` 는 게이트도 없어
        #    **조용히 없는 판단을 가리키는 행**이 된다. 전량 재파싱이 언젠가 고치지만
        #    단독 실행이나 중단된 실행에서는 그때까지 고아가 남는다.
        for 파생 in ("의율조문", "인용판례", "파싱실패"):
            지운수 += conn.execute(
                f"DELETE FROM {파생} WHERE 자료종류=?"
                " AND 자료ID IN (SELECT 키 FROM _지울것)", (종류,)).rowcount
        # ⚠️ **`수집실패` 도 같이 치워야 한다.** A1 은 `본문 + 없음 = 목록` 을 보는데,
        #    '없음'으로 확정된 자료가 나중에 목록에서도 빠지면 본문만 정리되고 실패 행이
        #    남아 합이 목록보다 커진다. **다시 수집해도 안 풀린다** — 이미 '없음'이라
        #    재시도 대상이 아니고 정리는 본문 테이블만 봤기 때문이다. 실측으로 나왔다
        #    (행정규칙 목록이 24,121 → 24,119 로 줄면서 A1 이 빨개졌다).
        #    **고칠 수 없는 빨간불은 표 전체를 무시하게 만든다.**
        지운수 += conn.execute(
            "DELETE FROM 수집실패 WHERE 자료종류=? AND 자료ID IN (SELECT 키 FROM _지울것)",
            (종류,)).rowcount
        # ⚠️ **살아 있는 판단이 지워진 판단을 가리키던 링크도 끊는다.** 위의 파생 삭제는
        #    `자료ID`(인용한 쪽)만 보므로, 남의 인용행에 박힌 `피인용자료ID` 는 그대로
        #    남아 **없는 자료를 가리킨다.** `NULL` 이 곧 "우리 적재 범위 밖" 이라는 뜻이니
        #    (인용판례 DDL) 지운 순간 그게 사실이 된다. 술어는 `참조파서` 가 이을 때 쓴
        #    것과 **같아야 한다** — 판례와 헌재결정례는 일련번호가 겹칠 수 있다.
        if 종류 in ("판례", "헌재결정례"):
            conn.execute(
                "UPDATE 인용판례 SET 피인용자료ID=NULL"
                " WHERE 피인용자료ID IN (SELECT 키 FROM _지울것) AND "
                + ("피인용법원 = '헌법재판소'" if 종류 == "헌재결정례"
                   else "(피인용법원 IS NULL OR 피인용법원 <> '헌법재판소')"))
        conn.executemany("DELETE FROM 정리후보 WHERE 자료종류=? AND 자료ID=?",
                        [(종류, k) for k in 지울것])
    로그(f"  목록에서 빠진 {지운수:,}행 정리")
    return 지운수, True



def _복귀대기기록(conn, 종류: str, 목록, 검증된목록: bool) -> None:
    """복귀했지만 본문이 아직 안 온 철회 자료의 수를 남긴다.

    ⚠️ **A1 이 이 수를 알아야 한다.** 복귀한 철회 자료는 본문에도 있고 **마지막 목록에도**
    있으므로 그 행에는 A1 의 `철회` 보정이 필요 없다. 안 빼면 `본문=목록` 인데 우변에
    철회만 더해져 **본문 API 가 계속 「없다」고 답하는 동안 내내 빨갛다** — 우리가 고칠 수
    없는 빨간불이고, 그런 불은 표 전체를 무시하게 만든다.

    ⚠️ **본문 조회가 끝난 뒤에 부른다.** 앞에서 적으면 이번 실행에 실제로 걷힌 표지가
    반영되지 않아, 이번에는 반대 방향으로 하나 어긋난다.
    """
    if 검증된목록:
        상태기록(conn, 종류, "정리", "복귀대기", "진행",
               len(철회된것(conn, 종류) & set(목록)))

