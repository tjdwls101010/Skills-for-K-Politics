    # `00:01` 에 재시도하면 날짜만으로는 이틀 연속이 된다). 재시도는 길어야 한두 시간
    # 안에 일어나므로 6 이면 넉넉하고, 이튿날 아침 수집을 하루 더 미루지 않을 만큼 작다.
