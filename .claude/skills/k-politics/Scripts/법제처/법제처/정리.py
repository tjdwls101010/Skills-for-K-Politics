    # 것을 막는다 — 날짜 조건은 "하루 두 번 도는 수집"을(원천이 하루 빠뜨리면 08시에도
    # 20시에도 똑같이 없다; 열두 시간 떨어졌다는 것은 독립 관측이 아니라 **같은 하루를
