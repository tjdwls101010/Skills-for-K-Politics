"""원천 텍스트를 저장 형태로. **문자열이 아닌 것도 받는다.**

⚠️ 원천이 같은 자리에 `str` 을 줬다 `list` 를 줬다 한다 — 부칙·개정문·제개정이유·별표는 **중첩 리스트**(행 배열의 배열)이고 조문내용은 문자열이다. `str(list)` 를 그대로 넣으면 `"[['부칙 <제10465호…'], …]"` 가 검색에 걸린다.
"""

from __future__ import annotations

import re
from datetime import date
from html import unescape


# ── 저장 형태 ────────────────────────────────────────────────
#
# 스키마 주석이 "저장 시 개행으로 치환하고 원본 태그는 남기지 않는다"고 정해 둔 규칙을
# 여기서 강제한다. 규칙과 그 집행이 갈리면 어느 쪽이 맞는지 아무도 모른다.

# ⚠️ **꺾쇠를 통째로 지우면 법령 본문이 망가진다.**
#    `<개정 2023.3.14>` · `<신설 2023.3.14>` · `<단서 생략>` 은 **HTML 이 아니라 법령 본문의
#    일부**다. 표본 20개 법령에서 꺾쇠 1,986개 중 진짜 HTML 은 `</img>` 37개뿐이고
#    나머지는 전부 개정 표기였다. `<[^>]+>` 로 지우면 어느 조문이 언제 개정됐는지가
#    통째로 사라진다 — 에러 없이.
#
#    그래서 **태그 이름을 명시한 것만** 지운다. `감사.py` 의 HTML 잔존 검사도 같은 목록을
#    써야 한다. 안 그러면 개정 표기 하나하나가 전부 빨간불이 된다.
_HTML태그 = "br|img|p|div|span|b|i|u|em|strong|font|table|thead|tbody|tr|td|th"
_개행태그 = re.compile(r"<\s*/?\s*(?:br|p|tr)\s*/?\s*>", re.I)
_지울태그 = re.compile(rf"<\s*/?\s*(?:{_HTML태그})\b[^>]*>", re.I)

# ㆍ(U+318D) ‧(U+2027) ․(U+2024) ∙(U+2219) ・(U+30FB) → ·(U+00B7)
#
# ⚠️ **저장 시점에 하나로 모은다.** 원천이 같은 법을 두 표기로 준다
#    (`진실ㆍ화해를 위한 과거사정리 기본법` / `진실·화해를 위한 과거사정리 기본법`).
#    원문 그대로 두면 `LIKE '%수집·이용%'` 이 `수집ㆍ이용` 으로 저장된 조문을 못 찾고,
#    **0건이 "그런 조문이 없다"로 읽힌다.** 반대로 정규화해 두면 이 DB 의 법령명을
#    그대로 API 에 넣었을 때 0건이 나올 수 있는데, 그건 눈에 보이는 실패다.
#    **조용한 오답보다 보이는 실패가 낫다.**
_중점표 = {ord(c): "·" for c in "ㆍ‧․∙・"}


def 씻는다(값) -> str:
    if 값 is None:
        return ""
    if isinstance(값, (list, tuple)):
        return "\n".join(x for x in (씻는다(v) for v in 값) if x)
    if not isinstance(값, str):
        값 = str(값)
    값 = _개행태그.sub("\n", 값)
    값 = _지울태그.sub("", 값)
    값 = unescape(값)  # &#8228; → ․ (헌재 참조조문에 실재)
    return 값.translate(_중점표).strip()


_점날짜 = re.compile(r"^(\d{4})\s*\.\s*(\d{1,2})\s*\.\s*(\d{1,2})\s*\.?$")


def 날짜(값) -> str | None:
    """`'2026.04.16'` · `'20260416'` → `'2026-04-16'`. 이미 ISO 면 그대로.

    ⚠️ **목록과 본문의 날짜 형식이 다르다.** 목록은 점을 찍고 본문은 안 찍는다 —
    판례 `선고일자` · 헌재 `종국일자` · 행정심판례 `의결일자` 가 전부 그렇다.
    통일 지점을 여기 하나로 모은다. 두 형식이 섞이면 범위 조건이 **점 찍힌 행을 통째로
    빠뜨린다** — 에러 없이.

    ⚠️ **`YYYY-MM-DD` 로 저장하는 이유는 미관이 아니다.** `YYYYMMDD` 를 주면 SQLite 의
    `date()`·`julianday()`·`strftime()` 이 **전부 NULL 을 돌려준다.** 에러가 아니라
    NULL 이라, `strftime('%Y', 선고일자)` 로 연도별 집계를 하면 전 행이 조용히 사라진다.
    더 나쁜 것은 `date('0')` 이 NULL 이 아니라 `'-4713-11-24'`(율리우스일 0)이라는 것이다.

    ⚠️ **이 함수는 멱등이어야 한다.** `이행()` 이 저장된 값에 이 함수를 다시 먹여
    마이그레이션하므로, 두 번째 통과가 값을 바꾸면 매일 조금씩 달라진다.

    ⚠️ **API 로 나갈 때는 `날짜원천()` 으로 되돌려라.** 원천은 계속 `YYYYMMDD` 만 받는다.
    """
    s = 씻는다(값)
    if not s or s == "0":
        # ⚠️ 원천이 날짜 자리에 `'0'` 을 넣는다 — 헌재 `종국일자` 5,080건이 그렇다.
        #    그대로 저장하면 범위 조건에서 조용히 빠진다.
        return None
    if m := _점날짜.match(s):
        년, 월, 일 = int(m.group(1)), int(m.group(2)), int(m.group(3))
    else:
        숫자 = "".join(ch for ch in s if ch.isdigit())
        if len(숫자) != 8:
            return None
        년, 월, 일 = int(숫자[:4]), int(숫자[4:6]), int(숫자[6:])
    # ⚠️ **단기(檀紀)로 적힌 옛 판례가 있다** — `4284…` 는 서기 1951년이다(실측 45건).
    #    그대로 두면 정렬·범위 조건에서 **미래로 취급**되고, "2020년 이후" 집계에도 섞인다.
    if 4200 <= 년 <= 4400:
        년 -= 2333
    try:
        date(년, 월, 일)  # 달력에 없는 날짜(2월 30일 등)를 걸러낸다
    except ValueError:
        return None
    return f"{년:04d}-{월:02d}-{일:02d}"


def 날짜원천(값) -> str | None:
    """저장 형태 → 원천 형태. `'2026-04-16'` → `'20260416'`.

    ⚠️ **경계에 역변환이 필요한 이유.** 원천 API 는 `regDt`·`efYd`·`prncYd` 를 여전히
    `YYYYMMDD` 로만 받는다. DB 에서 꺼낸 날짜를 그대로 파라미터에 넣으면 **에러가 아니라
    0건**이 오고, 0건은 "그런 자료가 없다"로 읽힌다.
    """
    return None if (s := 날짜(값)) is None else s.replace("-", "")


# ⚠️ **날짜 컬럼의 정본 목록이다.** `이행()` 이 값을 옮기고 `감사.py` 가 게이트를 걸고
#    테스트가 대조한다. 세 곳에 따로 적으면 새 날짜 컬럼이 생긴 날 **감사만 조용히
#    빠지고**, 그러면 형식이 어긋난 값이 다시 쌓이기 시작한다 — 헌재 `'0'` 5,080건이
#    그렇게 남았다.
#
# ⚠️ `수집일시`·`갱신일시` 류는 여기 없다. 그쪽은 `'2026-08-13 23:46:11'` 이고
#    SQLite 의 날짜 함수가 그 형식을 **이미 그대로 먹는다** — 고칠 것이 없다.
날짜컬럼: tuple[tuple[str, str], ...] = (
    ("법령", "공포일자"), ("법령", "시행일자"),
    ("조문", "조문시행일자"), ("부칙", "부칙공포일자"),
    ("판례", "선고일자"), ("헌재결정례", "종국일자"),
    ("행정심판례", "의결일자"), ("법령해석례", "해석일자"), ("법령해석례", "등록일시"),
    ("행정규칙", "발령일자"), ("행정규칙", "시행일자"),
    ("인용판례", "피인용선고일"),
)

# ⚠️ **`GLOB '____-__-__'` 로 쓰지 마라.** SQLite 의 GLOB 에는 `_` 와일드카드가 없다
#    (`?` 가 그 자리다). 그렇게 쓰면 게이트가 **전 행 거짓**이 되어 멀쩡한 날짜를 전부
#    위반으로 세고, 반대로 오탈자 하나에 표 전체를 못 믿게 된다.
#
#    `date(값) IS 값` 이 형식과 달력을 한 술어로 잡는다 — `'2026-02-30'` 은
#    `'2026-03-02'` 로 돌아오고 `'20200101'` 은 NULL, `'0'` 은 `'-4713-11-24'`(율리우스일
#    0)로 돌아온다. **`'0'` 이 NULL 이 아니라는 것이 요점이다.**
날짜위반술어 = "{c} IS NOT NULL AND date({c}) IS NOT {c}"


# ── 법원명 ───────────────────────────────────────────────────
#
# ⚠️ **원천이 같은 법원을 두 이름으로 준다.** 실측 87,723건에 `법원명` 224종이고
#    축약형이 94종 8,174건이다 — `서울고등법원` 4,797 옆에 `서울고법` 2,040 이 따로 산다.
#    `WHERE 법원명='서울고등법원'` 이 30%를 조용히 놓치고, **그 30%가 "없다"로 읽힌다.**
#    **클로드가 기본으로 손이 가는 이름이 옳은 컬럼이 되게 하는 것**이 요점이라, 정규화한
#    값을 `법원명` 에 넣고 원천 표기는 `법원명원문` 에 남긴다.
#
# ⚠️ `판례.py` 가 아니라 여기 있는 이유는 `날짜()` 와 같다 — **적재기와 `이행()` 이 같은
#    규칙을 봐야 한다.** 두 곳에 적으면 새로 들어오는 행과 이미 있는 행이 다르게 정규화되고,
#    감사는 초록인데 이름이 갈린다.

# ⚠️ **`가정→가정법원` 으로 쓰면 안 된다.** 이미 온전한 `서울가정법원` 이
#    `서울가정법원법원` 이 되고(실측 105행), `대구지법 가정지원` 이
#    `대구지방법원 가정법원지원` 이 된다. 진짜 축약은 `가법` 이다(실측 227건).
_축약 = {"고법": "고등법원", "지법": "지방법원", "행법": "행정법원",
        "가법": "가정법원", "회법": "회생법원"}
# 축약형은 법원 단위의 **꼬리**로만 나온다. 뒤에 공백·괄호·끝, 또는 붙여 쓴 지원이 온다.
_축약패턴 = re.compile("(" + "|".join(_축약) + r")(?=\s|\(|$|[^\s]*지원)")
# ⚠️ **축약만 펴면 종류가 오히려 는다.** `부산지법동부지원` → `부산지방법원동부지원` 은
#    실재하는 `부산지방법원 동부지원`(43건)과 여전히 다른 이름이다. 실측 14종 16건.
_붙은지원 = re.compile(r"(?<=법원)(?=[^\s]+지원)")


def 법원명정규화(이름: str | None) -> str | None:
    """`'서울고법'` → `'서울고등법원'`. 이미 온전하면 그대로. **멱등이다.**

    ⚠️ **합치는 것이 펴는 것보다 위험하다.** `서울지법`(2004년에 사라진 옛 단일 법원)을
    `서울중앙지방법원` 으로 옮기면 서로 다른 법원의 판결이 한 이름 아래 섞인다.
    여기서는 **표기만 편다** — 어느 법원이 어느 법원의 후신인가는 판단하지 않는다.

    ⚠️ **못 맞춘 이름은 그대로 둔다.** 실측에 `중앙해양안전심판원`·`부산고등법원 창원재판부`
    처럼 규칙 밖의 것이 있다. 억지로 맞추는 것보다 감사 보고값(R12)으로 드러내는 쪽이 낫다.

    실측 결과: 224종 → 127종 · 8,411행이 바뀐다 · 축약 잔존 0.
    """
    if not 이름 or not 이름.strip():
        return 이름
    편것 = _축약패턴.sub(lambda m: _축약[m.group(1)], 이름)
    return _붙은지원.sub(" ", 편것)


def 선고정규화(값: str | None) -> str | None:
    값 = re.sub(r"[,\.\s]+$", "", 씻는다(값))
    return None if 값 in ("", "null") else 값


