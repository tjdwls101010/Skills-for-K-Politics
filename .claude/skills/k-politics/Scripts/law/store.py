"""한 건을 **하나의 트랜잭션으로** 넣는다.

⚠️ **본문과 그 자식 행이 따로 커밋되면 반쪽 상태가 남는다.** 조문 없는 법령이 생기는데, 재개 조건이 "그 키의 행이 있나"라 **다음 실행이 그걸 완성된 것으로 보고 건너뛴다.**

⚠️ **자식은 명시적으로 지우고 다시 넣는다.** `REPLACE` 의 CASCADE 에만 기대면 순서가 미묘해지고, 무엇보다 **부모 컬럼이 하나도 안 바뀐 재저장에서도 옛 자식이 남을 수 있다.** 개정으로 조문이 통째로 갈릴 수 있어서 부분 갱신은 없는 조문을 검색에 남긴다.

⚠️ **`위임` 은 자식 목록에 없고, `REPLACE` 의 CASCADE 로 함께 사라진다 — 그것이 맞다.** 판본이 갈리면 옛 판본의 위임 관계는 더 이상 사실이 아니다. 자식 목록에 넣으면 위임을 받은 직후의 조문 재저장이 그걸 도로 지운다. **대신 `위임수집판본` 도 반드시 NULL 로 돌아가야 한다** — 행은 지워졌는데 표지만 남으면 그 법의 위임이 영영 빈 채로 "받았다"고 적힌다.

 원장 표 둘이 왜 이 모양인지도 여기 적는다 — 스키마 주석은 조회자가 읽는 자리라 게이트 설계는 거기 있으면 안 된다.

- **본문 수신은 `수집상태` 에서 추적하지 않는다.** 본문의 진행은 "본문 테이블에 그 행이 있나"가 그대로 답이라 원장이 따로 있으면 두 벌이 갈린다.
- **`수집상태` 는 자료종류·단계마다 한 행이다.** 옛 설계의 `키` 컬럼은 기준선을 '전체'·'최근수신' 두 행에 갈라 담으려고 있었는데, 기준선이 컬럼이 되면서 그 갈래가 필요 없어졌다.
"""

from __future__ import annotations

import sqlite3
from law.conn import now_kst, 트랜잭션


# 자료종류 → (본문 테이블, 기본키 컬럼, [(자식 테이블, 부모키 컬럼)] 삽입 순서)
#
# ⚠️ **감사 A1b 가 이 dict 의 길이를 모집단으로 쓴다.** 자료종류를 늘리고 여기 안 적으면
#    그 종류의 목록 단계 미완료가 게이트에 안 잡힌다.
본문테이블: dict[str, tuple[str, str, tuple[tuple[str, str], ...]]] = {
    "법령": ("법령", "법령ID", (("조문", "법령ID"),)),
    "판례": ("판례", "판례ID", ()),
    "헌재결정례": ("헌재결정례", "헌재결정례ID", ()),
    "법령해석례": ("법령해석례", "법령해석례ID", ()),
}


# 자료ID 로 이 자료를 가리키는 파생 표. 본문을 지울 때 함께 지운다.
파생표 = ("의율조문", "인용판례")


_컬럼캐시: dict[tuple[int, str], tuple[str, ...]] = {}



def 컬럼들(conn: sqlite3.Connection, 테이블: str) -> tuple[str, ...]:
    키 = (id(conn), 테이블)
    if 키 not in _컬럼캐시:
        _컬럼캐시[키] = tuple(
            r[1] for r in conn.execute(f"PRAGMA table_info({테이블})").fetchall()
        )
        if not _컬럼캐시[키]:
            raise LookupError(f"그런 테이블이 없다: {테이블}")
    return _컬럼캐시[키]



def _삽입(conn: sqlite3.Connection, 테이블: str, 값: dict, 방식: str = "REPLACE") -> None:
    쓸것 = {k: v for k, v in 값.items() if k in 컬럼들(conn, 테이블)}
    if not 쓸것:
        raise ValueError(f"{테이블}: 쓸 컬럼이 하나도 없다 — 받은 키 {list(값)}")
    자리 = ", ".join("?" * len(쓸것))
    conn.execute(
        f"INSERT OR {방식} INTO {테이블} ({', '.join(쓸것)}) VALUES ({자리})",
        tuple(쓸것.values()),
    )



def 저장(
    conn: sqlite3.Connection,
    종류: str,
    값: dict,
    자식: dict[str, list[dict]] | None = None,
) -> None:
    테이블, 키컬럼, 자식정의 = 본문테이블[종류]
    값 = {**값, "수집일시": 값.get("수집일시") or now_kst()}
    부모키 = 값.get(키컬럼)
    if not 부모키:
        raise ValueError(f"{종류}: {키컬럼} 이 비어 있다")

    with 트랜잭션(conn):
        for 자식테이블, 부모컬럼 in reversed(자식정의):
            conn.execute(f"DELETE FROM {자식테이블} WHERE {부모컬럼}=?", (부모키,))
        _삽입(conn, 테이블, 값)
        for 자식테이블, 부모컬럼 in 자식정의:
            for 행 in (자식 or {}).get(자식테이블, []):
                _삽입(conn, 자식테이블, {부모컬럼: 부모키, **행})
        conn.execute(
            "DELETE FROM 수집실패 WHERE 자료종류=? AND 자료ID=?", (종류, 부모키)
        )



def 본문지우기(conn: sqlite3.Connection, 종류: str, 자료IDs) -> int:
    """본문 행과 그것을 가리키는 파생 행을 함께 지운다. **부르는 쪽이 트랜잭션을 연다.**

    ⚠️ **파생 행은 FK 가 없어 부모를 지워도 안 따라 지워진다.** 남으면 `의율조문` 은 고아
    게이트를 빨갛게 만들고, `인용판례` 는 게이트도 없어 **조용히 없는 판단을 가리키는 행**이
    된다. 전량 재파싱이 언젠가 고치지만 단독 실행에서는 그때까지 고아가 남는다.

    ⚠️ **남의 인용행에 박힌 `피인용자료ID` 도 끊는다.** 위의 파생 삭제는 `자료ID`(인용한
    쪽)만 보므로 그대로 두면 **없는 자료를 가리킨다.** `NULL` 이 곧 "우리 적재 범위 밖"
    이라는 뜻이니 지운 순간 그게 사실이 된다. 술어는 `피인용종류` 다 — 판례와 헌재결정례는
    일련번호가 겹칠 수 있어 ID 만으로 가르면 남의 자료를 끊는다.
    """
    키들 = sorted(set(자료IDs))
    if not 키들:
        return 0
    테이블, 키컬럼, _ = 본문테이블[종류]
    conn.execute("CREATE TEMP TABLE IF NOT EXISTS _지울것(키 TEXT PRIMARY KEY)")
    conn.execute("DELETE FROM _지울것")
    conn.executemany("INSERT OR IGNORE INTO _지울것 VALUES (?)", [(k,) for k in 키들])
    n = conn.execute(
        f"DELETE FROM {테이블} WHERE {키컬럼} IN (SELECT 키 FROM _지울것)").rowcount
    for 파생 in 파생표:
        n += conn.execute(
            f"DELETE FROM {파생} WHERE 자료종류=?"
            " AND 자료ID IN (SELECT 키 FROM _지울것)", (종류,)).rowcount
    if 종류 in ("판례", "헌재결정례"):
        conn.execute(
            "UPDATE 인용판례 SET 피인용자료ID=NULL"
            " WHERE 피인용자료ID IN (SELECT 키 FROM _지울것) AND 피인용종류=?", (종류,))
    return n



# ── 실패 원장 ────────────────────────────────────────────────
#
# ⚠️ **비어 있는 것이 정상 상태가 아니다.** '재시도'는 다음 실행이 치우는 큐지만, '없음'·
#    '본문없음'·'철회'는 **목록에 있는데 본문이 없다**는 영속 기록이라 그 자료가 목록에
#    남아 있는 한 함께 남는다. 적재 등식이 본문 키와 이 셋의 **합집합**을 세는 이유다.

재시도상한 = 5


# 본문이 없다는 영속 기록. 목록에는 있으나 우리 본문 표에 행이 없는 자료다.
본문없는실패 = ("없음", "본문없음", "철회")



def record_failure(
    conn: sqlite3.Connection, 종류: str, 자료ID: str, 실패종류: str, 메시지: str = "",
    시도횟수: int | None = None,
) -> None:
    """실패 원장에 한 행을 올린다. `시도횟수` 를 주면 그 값으로 덮는다(연속 누락 수).

    ⚠️ **실패종류가 바뀌면 시도횟수를 1 로 되돌린다.** '재시도' 3회를 쌓은 자료가 '목록누락'
    으로 바뀌었을 때 그 3을 물려받으면, 연속 누락 상한이 **첫 누락에서 이미 채워져 있다** —
    하루를 유예한다는 설계가 통째로 우회되고 멀쩡한 자료가 하루 만에 지워진다.
    """
    때 = now_kst()
    conn.execute(
        "INSERT INTO 수집실패 (자료종류, 자료ID, 실패종류, 메시지, 시도횟수, 최초일시, 최종일시)"
        " VALUES (:종류, :자료ID, :실패종류, :메시지, COALESCE(:시도횟수, 1), :때, :때)"
        " ON CONFLICT(자료종류, 자료ID) DO UPDATE SET"
        "   실패종류=excluded.실패종류, 메시지=excluded.메시지, 최종일시=excluded.최종일시,"
        "   시도횟수=CASE"
        "     WHEN :시도횟수 IS NOT NULL THEN :시도횟수"
        "     WHEN 수집실패.실패종류 <> excluded.실패종류 THEN 1"
        "     ELSE 수집실패.시도횟수 + 1 END",
        {"종류": 종류, "자료ID": 자료ID, "실패종류": 실패종류,
         "메시지": 메시지[:500], "시도횟수": 시도횟수, "때": 때},
    )



def clear_failure(conn: sqlite3.Connection, 종류: str, 자료ID: str) -> None:
    conn.execute("DELETE FROM 수집실패 WHERE 자료종류=? AND 자료ID=?", (종류, 자료ID))



def 실패인것(conn: sqlite3.Connection, 종류: str, *실패종류: str) -> set[str]:
    """그 실패종류로 원장에 올라 있는 자료ID."""
    자리 = ", ".join("?" * len(실패종류))
    return {
        r[0]
        for r in conn.execute(
            f"SELECT 자료ID FROM 수집실패 WHERE 자료종류=? AND 실패종류 IN ({자리})",
            (종류, *실패종류),
        )
    }



def 잘못붙은없음(conn: sqlite3.Connection, 종류: str) -> set[str]:
    """**원천이 '없다'고 말한 적 없는데 '없음' 표지가 붙은 자료ID.**

    ⚠️ **앞을 막는 것만으로는 이미 잃은 것이 안 돌아온다.** `원천._보낸다` 가 본문 4xx 를
    `원천에없음` 으로 확정하던 동안 붙은 표지는 그 코드를 고쳐도 그대로 남고, '없음'은
    재시도 대상에서 **영구히** 빠지는 표지라 다음 실행도 그 자료를 안 묻는다.

    실측(2026-08-28) — '없음' 507건 중 **506건이 HTTP 4xx 에서 왔고 봉투에서 온 것은
    1건뿐**이었다. 그 506건은 전부 2026-08-14 한 실행에 찍혔고, 무작위 다섯을 지금 원천에
    물으니 **5/5 가 정상**이다. 원천에 멀쩡히 있는 자료였다.

    ⚠️ **`메시지` 로 가른다.** 표지가 어디서 왔는지를 우리 원장이 이미 적어 두었고
    (`…: HTTP 404` 대 `…: 일치하는 판례가 없습니다…`), 그것 말고는 둘을 가를 근거가 DB
    안에 없다. 원천의 답에서 온 표지는 **건드리지 않는다** — 진짜 부재까지 매일 다시
    물으면 수만 건을 헛되이 두드리게 되고, 그게 이 표지가 있는 이유다.

    ⚠️ **여기는 고를 뿐 지우지 않는다.** 지우는 것은 `수집루프` 가 **실제로 물을 대상을
    확정한 뒤**다 — 적재 등식이 본문과 '없음'의 합집합을 보므로, 이번에 안 물을 것의 표지를
    걷으면 좌변만 줄어 **이번 실행이 고칠 수 없는 빨간불**이 된다. `--표본` 이 정확히
    그 경우다: 표지는 506건을 다 걷었는데 실제로 묻는 것은 앞의 N 건뿐이다.
    """
    return {
        r[0]
        for r in conn.execute(
            "SELECT 자료ID FROM 수집실패 WHERE 자료종류=? AND 실패종류='없음'"
            " AND 메시지 LIKE '%: HTTP 4%'", (종류,)
        )
    }



def 없음인것(conn: sqlite3.Connection, 종류: str) -> set[str]:
    """재시도 대상에서 빼야 하는 것. **'본문없음'·'철회'도 여기 든다.**

    셋 다 "원천이 본문을 안 준다"의 기록이라 다음 실행이 다시 물어도 같은 답이 온다.
    다만 **'철회'는 목록에 다시 나타나면 부르는 쪽이 되물음 대상에 앞세운다** — 목록이
    답을 바꿨다는 증거이기 때문이다. 그 밖에 다시 묻게 하는 것은 `--전량` 뿐이다.
    """
    return 실패인것(conn, 종류, *본문없는실패)



def 지금() -> str:
    """연속 누락이 재는 시각. **호출 횟수가 아니라 경과 시간이다.**"""
    return now_kst()



def 철회기록(conn: sqlite3.Connection, 종류: str, 자료IDs) -> int:
    """원천이 거둔 것으로 확정한다 — **본문과 파생 행을 지우고** 원장에 '철회'를 남긴다.

    부르는 쪽이 **본문 API 로 확인한 뒤에만** 부른다. 목록에서 빠진 것만으로는 값을 안 쓴다
    — 목록 결함과 실제 철회를 가르는 증거가 본문 API 의 「없다」뿐이다.

    ⚠️ **행을 남기고 표지만 다는 옛 정책을 뒤집었다.** 옛 뷰가 철회 표지를 붙여 조회자에게
    보여 주었는데 새 뷰에는 그 표지가 없다 — 행을 남기면 **철회된 판단이 정상 판단처럼
    보인다.** 원장의 '철회' 행이 "목록에는 있는데 본문이 없다"를 대신 말한다.

    ⚠️ **'철회'는 '없음'과 같은 자리다.** 한 자료가 양쪽에 남으면 적재 등식이 같은 행을
    두 번 기대해 **고칠 수 없는 빨간불**이 되므로, 실패종류는 늘 한 행에 하나다.

    복귀는 목록이 알린다 — 본문을 다시 받아 **성공했을 때만** `저장()` 이 이 행을 지운다.
    재수신에 실패했거나 표본 밖이면 '철회'로 남아 있고 그것이 복귀 대기 상태다.
    """
    키들 = sorted(set(자료IDs))
    if not 키들:
        return 0
    with 트랜잭션(conn):
        본문지우기(conn, 종류, 키들)
        for k in 키들:
            record_failure(conn, 종류, k, "철회", "본문 API 가 부재로 답했다")
    return len(키들)



def 철회된것(conn: sqlite3.Connection, 종류: str) -> set[str]:
    return 실패인것(conn, 종류, "철회")



def 목록누락복귀(conn: sqlite3.Connection, 종류: str, 목록, 완결: bool) -> int:
    """목록에 다시 나타난 '목록누락' 자료의 연속 누락을 끊는다.

    ⚠️ **덜 받은 목록에서도 이건 한다.** "목록에 있다"는 존재의 증거라 완결과 무관하게
    유효하지만, "목록에 없다"는 부재의 증거가 아니라 완결일 때만 유효하다. 이 비대칭을
    놓치면 `정상(누락) → 부분(존재) → 정상(누락)` 이 연속 2회로 세져 **복귀가 증명된
    자료가 지워진다.** 세는 것은 **연속** 누락이다.

    ⚠️ **원장에서 지우느냐 0 으로 되돌리느냐는 기준선이 정한다.** 적재 등식은 마지막
    **완결** 목록을 기준선으로 쓴다. 완결 목록에서 복귀한 것은 그 목록에 들어 있으니
    누락에서 빼야 맞고, 덜 받은 목록에서 복귀한 것은 기준선이 그것 없이 세어진 옛 값
    그대로라 **누락이 계속 그만큼을 메워야 한다** — 지워 버리면 복귀할 때마다 등식이
    빨개져서 "흔한 부분 수신은 초록"이라는 분업이 깨진다.
    """
    돌아온것 = [
        (종류, k) for k in 실패인것(conn, 종류, "목록누락") if k in 목록
    ]
    conn.executemany(
        "DELETE FROM 수집실패 WHERE 자료종류=? AND 자료ID=?" if 완결
        else "UPDATE 수집실패 SET 시도횟수=0 WHERE 자료종류=? AND 자료ID=?",
        돌아온것)
    return len(돌아온것)



# ── 수집상태 ─────────────────────────────────────────────────

def 상태기록(
    conn: sqlite3.Connection, 종류: str, 단계: str, 상태: str,
    건수: int | None = None, 상세: str | None = None, 기준선: int | None = None,
) -> None:
    """자료종류·단계의 **지금 상태**를 덮어쓴다. 실행 이력이 아니다.

    `기준선` 은 `None` 이면 **건드리지 않는다** — 부분 수신·급감 판정이 옛 기준선을
    덮으면 다음 실행이 그 낮은 값과 비교해 통과하고, 크기 가드가 삭제를 하루 늦추는
    것 이상을 못 한다.
    """
    conn.execute(
        "INSERT INTO 수집상태 (자료종류, 단계, 상태, 건수, 기준선, 상세, 갱신일시, 상태시작일시)"
        " VALUES (?, ?, ?, ?, ?, ?, ?, ?)"
        " ON CONFLICT(자료종류, 단계) DO UPDATE SET"
        "   상태=excluded.상태, 건수=excluded.건수, 상세=excluded.상세,"
        "   기준선=COALESCE(excluded.기준선, 수집상태.기준선),"
        "   갱신일시=excluded.갱신일시,"
        # 상태가 그대로면 시작을 유지한다. 안 그러면 매 실행 덮여서 지속 기간이 사라진다.
        "   상태시작일시=CASE WHEN 수집상태.상태=excluded.상태"
        "     THEN COALESCE(수집상태.상태시작일시, 수집상태.갱신일시)"
        "     ELSE excluded.상태시작일시 END",
        (종류, 단계, 상태, 건수, 기준선, 상세, (때 := now_kst()), 때),
    )



def 상태읽기(conn: sqlite3.Connection, 종류: str, 단계: str) -> str | None:
    r = conn.execute(
        "SELECT 상태 FROM 수집상태 WHERE 자료종류=? AND 단계=?", (종류, 단계)
    ).fetchone()
    return r[0] if r else None



def 기준선읽기(conn: sqlite3.Connection, 종류: str) -> int | None:
    """마지막으로 완결 수신하고 급감이 아니었던 목록 건수. 적재 등식의 우변이다."""
    r = conn.execute(
        "SELECT 기준선 FROM 수집상태 WHERE 자료종류=? AND 단계='목록'", (종류,)
    ).fetchone()
    return r[0] if r else None



def 기준선기록(conn, 종류: str, 목록건수: int, 갱신: bool, 검증된목록: bool) -> None:
    """목록 단계의 상태와 건수를 남기고, **기준선은 자격이 있을 때만** 갈아 끼운다.

    ⚠️ **정리보다 뒤에서 불러야 한다.** 앞에 두면 이번 목록 건수가 새 기준선이 되고, 정리가
    그 기준선에 맞춰 지운 뒤 적재 등식이 맞아떨어진다 — **게이트가 자기가 지운 것을 자기가
    갱신한 기준으로 검사하게 된다.**
    """
    자격 = 갱신 and 검증된목록
    상태기록(conn, 종류, "목록", "완료" if 자격 else ("부분" if not 검증된목록 else "이상"),
           건수=목록건수, 기준선=목록건수 if 자격 else None)



def 수집끝냈다(conn: sqlite3.Connection) -> None:
    """한 번의 수집 실행이 끝났다고 적는다. `신선도.적재기준시각` 이 이 행을 읽는다.

    ⚠️ **행을 하나도 안 썼어도 적는다.** 이 값의 뜻은 "무엇이 새로 들어왔나"가 아니라
    **"우리가 마지막으로 원천을 확인한 때"**다. 밀린 것이 없어 조용히 끝난 실행과
    수집기가 며칠째 안 도는 상태는 전혀 다른 일인데, 행이 있을 때만 적으면 둘이
    똑같아 보인다. 행 단위 해상도는 각 테이블의 `수집일시` 가 갖고 있다.
    """
    상태기록(conn, "전체", "수집", "완료")
