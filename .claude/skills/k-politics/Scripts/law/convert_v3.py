def 법령과조문(옛, 새, 오늘: str) -> dict[str, int]:
    """법령ID 하나당 한 행으로 접고, 그 판본의 조문을 편장절과 함께 옮긴다.

    ⚠️ **조문은 선택 판본의 것만 옮긴다.** 다른 판본의 조문을 함께 옮기면 같은 법령ID 에
    같은 조가 여러 벌 생겨 `(법령ID, 조, 가지)` UNIQUE 가 거부한다 — 거부되는 편이 낫다.
    소리 없이 들어갔다면 조문 조회가 판본 수만큼 곱한 답을 준다.
    """
    현행, 예정 = [], []
    for r in 옛.execute(
        "SELECT 법령일련번호, 법령ID, 시행일자, 현행연혁코드 FROM 법령"
        " WHERE 원천철회일 IS NULL"
    ):
        (현행 if r[3] == "현행" else 예정).append(
            {"법령일련번호": r[0], "법령ID": r[1], "시행일자": r[2]})
    고른 = 판본선택(현행, 예정, 오늘)
    _로그(f"  법령ID {len(고른):,}개 (옛 판본 행 {len(현행) + len(예정):,})")

    # 위임을 받아 둔 판본. **다른 판본의 완료 행은 쓰지 않는다** — 그 판본의 위임은
    # 지금 담는 판본의 위임이 아니다.
    받은위임 = {
        r[0] for r in 옛.execute(
            "SELECT 키 FROM 수집상태 WHERE 자료종류='법령' AND 단계='위임' AND 상태='완료'")
    }

    수 = {"법령": 0, "조문": 0, "위임": 0}
    for 법령ID, 골라낸 in 고른.items():
        mst = str(골라낸["선택"]["법령일련번호"])
        옛행 = 옛.execute(
            "SELECT 법령명, 법령약칭, 법종구분, 소관부처, 공포일자, 공포번호, 시행일자,"
            " 제개정구분, 개정문, 제개정이유, 수집일시 FROM 법령 WHERE 법령일련번호=?",
            (mst,)).fetchone()
        새.execute(
            "INSERT INTO 법령 (법령ID, 법령일련번호, 법령명, 법령약칭, 법종구분, 소관부처,"
            " 공포일자, 공포번호, 시행일자, 제개정구분, 개정문, 제개정이유, 수집일시,"
            " 시행예정일련번호, 시행예정일, 위임수집판본)"
            " VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (법령ID, mst, *옛행,
             골라낸["시행예정일련번호"], 골라낸["시행예정일"],
             mst if mst in 받은위임 else None))
        수["법령"] += 1

        # ⚠️ **접기 규칙을 여기 다시 적지 않는다.** `조문행들` 을 그대로 쓰면 변환이 만든
        #    `편장절` 과 다음 수집이 만드는 `편장절` 이 구조적으로 같다.
        조문들 = 조문행들(
            {"조문여부": 여부, "조": 조문번호, "가지": 가지, "제목": 제목, "전문": 전문,
             "시행일자": 정규화.날짜(시행일자), "변경여부": 변경여부}
            for 여부, 조문번호, 가지, 제목, 전문, 시행일자, 변경여부 in 옛.execute(
                "SELECT 조문여부, 조문번호, 조문가지번호, 조문제목, 전문, 조문시행일자,"
                " 조문변경여부 FROM 조문 WHERE 법령일련번호=? ORDER BY 순서", (mst,)))
        새.executemany(
            "INSERT INTO 조문 (법령ID, 순서, 조, 가지, 편장절, 제목, 전문, 시행일자,"
            " 변경여부) VALUES (:법령ID,:순서,:조,:가지,:편장절,:제목,:전문,:시행일자,:변경여부)",
            [{**r, "법령ID": 법령ID} for r in 조문들])
        수["조문"] += len(조문들)

        # ⚠️ **`순서` 를 옛 값 그대로 옮기면 안 된다.** 버린 잎의 자리가 비어 PK 가
        #    성기게 되고, 재수집이 0부터 다시 매기면 같은 법에 옛 순서와 새 순서가 섞인다.
        위임순서 = 0
        for 조, 가지, 자리, 구분, 대상제목, 대상법령ID, 대상조, 대상가지, 근거 in 옛.execute(
            "SELECT 조문번호, 조문가지번호, 위임한자리, 위임구분, 대상제목, 대상법령ID,"
            " 대상조문번호, 대상조문가지번호, 근거문구 FROM 위임"
            " WHERE 법령일련번호=? AND 위임구분 IN ('시행령','시행규칙') ORDER BY 순서",
            (mst,)
        ):
            새.execute(
                "INSERT INTO 위임 (법령ID, 순서, 조, 가지, 위임한자리, 위임구분, 대상제목,"
                " 대상법령ID, 대상조, 대상가지, 근거문구) VALUES (?,?,?,?,?,?,?,?,?,?,?)",
                (법령ID, 위임순서, 조, 가지, 자리, 구분, 대상제목, 대상법령ID,
                 대상조, 대상가지 or 0, 근거))
            위임순서 += 1
        수["위임"] += 위임순서
    return 수


def 판례(옛, 새) -> int:
    """`판결유형` 을 `형식`·`전원합의체` 로 가르고 원문 컬럼 넷을 버린다.

    ⚠️ **`선고`·`선고원문` 은 형식에서 전부 유도되므로 버린다.** `법원명원문` 도 실측
    차이가 전부 축약형이라 되돌릴 정보가 없다. 반대로 **`판결유형` 은 여기서 안 쪼개면
    전원합의체 표지 559건이 사라진다** — 판례내용 본문에 그 말이 없다.
    """
    n = 0
    for (판례ID, 사건번호, 사건명, 법원명, 선고일자, 판결유형, 사건종류,
         판시사항, 판결요지, 참조조문, 참조판례, 판례내용, 수집일시) in 옛.execute(
        "SELECT 판례일련번호, 사건번호, 사건명, 법원명, 선고일자, 판결유형, 사건종류명,"
        " 판시사항, 판결요지, 참조조문원문, 참조판례원문, 판례내용, 수집일시"
        " FROM 판례 WHERE 원천철회일 IS NULL"
    ):
        형식, 전합 = 정규화.형식과전원합의체(판결유형)
        새.execute(
            "INSERT INTO 판례 (판례ID, 사건번호, 사건명, 법원명, 선고일자, 형식,"
            " 전원합의체, 사건종류, 판시사항, 판결요지, 참조조문, 참조판례, 판례내용,"
            " 수집일시) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
            (판례ID, 사건번호, 사건명, 법원명, 선고일자, 형식, 전합, 사건종류,
             판시사항, 판결요지, 참조조문, 참조판례, 판례내용, 수집일시))
        n += 1
    return n


def 헌재결정례(옛, 새) -> tuple[int, list[str]]:
    """전문·판시사항·결정요지가 모두 빈 껍데기는 담지 않고 '본문없음' 으로 돌려준다.

    ⚠️ **담으면 사건번호만 있는 행이 `조문판단` 에 요지 NULL 로 섞인다** — "판단이 있는데
    요지를 못 읽었다"처럼 보이는데 실제로는 미공개·계류 결정이다.

    ⚠️ **`사건종류명` 은 버린다.** 실측 35,583건이 사건번호 접미와 같은 값이고 나머지는
    두 자리 연도 때문에 갈린 것이다 — 사건번호가 이미 답한다.
    """
    n, 껍데기 = 0, []
    for (ID, 사건번호, 사건명, 종국일자, 심판대상조문, 참조조문, 참조판례,
         판시사항, 결정요지, 전문, 주문, 수집일시) in 옛.execute(
        "SELECT 헌재결정례일련번호, 사건번호, 사건명, 종국일자, 심판대상조문, 참조조문,"
        " 참조판례, 판시사항, 결정요지, 전문, 주문, 수집일시"
        " FROM 헌재결정례 WHERE 원천철회일 IS NULL"
    ):
        if not any((v or "").strip() for v in (전문, 판시사항, 결정요지)):
            껍데기.append(ID)
            continue
        새.execute(
            "INSERT INTO 헌재결정례 (헌재결정례ID, 사건번호, 사건명, 종국일자, 주문,"
            " 심판대상조문, 참조조문, 참조판례, 판시사항, 결정요지, 전문, 수집일시)"
            " VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
            (ID, 사건번호, 사건명, 종국일자, 주문, 심판대상조문, 참조조문, 참조판례,
             판시사항, 결정요지, 전문, 수집일시))
        n += 1
    return n, 껍데기


def 법령해석례(옛, 새) -> int:
    """⚠️ **원천 필드 이름은 `등록일시` 인데 실물은 8자리 날짜다**(실측 8,842건 전부).
    컬럼 이름을 `등록일자` 로 바꾼 것은 없는 정밀도를 이름으로 주장하지 않으려는 것이다."""
    행들 = 옛.execute(
        "SELECT 법령해석례일련번호, 안건번호, 안건명, 질의기관명, 해석일자, 등록일시,"
        " 질의요지, 회답, 이유, 수집일시 FROM 법령해석례 WHERE 원천철회일 IS NULL"
    ).fetchall()
    새.executemany(
        "INSERT INTO 법령해석례 (법령해석례ID, 안건번호, 안건명, 질의기관, 해석일자,"
        " 등록일자, 질의요지, 회답, 이유, 수집일시) VALUES (?,?,?,?,?,?,?,?,?,?)", 행들)
    return len(행들)


def 원장(옛, 새, 껍데기: list[str], 담긴법령: dict[str, str]) -> dict[str, int]:
    """실패 원장과 수집상태를 새로 쓴다. **옛 행을 그대로 복사하지 않는다.**

    ⚠️ **법령의 옛 '없음' 은 버린다.** 키가 MST 뿐이라 그 판본의 법령ID 를 알 길이 없고,
    지어내면 남의 법에 붙는다. 기준선에도 안 넣으므로 첫 일일 실행이 목록으로 다시 잡는다.

    ⚠️ **기준선은 옛 원장에서 낸다.** 변환 결과로 세면 변환이 빠뜨린 것이 기준선에도
    빠져, 적재 등식이 그 손실을 못 잡는다.
    """
    수 = {"실패": 0, "목록누락": 0}
    때 = 연결.now_kst()

    for 종류, 자료ID, 실패종류, 메시지, 시도, 최종 in 옛.execute(
        "SELECT 자료종류, 자료ID, 실패종류, 메시지, 시도횟수, 최종시도일시 FROM 수집실패"
    ):
        if 종류 not in _옮길종류 or 실패종류 not in _실패종류:
            continue
        새.execute(
            "INSERT INTO 수집실패 (자료종류, 자료ID, 실패종류, 메시지, 시도횟수,"
            " 최초일시, 최종일시) VALUES (?,?,?,?,?,?,?)",
            (종류, 자료ID, _실패종류[실패종류], 메시지, 시도, 최종 or 때, 최종 or 때))
        수["실패"] += 1

    for ID in 껍데기:
        새.execute(
            "INSERT INTO 수집실패 (자료종류, 자료ID, 실패종류, 메시지, 시도횟수,"
            " 최초일시, 최종일시)"
            " VALUES ('헌재결정례', ?, '본문없음', '전문·판시사항·결정요지가 모두 비었다',"
            " 1, ?, ?)", (ID, 때, 때))
        수["실패"] += 1

    # 계류 중인 정리 후보 → '목록누락'. 본문이 살아남은 자료만 옮긴다 — 본문이 없으면
    # 셀 것도 지킬 것도 없고, 적재 등식의 좌변에서 빼야 할 것도 없다.
    for 종류, 자료ID, 연속 in 옛.execute(
        "SELECT 자료종류, 자료ID, 연속누락 FROM 정리후보"
    ):
        if 종류 == "법령":
            자료ID = 담긴법령.get(자료ID)
        if 종류 not in ("법령", *_옮길종류) or not 자료ID:
            continue
        표 = {"법령": "법령", "판례": "판례", "헌재결정례": "헌재결정례",
             "법령해석례": "법령해석례"}[종류]
        키 = {"법령": "법령ID", "판례": "판례ID", "헌재결정례": "헌재결정례ID",
             "법령해석례": "법령해석례ID"}[종류]
        if not 새.execute(f"SELECT 1 FROM {표} WHERE {키}=?", (자료ID,)).fetchone():
            continue
        새.execute(
            "INSERT OR REPLACE INTO 수집실패 (자료종류, 자료ID, 실패종류, 메시지,"
            " 시도횟수, 최초일시, 최종일시)"
            " VALUES (?, ?, '목록누락', '완결 목록에 없다', ?, ?, ?)",
            (종류, 자료ID, 연속, 때, 때))
        수["목록누락"] += 1

    기준선 = {
        종류: 옛.execute(
            "SELECT 건수 FROM 수집상태 WHERE 자료종류=? AND 단계='목록' AND 키='전체'"
            " AND 상태='완료'", (종류,)).fetchone()[0]
        for 종류 in _옮길종류
    }
    # 법령의 기준선은 판본 수가 아니라 목록이 주는 **법 수**다.
    기준선["법령"] = 옛.execute(
        "SELECT COUNT(DISTINCT 법령ID) FROM 법령 WHERE 원천철회일 IS NULL").fetchone()[0]
    for 종류, 값 in 기준선.items():
        for 단계 in ("목록", "정리"):
            새.execute(
                "INSERT INTO 수집상태 (자료종류, 단계, 상태, 건수, 기준선, 갱신일시,"
                " 상태시작일시) VALUES (?, ?, '완료', ?, ?, ?, ?)",
                (종류, 단계, 값 if 단계 == "목록" else 0,
                 값 if 단계 == "목록" else None, 때, 때))
    # `신선도.적재기준시각` 은 **옛 DB 가 마지막으로 원천을 확인한 때**다. 변환 시각을
    # 적으면 변환이 곧 수집인 것처럼 보이고, 며칠 묵은 자료가 오늘 것으로 읽힌다.
    마지막 = 옛.execute("SELECT 값 FROM 메타 WHERE 키='마지막수집일시'").fetchone()
    새.execute(
        "INSERT INTO 수집상태 (자료종류, 단계, 상태, 갱신일시, 상태시작일시)"
        " VALUES ('전체', '수집', '완료', ?, ?)",
        (마지막[0] if 마지막 else 때, 마지막[0] if 마지막 else 때))
    수["기준선"] = 기준선
    return 수


def 변환(옛경로: Path, 새경로: Path, 오늘: str):
    """돌려주는 것은 `(보고, 새 연결)`. 연결을 닫지 않는 이유는 부르는 쪽이 이어서
    재파싱과 VACUUM 을 돌리기 때문이다.

    ⚠️ **읽기 연결을 따로 연다.** `ATTACH` 로 한 연결에서 양쪽을 보면 표 이름이 겹쳐
    (`법령`·`조문`·`판례` …) 접두사를 하나만 빠뜨려도 **새 DB 의 빈 표를 읽는다** —
    에러 없이 0행이 오고, 0행은 "옮길 것이 없었다"로 읽힌다.

    ⚠️ **`옛` 은 읽기 전용으로 연다.** 변환이 원본을 건드리면 되돌릴 것이 없어진다.
    """
    if 새경로.exists():
        raise SystemExit(f"🔴 {새경로} 가 이미 있다 — 지우고 다시 돌려라")
    옛 = sqlite3.connect(f"file:{옛경로}?mode=ro", uri=True)
    옛.execute("PRAGMA query_only=ON")
    새 = 연결.connect(새경로)
    이행.init_schema(새)

    보고: dict = {}
    with 연결.트랜잭션(새):
        _로그("── 법령 · 조문 · 위임 ──")
        보고 |= 법령과조문(옛, 새, 오늘)
        _로그(f"  조문 {보고['조문']:,} · 위임 {보고['위임']:,}")

        _로그("── 판례 ──")
        보고["판례"] = 판례(옛, 새)
        _로그(f"  {보고['판례']:,}")

        _로그("── 헌재결정례 ──")
        보고["헌재결정례"], 껍데기 = 헌재결정례(옛, 새)
        _로그(f"  {보고['헌재결정례']:,} (껍데기 {len(껍데기):,} 은 '본문없음')")

        _로그("── 법령해석례 ──")
        보고["법령해석례"] = 법령해석례(옛, 새)
        _로그(f"  {보고['법령해석례']:,}")

        _로그("── 원장 ──")
        담긴법령 = dict(새.execute("SELECT 법령일련번호, 법령ID FROM 법령"))
        보고["원장"] = 원장(옛, 새, 껍데기, 담긴법령)
        _로그(f"  {보고['원장']}")

    옛.close()
    return 보고, 새


def _main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="옛 LAW.db 를 새 스키마로 옮긴다. **일회성이다 — 컷오버 뒤 이 파일을"
                    " 지운다.** 파생 표는 옮기지 않고 변환 뒤 재파싱이 다시 만든다.")
    ap.add_argument("옛", type=Path)
    ap.add_argument("새", type=Path)
    ap.add_argument("--재파싱생략", action="store_true",
                    help="파생 표를 안 만든다 (변환만 따로 재볼 때)")
    a = ap.parse_args(argv)

    보고, 새 = 변환(a.옛, a.새, 연결.now_kst()[:10])

    if not a.재파싱생략:
        from law import refparser as 참조파서
        _로그("── 재파싱 ──")
        수치, 실패 = 참조파서.재파싱(새, 로그=_로그)
        _로그(f"  {수치} · 실패 표본 {len(실패)}")

    _로그("── VACUUM ──")
    이행._공간회수(새, _로그)
    새.close()
    _로그(f"\n🟢 {a.새}\n  {보고}")
    return 0


if __name__ == "__main__":
    raise SystemExit(_main())
