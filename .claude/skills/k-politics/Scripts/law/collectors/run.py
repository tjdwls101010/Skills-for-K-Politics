def _철회확정(conn, c, 종류: str, 예상: int) -> int:
    """목록에서 빠진 것을 **본문 API 로 하나씩 물어** 원천에도 없는 것만 남긴다.

    **표시의 뜻이 여기서 정해진다.** "목록에 없다"는 부재의 **정황**이라 하루 뒤에
    되돌아올 수 있지만, "본문 API 가 없다고 답했다"는 확인된 사실이다. 목록만 보고
    남기면 원천이 하루 흔들린 것을 **영구 사실로 굳힌다** — 그게 정리와 이 명령을
    가르는 유일한 것이고, 그래서 느려도 전건을 묻는다.

    ⚠️ **확정은 본문·파생 행을 지운다.** 행을 남기고 표지만 달면 새 뷰에 그 표지가 없어
    **철회된 판단이 정상 판단처럼 보인다.** 남는 것은 원장의 '철회' 한 행이다.

    ⚠️ **`예상` 이 안 맞으면 아무것도 안 한다.** 원천이 크게 망가진 날 이 명령을 돌리면
    수만 행이 "원천에 없음"으로 굳고, 그건 지우는 것만큼이나 되돌리기 어렵다 — 사람이
    본 수와 지금 세는 수가 같은지가 **그날의 원천이 그날의 원천인지**를 확인하는 값싼 문이다.
    """
    테이블, 키컬럼, _ = 저장모듈.본문테이블[종류]

    행들, 완결 = c.목록전량(종류)
    if not 완결:
        print("🔴 목록을 다 못 받았다 — 이 목록으로는 '원천에 없다'를 물을 수 없다.",
              file=sys.stderr)
        return 2
    # ⚠️ **법령의 손잡이는 둘이다.** 목록 대조는 `법령ID` 로 하고 본문 확인만 그 법의 MST
    #    로 한다. 한 손잡이로 뭉뚱그리면 **`법령ID` 를 MST 로 물어 부재 응답을 받고 멀쩡한
    #    법을 지운다** — 두 값이 같은 자리에 오는 일이 실제로 있다.
    if 종류 == "법령":
        예정행들, 예정완결 = c.목록전량(
            종류, target="eflaw", nw=2, 행키=("법령일련번호", "시행일자"))
        if not 예정완결:
            print("🔴 시행예정 목록을 다 못 받았다 — 예정만 있는 법이 누락으로 보인다.",
                  file=sys.stderr)
            return 2
        고른 = 법령.판본선택(행들, 예정행들, 연결.now_kst()[:10])
        키 = set(고른)
        본문손잡이 = {k: str(v["선택"]["법령일련번호"]) for k, v in 고른.items()}
    else:
        키 = {r[원천.봉투[종류].목록식별자] for r in 행들}
        본문손잡이 = {}
    사라진 = sorted({r[0] for r in conn.execute(f"SELECT {키컬럼} FROM {테이블}")} - 키)
    print(f"목록 {len(키):,} · 본문에 있고 목록에 없으며 아직 표시 안 한 것 {len(사라진):,}")
    if len(사라진) != 예상:
        print(f"🔴 --예상 {예상:,} 과 다르다 ({len(사라진):,}). 아무것도 안 했다.",
              file=sys.stderr)
        return 1

    없는것, 있는것 = [], []
    for i, k in enumerate(사라진, 1):
        try:
            (있는것 if c.본문하나(종류, 본문손잡이.get(k, k)) else 없는것).append(k)
        except 원천.원천에없음:
            없는것.append(k)
        if i % 100 == 0:
            print(f"  {i:,}/{len(사라진):,} 확인")
    # ⚠️ **본문이 아직 있는 것은 철회가 아니다.** 목록에서만 빠진 것이라 원천의 목록이
    #    흔들렸을 수 있다 — 여기 섞어 넣으면 이 표의 뜻이 "목록에 없다"로 되돌아간다.
    if 있는것:
        print(f"⚠️ {len(있는것):,}건은 본문이 아직 있다 — 철회로 남기지 않는다."
              f" 표본 {있는것[:3]}")
    # ⚠️ **표시와 기준선을 한 트랜잭션에 함께 남긴다.** 기준선을 안 옮기면 다음 실행이
    #    옛 목록 건수와 비교해 **같은 감소를 다시 사고로 세고**, 사람이 전건을 확인한
    #    판단이 반영되지 않은 채 게이트가 계속 빨갛다 — 판단을 내려도 상태가 안 닫힌다.
    with 연결.트랜잭션(conn):
        n = 저장모듈.본문지우기(conn, 종류, 없는것)
        conn.executemany("DELETE FROM 수집실패 WHERE 자료종류=? AND 자료ID=?",
                        [(종류, k) for k in 없는것])
        저장모듈.기준선기록(conn, 종류, len(키), 갱신=True, 검증된목록=True)
    print(f"🟢 원천에도 없음을 확정해 {len(없는것):,}건을 지웠다({n:,}행)"
          f" · 본문 남아 있음 {len(있는것):,}건")
    # ⚠️ **여기서 감사를 돌리지 않는다.** 돌리면 방금 쓴 **연결이 아니라 경로**를 다시
    #    열게 되어, 검사가 넘긴 메모리 DB 대신 실물 DB 를 연다 — 함수가 받은 `conn` 과
    #    판정하는 대상이 갈리는 것이라, 그 자체로 틀렸다. 감사는 부르는 쪽이 한다.
    return 0


def _감사하고_남긴다(경로, 곁기록=None, 표본=None) -> int:
    """감사를 돌리고 **판정을 메타에 한 줄로 남긴다.**

    ⚠️ **세션 시작 훅은 감사를 스스로 못 돌린다** — 게이트 하나가 30만 행을 훑으므로
    ms 단위 규율을 깬다. 그런데 나이만 보면 **게이트가 빨간 실행이 고친 DB 도 '최신'**
    이다: 실측(2026-08-27) 실행이 적재 등식 위반으로 실패했는데 적재 기준 시각은 그 실패
    실행 시각으로 이미 갱신돼 있었다. 종료코드는 이 프로세스와 함께 사라지므로,
    남기지 않으면 세션 안에서 그 사실을 알 방법이 없다.

    ⚠️ **감사가 스스로 적게 하지 않는다.** 백업이 사본을 감사할 때 그 사본에 쓰게 되고,
    그러면 "이 사본이 우리가 검증한 그 파일" 이라는 이야기가 깨진다.

    락 밖이라 두 실행이 겹치면 나중 것이 이긴다 — 그게 더 최근의 판정이므로 맞다.
    """
    conn = 연결.connect(경로)
    try:
        # ⚠️ **감사는 한 번만 돈다.** 화면·곁기록·`메타` 셋이 같은 한 번의 결과를 써야
        #    한다 — 각자 부르면 게이트 하나가 30만 행을 세 번 훑고, 그 사이 DB 가 바뀌면
        #    요약에 적힌 값과 판정이 갈린다.
        게, 보, 실패 = 감사.감사한다(conn)
        코드 = 1 if 실패 else 0
        # ⚠️ **표본 실행의 빨간불은 사고가 아니다.** 목록은 전체를 받고 본문만 앞의 N 건으로
        #    자르므로 적재 등식이 **일부러** 안 맞는다. 그 사실을 판정 옆에 안 적으면 다음
        #    사람이 실물 사고와 구별할 수단이 없다.
        if 표본:
            print(f"\n⚠️ `--표본 {표본}` 실행이다 — 목록은 전체를 받고 본문만 잘랐으므로"
                  " 적재 등식은 일부러 안 맞는다. 이 판정으로 실물을 판단하지 마라.",
                  file=sys.stderr)
        if 곁기록 is not None:
            곁기록["감사실행"] = True
            곁기록["표본"] = 표본
            곁기록["게이트"] = [
                {"번호": 번호, "이름": 이름, "값": v, "ok": ok,
                 "해석": 감사._해석.get(번호) if not ok else None}
                for 번호, 이름, v, ok in 게]
            곁기록["보고"] = [{"번호": 번호, "이름": 이름, "값": v} for 번호, 이름, v in 보]
        # ⚠️ **상세는 게이트 번호가 아니라 이름으로 쓴다.** `.schema` 만 읽는 조회자는
        #    'A1=3' 을 풀 수단이 없다 — 그 자리에 번호를 적으면 `신선도.감사상세` 가
        #    "위반이 있다"까지만 말하고 무엇이 어긋났는지는 말하지 못한다.
        위반 = [(이름, v) for 번호, 이름, v, ok in 게 if not ok]
        저장모듈.상태기록(
            conn, "전체", "감사", "완료", len(위반),
            " · ".join(f"{이름}={v}" for 이름, v in 위반) or None)
        conn.commit()
    finally:
        conn.close()
    return 코드


def _결과쓰기(경로, 곁기록) -> None:
    """곁기록을 원자적으로 남긴다.

    ⚠️ **여기서 죽어 수집 판정을 뒤집지 않는다.** 이 파일은 요약을 예쁘게 그리려고
    남기는 것이지 수집의 일부가 아니다 — 못 쓴 날은 요약이 로그 꼬리로 물러나면 된다.
    """
    if not 경로:
        return
    try:
        임시 = Path(f"{경로}.tmp")
        임시.write_text(json.dumps(곁기록, ensure_ascii=False, indent=2, default=str))
        임시.replace(경로)
    except Exception as e:                                    # noqa: BLE001
        print(f"⚠️ 결과 곁기록을 못 남겼다: {e}", file=sys.stderr)


