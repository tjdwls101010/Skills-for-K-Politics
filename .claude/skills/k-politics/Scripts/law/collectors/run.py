def _main(argv: list[str] | None = None) -> int:
    """인자를 읽고 **곁기록을 반드시 남기는 자리.** 일은 `_돈다` 가 한다.

    ⚠️ **`try` 를 `connect()` 보다 안쪽에 두지 마라.** 유령 DB 거부와 연결 실패가
    바깥에 남아, 경로를 오타 낸 날 곁기록 없이 죽고 요약이 아무 말도 못 한다.

    ⚠️ **약속은 "모든 종료"가 아니라 "인자를 읽은 뒤 파이썬이 통제하는 종료"다.**
    SIGKILL·러너 유실·잡 타임아웃에서는 `finally` 가 안 돈다 — 그 경우는 요약 쪽의
    "곁기록이 없다" 갈래가 받는다.
    """
    ap = argparse.ArgumentParser(description="네 자료종류를 이어받아 수집하고 참조를 파싱한다. 어디서 중단돼도 다음 실행이 이어받는다.",
                                 formatter_class=argparse.RawDescriptionHelpFormatter, epilog=운영지면)
    ap.add_argument("--결과", metavar="경로",
                    help="판정·게이트·보고값을 JSON 한 장으로 남긴다 (요약이 읽는다)")
    ap.add_argument("--db")
    ap.add_argument("--rate", type=float, default=원천.기본유량)
    ap.add_argument("--자료", nargs="*", choices=[n for n, _ in 순서],
                    help="일부만 (기본: 전부)")
    ap.add_argument("--표본", type=int, help="자료당 이 건수만 (개발용)")
    ap.add_argument("--전량", action="store_true", help="이미 있는 것도 다시 받는다")
    ap.add_argument("--재파싱", action="store_true", help="③단계만 (네트워크 안 탄다)")
    ap.add_argument("--감사만", action="store_true", help="무엇이 밀렸나 (네트워크 안 탄다)")
    ap.add_argument("--철회확정", metavar="자료종류", choices=sorted(저장모듈.본문테이블),
                    help="목록에서 빠진 것을 본문 API 로 하나씩 확인해, 원천에도 없는 것의"
                         " 본문·파생 행을 지우고 원장에 '철회'로 남긴다. --예상 이 함께 있어야 한다")
    ap.add_argument("--예상", type=int, metavar="N",
                    help="--철회확정 이 확인할 건수. 실제와 다르면 아무것도 안 한다")
    a = ap.parse_args(argv)
    # ⚠️ **이름이 `결과` 면 안 된다** — 국회 쪽에서 `if 결과 := db.migrate(conn)` 과
    #    겹쳐 표를 담는 순간 `KeyError` 로 죽었다(실측). 두 수집기를 같은 이름으로 읽는다.
    곁기록: dict = {"코퍼스": "law", "시각": None, "종류": "예외", "판정": 1,
                 "감사실행": False, "표본": None, "단계": [], "유량": {},
                 "게이트": [], "보고": [], "파싱실패": []}
    잰다 = time.monotonic()
    try:
        # ⚠️ **시계를 `try` 밖에서 읽지 마라.** 여기서 죽으면 곁기록이 통째로 안 남고,
        #    그런 날일수록 요약이 필요하다. 못 읽으면 `시각` 만 비운다.
        곁기록["시각"] = 연결.now_kst()
        곁기록["판정"] = 코드 = _돈다(a, 곁기록)
        return 코드
    finally:
        곁기록["소요초"] = round(time.monotonic() - 잰다, 1)
        _결과쓰기(a.결과, 곁기록)


def _돈다(a, 곁기록: dict) -> int:
    conn = 연결.connect(a.db)

    # ⚠️ **감사는 스키마를 건드리지 않는다.** 예전엔 여기 오기 전에 `init_schema`·
    #    `migrate` 가 돌아서, "무엇이 밀렸나"만 보려는 호출이 **락 밖에서 DB 를 고쳤다.**
    if a.감사만:
        코드 = _감사하고_남긴다(연결.db_path(a.db), 곁기록, a.표본)
        곁기록["종류"] = "게이트" if 코드 else "정상"
        return 코드

    if a.철회확정:
        # ⚠️ **의도한 거부를 "예외" 로 남기지 마라.** 기본값이 `예외` 라 그대로 두면
        #    요약이 "뜻밖의 예외로 죽었다"고 말한다 — 인자가 어긋나 아무것도 안 한 것과
        #    정말로 터진 것은 사람이 할 일이 다르다.
        곁기록["종류"] = "거부"
        if a.예상 is None:
            print("🔴 --철회확정 에는 --예상 N 이 있어야 한다.", file=sys.stderr)
            return 1
        with 연결.락(연결.db_path(a.db)) as lk:
            if not lk.잡음:
                곁기록["종류"] = "락"
                return 0
            이행모듈.init_schema(conn)
            with 원천.Client(rate=a.rate, 로그=print) as c:
                if rc := _철회확정(conn, c, a.철회확정, a.예상):
                    return rc
        코드 = _감사하고_남긴다(연결.db_path(a.db), 곁기록)
        곁기록["종류"] = "게이트" if 코드 else "정상"
        return 코드

    with 연결.락(연결.db_path(a.db)) as lk:
        if not lk.잡음:
            # ⚠️ **3 을 낸다 — 국회와 같다.** 0 이면 물러난 실행과 끝까지 간 실행이 같은
            #    색이라 겹침이 매일 나도 워크플로는 매일 초록이다. `law-collect.yml` 의
            #    `판정 전파` 가 3 을 「건너뜀」(경고 주석, 실패 아님)으로 읽는다.
            #    요약의 문구는 `종류` 가 소유한다.
            곁기록["종류"] = "락"
            return 3
        # ⚠️ **스키마 변경은 반드시 락 안에서 한다.** 밖에 두면 두 실행이 동시에
        #    `DROP COLUMN`·테이블 재구축에 들어갈 수 있고, 그건 되돌릴 방법이 없다.
        # ⚠️ 순서가 정해져 있다 — `init_schema`(없는 표·뷰) → `migrate`(주석).
        #    뒤집으면 `migrate` 가 구조불일치로 물러나고 **이 DB 의 주석(=문서)이 안에서
        #    낡은 채로 남는다.**
        이행모듈.init_schema(conn)
        for t in 이행모듈.migrate(conn)["구조불일치"]:
            print(f"⚠️ 스키마 주석을 못 갈아 끼웠다 (구조가 다르다): {t}", file=sys.stderr)
        시작 = time.monotonic()
        try:
            if not a.재파싱:
                with 원천.Client(rate=a.rate, 로그=print) as c:
                    for 이름, 수집함수 in 순서:
                        if a.자료 and 이름 not in a.자료:
                            continue
                        print(f"── {이름} ──")
                        수치 = 수집함수(conn, c, 표본=a.표본, 전량=a.전량)
                        곁기록["단계"].append({"이름": 이름, "수치": dict(수치)})
                        print("  " + " · ".join(f"{k} {v:,}" for k, v in 수치.items()))
                곁기록["유량"] = {"요청": c.요청수, "백오프": c.backoff_횟수}
                print(f"\n요청 {c.요청수:,} · 백오프 {c.backoff_횟수}")
                # ⚠️ **네트워크를 탄 실행만 이걸 적는다.** `신선도.적재기준시각` 의 뜻이
                #    "우리가 마지막으로 원천을 확인한 때"라, 아래 `--재파싱`(DB 안의
                #    원문만 다시 읽는다)이 갱신하면 **수집기가 며칠째 멈춰 있어도
                #    "방금 확인함"으로 보인다.** 그러면 이 값을 남긴 이유가 사라진다.
                저장모듈.수집끝냈다(conn)

            print("\n── 파싱 ──")
            # ⚠️ **파싱 실패는 DB 가 아니라 여기로 온다.** 표로 담으면 조회자가 매 세션
            #    읽는 `.schema` 에 수집기 내부 사정이 한 표로 서는데, 그 표를 읽던 코드는
            #    감사 보고값 둘뿐이었다. 이 실행의 산물은 이 실행의 결과 파일이 그 자리다.
            수치, 파싱실패 = 참조파서.재파싱(conn)
            곁기록["단계"].append({"이름": "파싱", "수치": dict(수치)})
            곁기록["파싱실패"] = 파싱실패
            print("  " + " · ".join(f"{k} {v:,}" for k, v in 수치.items()))
            # 주문도 저장된 전문에서 나오므로 여기 함께 둔다 — 추출 규칙을 고쳤을 때
            # 헌재 전량을 다시 받지 않아도 되게 하는 것이 이 단계의 뜻이다.
            print(f"  헌재 주문 {결정례.주문재추출(conn):,}")
        except 원천.인증실패 as e:
            # ⚠️ 계속 돌면 20만 건을 헛되이 두드리고 빈손 수집이 초록불로 끝난다.
            print(f"\n🔴 인증 실패 — 즉시 중단한다: {e}", file=sys.stderr)
            # ⚠️ **1 이지만 게이트 위반이 아니다.** 감사는 아예 안 돌았다 — 종료코드만
            #    보고 문구를 정하면 요약이 "사람이 봐야 할 게이트"라고 잘못 말한다.
            곁기록["종류"] = "인증"
            return 1
        except KeyboardInterrupt:
            print("\n⚠️ 중단됐다. 다음 실행이 이어받는다.", file=sys.stderr)
            곁기록["종류"] = "중단"
            return 2
        except 원천.API오류 as e:
            # ⚠️ **이걸 그냥 죽게 두면 파이썬이 1 로 나가고, 워크플로가 그걸
            #    `🔴 게이트 위반 — 사람이 봐야 한다` 로 요약한다.** 실제로는 원천이
            #    흔들린 것이라 사람이 할 일이 없다 — 다음 실행이 이어받는다. 둘을 섞으면
            #    진짜 게이트 위반이 왔을 때 사람이 그 빨간불을 무시하게 된다.
            #    (인증실패는 위에서 먼저 잡힌다 — 그건 다음 실행도 똑같이 실패한다.)
            print(f"\n⚠️ 원천 장애로 중단됐다. 다음 실행이 이어받는다: {e}", file=sys.stderr)
            곁기록["종류"] = "중단"
            return 2
        print(f"\n경과 {time.monotonic() - 시작:.0f}초")

    코드 = _감사하고_남긴다(연결.db_path(a.db), 곁기록, a.표본)
    곁기록["종류"] = "게이트" if 코드 else "정상"
    return 코드
