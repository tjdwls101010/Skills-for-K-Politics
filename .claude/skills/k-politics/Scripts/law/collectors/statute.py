# ── 판본 병합 ────────────────────────────────────────────────
#
# ⚠️ **이 규칙 하나를 목록 단계와 변환 스크립트가 함께 쓴다.** 두 곳에 따로 적으면 변환이
#    고른 판본과 다음 일일 수집이 고른 판본이 갈리고, 매일 본문을 다시 받으면서도 행은
#    그대로인 상태가 된다 — 수집은 성공으로 끝나고 아무도 모른다.


def 판본선택(현행행들, 예정행들, 오늘: str) -> dict[str, dict]:
    """법령ID → `{'선택', '현행에서', '시행예정일련번호', '시행예정일'}`.

    - **선택 판본**: 현행 분류 중 시행일자가 가장 늦은 것. 현행이 하나도 없으면(제정 후 시행
      전 등, 실측 51건) 예정 중 **시행일이 오늘 뒤인** 가장 이른 것, 그것도 없으면 예정 중
      가장 늦은 것.
    - **예정 판본**: 선택 판본이 아닌 예정 중 시행일이 오늘 뒤인 가장 이른 것.

    ⚠️ **시행예정 목록에 시행일이 이미 지난 판본이 섞여 있다**(실측 102건). 그것을 예정으로
    이으면 `시행예정일` 이 과거가 되어 "곧 이렇게 바뀐다"가 거짓이 된다. 오늘 뒤인 것만
    예정으로 잇는다.

    ⚠️ **시행예정 목록은 한 판본을 시행일마다 한 행씩 준다.** 개정이 여러 날에 걸쳐 나뉘어
    시행되는 법이 그렇다. 같은 MST 가 여러 행이므로 MST 로 묶지 말고 행 그대로 훑는다.
    """
    묶음: dict[str, dict[str, list[dict]]] = {}
    for 분류, 행들 in (("현행", 현행행들), ("시행예정", 예정행들)):
        for 행 in 행들:
            법령ID = str(행.get("법령ID") or "")
            if not 법령ID:
                continue
            묶음.setdefault(법령ID, {"현행": [], "시행예정": []})[분류].append(행)

    def 시행일(행) -> str:
        return 정규화.날짜(행.get("시행일자")) or ""

    결과: dict[str, dict] = {}
    for 법령ID, 갈래 in 묶음.items():
        예정 = sorted(갈래["시행예정"], key=시행일)
        앞선예정 = [행 for 행 in 예정 if 시행일(행) > 오늘]
        if 갈래["현행"]:
            선택 = max(갈래["현행"], key=시행일)
        elif 앞선예정:
            선택 = 앞선예정[0]
        else:
            선택 = 예정[-1]
        선택MST = str(선택["법령일련번호"])
        다음 = next((행 for 행 in 앞선예정 if str(행["법령일련번호"]) != 선택MST), None)
        결과[법령ID] = {
            "선택": 선택,
            # ⚠️ **선택이 현행 분류에서 왔는가.** 부분 수신에서 이 값이 거짓이면 그 법의
            #    현행 행을 **못 받은 것**일 수 있고, 그때 예정 본문을 담으면 오늘 효력
            #    있는 조문이 몇 년 뒤 조문으로 바뀐다. 부르는 쪽이 이 값으로 가른다.
            "현행에서": bool(갈래["현행"]),
            "시행예정일련번호": str(다음["법령일련번호"]) if 다음 else None,
            "시행예정일": 시행일(다음) or None if 다음 else None,
        }
    return 결과


# ── 번호 정규화 ──────────────────────────────────────────────

# 원천은 항번호를 원 문자로 준다. ①~⑳ 은 이어져 있지만 그 위는 블록이 갈린다.
_원문자: dict[str, int] = {}
for _시작, _n, _기준 in (("①", 20, 1), ("㉑", 15, 21), ("㊱", 15, 36)):
    for _i in range(_n):
        _원문자[chr(ord(_시작) + _i)] = _기준 + _i


def 번호(값, 기본: int | None = None) -> int | None:
    """`'①'` → 1 · `'1.'` → 1 · `'2'` → 2 · `''` → 기본.

    ⚠️ **원 문자를 먼저 본다.** 숫자만 뽑는 방식으로 시작하면 `'①'` 에서 아무 숫자도
    안 나와 항번호가 통째로 NULL 이 된다.
    """
    if 값 is None:
        return 기본
    s = str(값).strip()
    if not s:
        return 기본
    if (n := _원문자.get(s[0])) is not None:
        return n
    숫자 = "".join(ch for ch in s if ch.isdigit())
    return int(숫자) if 숫자 else 기본


# ── 편장절 접기 ──────────────────────────────────────────────

# 원천은 편·장·절·관 제목을 조문과 같은 배열에 한 행씩 섞어 준다. 그 행도 조문번호를 갖고
# 실제 조와 겹치므로 `조문번호=15` 만 걸면 제목 행이 함께 나온다 — 에러 없이.
_수준 = ("편", "장", "절", "관")
_제목패턴 = re.compile(r"^제\s*\d+\s*(편|장|절|관)")


class 편장절경로:
    """제목 행을 수준별 슬롯에 넣고 조마다 경로 한 줄을 낸다.

    ⚠️ **단순 누적(`group_concat`)은 틀린다.** 실측에서 제1편 총칙이 제2편 조문에까지
    따라붙었다. 상위 수준이 갱신되면 **하위 슬롯을 비워야** 한다.

    ⚠️ **규칙 밖의 제목 행도 버리지 않는다**(실측 44건, `'제3속 …'`·`'○○법은 이를 폐지한다'`
    같은 것). 가장 아래 슬롯 뒤에 그대로 덧붙인다 — 수준을 못 읽었다고 지우면 그 조가
    어디 속하는지가 통째로 사라진다.
    """

    def __init__(self) -> None:
        self._슬롯: dict[str, str] = {}
        self._덧붙임: list[str] = []

    def 제목(self, 내용: str) -> None:
        if m := _제목패턴.match(내용):
            수준 = m.group(1)
            self._슬롯[수준] = 내용
            for 아래 in _수준[_수준.index(수준) + 1:]:
                self._슬롯.pop(아래, None)
            self._덧붙임.clear()
        else:
            self._덧붙임.append(내용)

    def 경로(self) -> str | None:
        길 = [self._슬롯[수준] for 수준 in _수준 if 수준 in self._슬롯] + self._덧붙임
        return " > ".join(길) or None


