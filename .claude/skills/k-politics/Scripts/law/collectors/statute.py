def 전문조립(단위: dict) -> str:
    """조 머리와 모든 항·호·목을 원천 순서대로 이어 붙인다. **이 파일의 요점이다.**

    ⚠️ **모든 배열 필드에 단수/복수 정규화를 건다.** 항이 하나뿐인 조에서 `항` 이
    리스트가 아니라 dict 로 온다.

    ⚠️ **`항` 객체에 항번호·항내용이 없고 `호` 만 있는 조가 있다**(개인정보 보호법 126개 중
    12개). 그 호도 그대로 이어 붙는다 — 없는 항을 만들어 낄 필요가 없다.
    """
    조각: list[str] = []
    if 머리 := 정규화.씻는다(단위.get("조문내용")):
        조각.append(머리)
    for 항 in 원천.행들(단위.get("항")):
        if 내용 := 정규화.씻는다(항.get("항내용")):
            조각.append(내용)
        for 호 in 원천.행들(항.get("호")):
            if 내용 := 정규화.씻는다(호.get("호내용")):
                조각.append(내용)
            for 목 in 원천.행들(호.get("목")):
                if 내용 := 정규화.씻는다(목.get("목내용")):
                    조각.append(내용)
    return "\n".join(조각)


def 조문행들(단위들) -> list[dict]:
    """정규화된 조문 단위들을 `조문` 행 목록으로. 제목 행은 `편장절` 컬럼으로 접힌다.

    단위는 `{조문여부, 조, 가지, 제목, 전문, 시행일자, 변경여부}` 다 — 원천 응답과 옛 DB 가
    **이 한 함수를 함께 쓰게** 하려고 모양을 맞춰 넘긴다. 접기 규칙을 두 곳에 적으면
    변환이 만든 `편장절` 과 다음 수집이 만드는 `편장절` 이 갈리고, 그건 조용하다.

    ⚠️ **조가 하나도 없는 법령이 실재한다**(실측 26건). `경상북도와 대구광역시 간 관할구역
    변경에 관한 법률` 처럼 한 문장이 법의 전부인 것들이고, 원천은 그 문장을 조가 아닌 행으로
    준다. 제목으로만 접으면 **그 법의 본문이 통째로 사라진다** — 조문 0행이라 검색에도
    안 걸리고, 법령 행은 멀쩡히 남아 "본문이 없는 법"처럼 보이지도 않는다.
    그래서 조가 하나도 안 나온 법에서는 그 문장들이 곧 본문이며 `조 0` 으로 담는다.
    """
    경로 = 편장절경로()
    행들: list[dict] = []
    접힌것: list[dict] = []
    for 단위 in 단위들:
        내용 = 단위["전문"]
        if 단위["조문여부"] != "조문":
            if 내용:
                경로.제목(내용)
                접힌것.append(단위)
            continue
        if not 내용:
            continue
        행들.append({
            "순서": len(행들),
            "조": 단위["조"],
            "가지": 단위["가지"],
            "편장절": 경로.경로(),
            "제목": 단위["제목"],
            "전문": 내용,
            "시행일자": 단위["시행일자"],
            "변경여부": 단위["변경여부"],
        })
    if not 행들 and 접힌것:
        행들.append({
            "순서": 0, "조": 0, "가지": 0, "편장절": None, "제목": None,
            "전문": "\n".join(u["전문"] for u in 접힌것),
            "시행일자": 접힌것[-1]["시행일자"], "변경여부": 접힌것[-1]["변경여부"],
        })
    return 행들


def 조문들풀기(몸통: dict) -> list[dict]:
    """본문 응답의 조문 배열을 `조문행들` 이 받을 모양으로 정규화해 넘긴다."""
    return 조문행들(
        {
            "조문여부": 정규화.씻는다(단위.get("조문여부")) or "조문",
            "조": 번호(단위.get("조문번호"), 0),
            "가지": 번호(단위.get("조문가지번호"), 0),
            "제목": 정규화.씻는다(단위.get("조문제목")) or None,
            "전문": 전문조립(단위),
            "시행일자": 정규화.날짜(단위.get("조문시행일자")),
            "변경여부": 정규화.씻는다(단위.get("조문변경여부")) or None,
        }
        for 단위 in 원천.행들((몸통.get("조문") or {}).get("조문단위"))
    )


def 본문파싱(몸통: dict, 목록행: dict) -> tuple[dict, dict[str, list[dict]]]:
    """본문 응답과 **병합된** 목록 행을 합쳐 `저장()` 이 받을 모양으로.

    ⚠️ **시행예정 두 컬럼은 본문에 없다.** 목록 병합의 산물이라 `목록행` 에서만 온다.
    빠뜨리면 "곧 이렇게 바뀐다"를 통째로 못 말하게 된다.
    """
    기본 = 몸통.get("기본정보") or {}
    법종 = 기본.get("법종구분") or {}
    부처 = 기본.get("소관부처") or {}

    법령 = {
        "법령ID": 정규화.씻는다(기본.get("법령ID") or 목록행.get("법령ID")),
        "법령일련번호": str(목록행["법령일련번호"]),
        "법령명": 정규화.씻는다(기본.get("법령명_한글") or 목록행.get("법령명한글")),
        "법령약칭": 정규화.씻는다(기본.get("법령명약칭") or 목록행.get("법령약칭명")) or None,
        "법종구분": 정규화.씻는다(법종.get("content") or 목록행.get("법령구분명")),
        "소관부처": 정규화.씻는다(부처.get("content") or 목록행.get("소관부처명")) or None,
        # ⚠️ **날짜는 `씻는다()` 가 아니라 `날짜()` 다.** 여기 넷만 `씻는다()` 로 지나가서
        #    같은 DB 안에서 저장 형식이 갈렸고, 달력 검증도 이 넷에만 안 걸려 있었다.
        "공포일자": 정규화.날짜(기본.get("공포일자") or 목록행.get("공포일자")),
        "공포번호": 정규화.씻는다(기본.get("공포번호") or 목록행.get("공포번호")) or None,
        "시행일자": 정규화.날짜(기본.get("시행일자") or 목록행.get("시행일자")),
        "제개정구분": 정규화.씻는다(기본.get("제개정구분") or 목록행.get("제개정구분명")) or None,
        "개정문": 정규화.씻는다((몸통.get("개정문") or {}).get("개정문내용")) or None,
        "제개정이유": 정규화.씻는다(
            (몸통.get("제개정이유") or {}).get("제개정이유내용")
        ) or None,
        "시행예정일련번호": 목록행.get("시행예정일련번호"),
        "시행예정일": 목록행.get("시행예정일"),
    }
    return 법령, {"조문": 조문들풀기(몸통)}


def 실패한판본(conn, 법령ID: str) -> str | None:
    """그 법의 실패 원장이 **어느 MST 에 대한 답**인가. 없으면 `None`.

    ⚠️ **원장의 키는 법령ID 하나지만 실패는 판본에 대한 것이다.** 이 둘을 안 가르면
    MST 하나의 부재가 그 법의 이후 모든 개정 수집을 막는다 — `'없음'` 은 재시도 대상에서
    영구히 빠지는 표지라 다음 실행도, 그다음도 그 법을 안 묻는다.
    """
    r = conn.execute(
        "SELECT 메시지 FROM 수집실패 WHERE 자료종류='법령' AND 자료ID=?",
        (법령ID,)).fetchone()
    if not r or not (r[0] or "").startswith("MST "):
        return None
    return r[0][4:].split(":", 1)[0].strip()


# ── 수집 ─────────────────────────────────────────────────────


def 목록받기(c: 원천.Client) -> tuple[dict[str, dict], int, bool]:
    """현행 + 시행예정을 병합해 `법령ID` → 목록행 으로. 목록행에 시행예정 두 값이 붙는다.

    ⚠️ **`eflaw` 의 `nw` 는 `admrul` 과 뜻이 반대다.** 여기서 2 가 시행예정이고 3 이 현행이다.

    ⚠️ **시행예정 목록의 완결 판정에 행 키를 명시해야 한다.** 한 판본이 시행일마다 한 행씩
    오므로(실측 1,020행 / MST 937종) MST 로 세면 영원히 불완결이 되고, 정리가 통째로
    건너뛰어진다 — 수집은 성공하는데 감사만 빨갛다.
    """
    현행행들, 완결1 = c.목록전량(종류)
    예정행들, 완결2 = c.목록전량(
        종류, target="eflaw", nw=2, 행키=("법령일련번호", "시행일자")
    )
    병합 = 판본선택(현행행들, 예정행들, 연결.now_kst()[:10])
    목록 = {
        법령ID: {**고른["선택"],
                "현행에서": 고른["현행에서"],
                "시행예정일련번호": 고른["시행예정일련번호"],
                "시행예정일": 고른["시행예정일"]}
        for 법령ID, 고른 in 병합.items()
    }
    현행수 = sum(1 for 행 in 현행행들 if 행.get("법령ID"))
    return 목록, 현행수, 완결1 and 완결2


def 수집(
    conn,
    c: 원천.Client,
    로그=print,
    표본: int | None = None,
    전량: bool = False,
) -> dict[str, int]:
    수치 = {"목록": 0, "판본교체": 0, "본문": 0, "실패": 0, "없음": 0, "정리": 0}

    목록, 현행수, 완결 = 목록받기(c)
    수치["목록"] = len(목록)
    예정있음 = sum(1 for 행 in 목록.values() if 행.get("시행예정일련번호"))
    로그(f"  목록 {len(목록):,}개 법령 (현행 판본 {현행수:,}행 · 시행 대기 {예정있음:,})"
        f"{'' if 완결 else ' ⚠️ 불완결 — 정리를 건너뛴다'}")

    # ⚠️ **여기서 직접 DELETE 하지 마라.** `완결` 은 "덜 받았나"만 답하지 "원천이 줄었나"는
    #    안 답한다 — 원천이 반토막 난 목록을 완결로 주면 코퍼스의 절반이 사라진다.
    #    크기·연속 누락 가드는 `prune.정리한다` 가 진다.
    # ⚠️ 목록이 비어도 부른다 — 원천이 0건을 준 날 `정리` 기록이 안 남으면 게이트도 초록이다.
    수치["정리"], 기준선갱신 = 정리.정리한다(
        conn, 종류, "법령", "법령ID", 목록, 완결, 로그)
    저장.기준선기록(conn, 종류, len(목록), 기준선갱신, 완결)

    # **기수집 판정은 "법령ID 행이 있고 그 MST 가 선택 판본과 같다"** 이다.
    # ⚠️ 재개 조건을 "법령ID 행이 있나"로만 두면 **개정이 영영 안 들어온다.** 법령ID 는
    #    개정돼도 유지되므로 첫 수집 이후 모든 판본 교체가 "이미 있다"로 건너뛰어진다.
    담긴판본 = dict(conn.execute("SELECT 법령ID, 법령일련번호 FROM 법령").fetchall())
    # ⚠️ **부분 수신에서 예정 두 컬럼을 지우지 않는다.** 예정 목록을 덜 받은 날 어떤 법의
    #    예정 행이 빠지면 목록행의 값이 NULL 이고, 그대로 `REPLACE` 하면 **멀쩡한 예정이
    #    사라진다** — 부분 수신은 취소로 읽지 않는다는 규율이 본문 저장 경로에도 걸린다.
    담긴예정 = {
        r[0]: (r[1], r[2]) for r in conn.execute(
            "SELECT 법령ID, 시행예정일련번호, 시행예정일 FROM 법령"
            " WHERE 시행예정일련번호 IS NOT NULL")
    }
    없음 = 저장.없음인것(conn, 종류)
    # ⚠️ **'없음'은 그 MST 에 대한 답이지 그 법에 대한 답이 아니다.** 판본이 갈렸으면
    #    다시 묻는다 — 안 그러면 MST 하나의 부재가 **그 법의 이후 모든 개정 수집을 막는다.**
    없음 = {k for k in 없음
          if k in 목록 and 실패한판본(conn, k) == str(목록[k]["법령일련번호"])}
    # ⚠️ **목록에 돌아온 철회 자료는 다시 묻는다.** 공용 루프와 같은 계약이다 — 본문이
    #    실제로 와야 표지가 걷히므로, 안 물으면 복귀가 영영 확인되지 않는다.
    되물을것 = 저장.철회된것(conn, 종류) & set(목록)
    # ⚠️ **부분 수신에서 예정 판본을 현행 자리에 올리지 않는다.** 현행 목록을 덜 받은 날
    #    어떤 법의 현행 행이 빠지면 `판본선택` 이 예정 판본을 고르는데, 그것을 담으면
    #    **오늘 효력 있는 본문이 몇 년 뒤 본문으로 교체된다.** 못 받은 것은 없는 것이 아니다.
    담을수있나 = lambda k: 완결 or 목록[k].get("현행에서") or k not in 담긴판본  # noqa: E731
    대상 = sorted(되물을것, key=list(목록).index) + [
        k for k, 행 in 목록.items()
        if k not in 되물을것 and 담을수있나(k)
        and (전량 or (담긴판본.get(k) != str(행["법령일련번호"]) and k not in 없음))
    ]
    수치["판본교체"] = sum(
        1 for k in 대상 if k in 담긴판본 and 담긴판본[k] != str(목록[k]["법령일련번호"]))
    if 표본:
        대상 = 대상[:표본]
    로그(f"  본문 대상 {len(대상):,}건 (판본 교체 {수치['판본교체']:,} · 없음 {len(없음):,})")
    # ⚠️ **시행예정 두 컬럼은 본문을 다시 안 받는 법령에도 갱신해야 한다.** 예정 판본이
    #    새로 공포된 것은 목록만 바뀌고 선택 판본은 그대로라 위 대상에 안 든다 — 그 법의
    #    "곧 이렇게 바뀐다"가 영영 안 붙는다.
    # ⚠️ **없어진 예정을 NULL 로 되돌리는 것은 완결 수신일 때만이다.** 덜 받은 목록에서
    #    비우면 멀쩡한 예정이 매일 사라졌다 돌아온다 — 부분 수신은 취소로 읽지 않는다.
    if 완결:
        with 연결.트랜잭션(conn):
            conn.executemany(
                "UPDATE 법령 SET 시행예정일련번호=?, 시행예정일=? WHERE 법령ID=?",
                [(행.get("시행예정일련번호"), 행.get("시행예정일"), k)
                 for k, 행 in 목록.items() if k in 담긴판본])
    if not 대상:
        return 수치

    # 원천과 주고받는 손잡이는 MST 이고 우리 키는 법령ID 다. 응답을 우리 키로 되돌리는
    # 표를 미리 만든다 — 매 응답마다 목록을 훑으면 6,000건에 이차 비용이 든다.
    MST에서 = {str(목록[k]["법령일련번호"]): k for k in 대상}
    진행 = 원천.진행자(로그, f"{종류} 본문", len(대상), c)
    처리 = 0
    for 식별값, 몸통, 오류 in c.본문여럿(종류, list(MST에서)):
        처리 += 1
        진행(처리)
        법령ID = MST에서.get(식별값)
        if 법령ID is None:
            continue
        if 오류 is not None:
            # ⚠️ **실패 원장의 키도 법령ID 다.** MST 로 적으면 판본이 갈릴 때마다 원장에
            #    새 행이 쌓이고 적재 등식의 우변이 목록보다 커진다. 어느 판본이 실패했는지는
            #    `실패한판본()` 이 읽는 메시지 머리가 진다.
            # ⚠️ **철회 자료의 재수신이 실패하면 원장을 건드리지 않는다.** '철회'를 덮으면
            #    그 자료가 "원천이 거둬들였다"는 사실을 잃는다 — 공용 루프와 같은 계약이다.
            분류 = "없음" if isinstance(오류, 원천.원천에없음) else "재시도"
            if 법령ID not in 되물을것:
                저장.record_failure(conn, 종류, 법령ID, 분류, f"MST {식별값}: {오류}")
            수치["없음" if 분류 == "없음" else "실패"] += 1
            continue
        try:
            법령행, 자식 = 본문파싱(몸통, 목록[법령ID])
            if not 완결 and 법령행["시행예정일련번호"] is None and 법령ID in 담긴예정:
                법령행["시행예정일련번호"], 법령행["시행예정일"] = 담긴예정[법령ID]
            # ⚠️ **위임 표지를 물려주지 않는다.** `저장()` 의 `REPLACE` 가 `위임` 을
            #    CASCADE 로 이미 비웠으므로, 표지만 남기면 **행이 0인데 "받았다"고 적힌**
            #    상태가 되고 재개 판정이 그 법을 영영 건너뛴다. 표지가 NULL 로 돌아가야
            #    다음 위임 단계가 다시 받는다 — 다시 받는 비용이 빈 채로 굳는 것보다 싸다.
            저장.저장(conn, 종류, 법령행, 자식)
        except Exception as e:  # noqa: BLE001 — 한 건의 실패로 배치를 버리지 않는다
            if 법령ID not in 되물을것:
                저장.record_failure(conn, 종류, 법령ID, "재시도", f"MST {식별값}: {e}")
            수치["실패"] += 1
            continue
        수치["본문"] += 1

    return 수치
