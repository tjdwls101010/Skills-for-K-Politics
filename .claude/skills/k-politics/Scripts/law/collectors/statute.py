"""현행법령 + 시행예정 법령을 받아 `법령`·`조문`·`조문요소`·`부칙` 에 넣는다.

**이 파일의 핵심은 `전문` 조립 하나다.** 원천의 `조문내용` 은 항이 있는 조에서 제목만 담는다 — 개인정보 보호법 조문 126개 중 **항이 있는 조가 97개이고 그 97개가 전부** 그 상태라(요소가 달린 조는 109개인데 12개는 항 없이 호가 바로 온다), `조문내용` 만 인덱싱하면 **68,416자 중 63,835자(93%)가 검색에서 통째로 사라진다.** 에러 없이.
"""

from __future__ import annotations


from law import source as 원천  # noqa: E402
from law import conn as 연결
from law import store as 저장
from law import normalize as 정규화
from law import prune as 정리  # noqa: E402

종류 = "법령"


# ── 번호 정규화 ──────────────────────────────────────────────

# 원천은 항번호를 원 문자로 준다. ①~⑳ 은 이어져 있지만 그 위는 블록이 갈린다.
_원문자: dict[str, int] = {}
for _시작, _n, _기준 in (("①", 20, 1), ("㉑", 15, 21), ("㊱", 15, 36)):
    for _i in range(_n):
        _원문자[chr(ord(_시작) + _i)] = _기준 + _i


def 번호(값, 기본: int | None = None) -> int | None:
    """`'①'` → 1 · `'1.'` → 1 · `'2'` → 2 · `''` → 기본.

    ⚠️ **원 문자를 먼저 본다.** 숫자만 뽑는 방식으로 시작하면 `'①'` 에서 아무 숫자도
    안 나와 항번호가 통째로 NULL 이 된다 — 조문요소가 다 들어가는데 주소만 없는 상태다.
    """
    if 값 is None:
        return 기본
    s = str(값).strip()
    if not s:
        return 기본
    if (n := _원문자.get(s[0])) is not None:
        return n
    숫자 = "".join(ch for ch in s if ch.isdigit())
    return int(숫자) if 숫자 else 기본


def 목번호(값) -> str | None:
    """`'가.'` → `'가'`. 원천이 마침표를 붙여 준다."""
    s = 정규화.씻는다(값).rstrip(". ")
    return s or None


# ── 조문 풀기 ────────────────────────────────────────────────


def 조문단위풀기(단위: dict, 순서: int) -> tuple[dict, list[dict]]:
    """조문단위 하나를 `조문` 행 하나 + `조문요소` 행 여럿으로.

    ⚠️ **모든 배열 필드에 단수/복수 정규화를 건다.** 항이 하나뿐인 조에서 `항` 이
    리스트가 아니라 dict 로 온다. `display=1` 로 개발하고 운영에서 터지는 것과 같은 종류다.

    ⚠️ **조문요소는 `조문키` 가 아니라 `순서`(원천 배열 인덱스)로 잇는다.** 조문키는 법령
    안에서 유일하지 않다 — 편·장 제목이 연달아 오면 두 행이 같은 키를 갖는다.

    ⚠️ **`항` 객체에 항번호·항내용이 없고 `호` 만 있는 조가 있다**(개인정보 보호법 126개 중
    12개). 그때는 깊이 1 행 없이 호가 조 바로 아래 붙는 것이 맞다 — 없는 항을 만들지 마라.
    """
    조문키 = str(단위.get("조문키") or "")
    조문내용 = 정규화.씻는다(단위.get("조문내용"))
    조각: list[str] = [조문내용] if 조문내용 else []
    요소: list[dict] = []

    for 항 in 원천.행들(단위.get("항")):
        항번호 = 번호(항.get("항번호"))
        if 내용 := 정규화.씻는다(항.get("항내용")):
            조각.append(내용)
            요소.append(
                {"조문순서": 순서, "항번호": 항번호, "깊이": 1, "내용": 내용, "순서": len(요소)}
            )
        for 호 in 원천.행들(항.get("호")):
            호번호 = 번호(호.get("호번호"))
            호가지 = 번호(호.get("호가지번호"), 0)
            if 내용 := 정규화.씻는다(호.get("호내용")):
                조각.append(내용)
                요소.append(
                    {
                        "조문순서": 순서,
                        "항번호": 항번호,
                        "호번호": 호번호,
                        "호가지번호": 호가지,
                        "깊이": 2,
                        "내용": 내용,
                        "순서": len(요소),
                    }
                )
            for 목 in 원천.행들(호.get("목")):
                if 내용 := 정규화.씻는다(목.get("목내용")):
                    조각.append(내용)
                    요소.append(
                        {
                            "조문순서": 순서,
                            "항번호": 항번호,
                            "호번호": 호번호,
                            "호가지번호": 호가지,
                            "목번호": 목번호(목.get("목번호")),
                            "깊이": 3,
                            "내용": 내용,
                            "순서": len(요소),
                        }
                    )

    조문 = {
        "조문키": 조문키,
        "조문번호": 번호(단위.get("조문번호"), 0),
        "조문가지번호": 번호(단위.get("조문가지번호"), 0),
        "조문제목": 정규화.씻는다(단위.get("조문제목")) or None,
        "조문내용": 조문내용,
        # ⚠️ 여기가 이 파일의 요점이다. 조문내용만 쓰면 본문의 93%가 사라진다.
        "전문": "\n".join(조각),
        "조문시행일자": 정규화.날짜(단위.get("조문시행일자")),
        "조문변경여부": 정규화.씻는다(단위.get("조문변경여부")) or None,
        "조문여부": 정규화.씻는다(단위.get("조문여부")) or "조문",
        "순서": 순서,
    }
    return 조문, 요소


def 본문파싱(몸통: dict, 목록행: dict) -> tuple[dict, dict[str, list[dict]]]:
    """본문 응답과 목록 행을 합쳐 `저장()` 이 받을 모양으로.

    ⚠️ **`현행연혁코드` 는 본문에 없다.** 목록에만 있다. 이걸 빠뜨리면 NOT NULL 로 터지거나,
    기본값을 채우면 **시행예정 조문을 현행이라고 답하는** 조용한 오답이 된다.
    """
    기본 = 몸통.get("기본정보") or {}
    법종 = 기본.get("법종구분") or {}
    부처 = 기본.get("소관부처") or {}

    법령 = {
        "법령일련번호": str(목록행["법령일련번호"]),
        "법령ID": 정규화.씻는다(기본.get("법령ID") or 목록행.get("법령ID")),
        "법령명": 정규화.씻는다(기본.get("법령명_한글") or 목록행.get("법령명한글")),
        "법령약칭": 정규화.씻는다(기본.get("법령명약칭") or 목록행.get("법령약칭명")) or None,
        "법종구분": 정규화.씻는다(법종.get("content") or 목록행.get("법령구분명")),
        "소관부처": 정규화.씻는다(부처.get("content") or 목록행.get("소관부처명")) or None,
        # ⚠️ **날짜는 `씻는다()` 가 아니라 `날짜()` 다.** 여기 넷만 `씻는다()` 로 지나가서
        #    같은 DB 안에서 저장 형식이 갈렸고, 달력 검증도 이 넷에만 안 걸려 있었다.
        "공포일자": 정규화.날짜(기본.get("공포일자") or 목록행.get("공포일자")),
        "공포번호": 정규화.씻는다(기본.get("공포번호") or 목록행.get("공포번호")) or None,
        "시행일자": 정규화.날짜(기본.get("시행일자") or 목록행.get("시행일자")),
        "제개정구분": 정규화.씻는다(기본.get("제개정구분") or 목록행.get("제개정구분명")) or None,
        "현행연혁코드": 목록행["현행연혁코드"],
        "개정문": 정규화.씻는다((몸통.get("개정문") or {}).get("개정문내용")) or None,
        "제개정이유": 정규화.씻는다(
            (몸통.get("제개정이유") or {}).get("제개정이유내용")
        ) or None,
    }

    조문들: list[dict] = []
    요소들: list[dict] = []
    for i, 단위 in enumerate(원천.행들((몸통.get("조문") or {}).get("조문단위"))):
        조문, 요소 = 조문단위풀기(단위, i)
        if not 조문["조문키"]:
            continue
        조문들.append(조문)
        요소들.extend(요소)

    부칙들 = []
    for i, 단위 in enumerate(원천.행들((몸통.get("부칙") or {}).get("부칙단위"))):
        # ⚠️ 부칙내용은 문자열이 아니라 중첩 리스트다(표본 360/360).
        if 내용 := 정규화.씻는다(단위.get("부칙내용")):
            부칙들.append(
                {
                    "순서": i,
                    "부칙공포일자": 정규화.날짜(단위.get("부칙공포일자")),
                    "부칙공포번호": 정규화.씻는다(단위.get("부칙공포번호")) or None,
                    "내용": 내용,
                }
            )

    return 법령, {"조문": 조문들, "조문요소": 요소들, "부칙": 부칙들}


# ── 수집 ─────────────────────────────────────────────────────


def 목록받기(c: 원천.Client) -> tuple[dict[str, dict], int, bool]:
    """현행 + 시행예정을 `법령일련번호` → 목록행 으로.

    ⚠️ **`eflaw` 의 `nw` 는 `admrul` 과 뜻이 반대다.** 여기서 2 가 시행예정이고 3 이 현행이다.

    ⚠️ **시행예정 목록은 한 버전을 시행일마다 한 행씩 준다.** 실측 1,020행에 MST 는
    937종이고 `(MST, 시행일자)` 가 1,020이다 — 개정이 여러 날에 걸쳐 나뉘어 시행되는
    법이 그렇다(`각급 법원의 설치와 관할구역에 관한 법률` MST 216003 이 세 행).
    그래서 완결 판정의 **행 키를 명시해야 한다.** 안 하면 MST 로 세어 영원히 불완결이
    되고, 아래 정리·승격이 통째로 건너뛰어진다 — 수집은 성공하는데 감사만 빨갛다.
    """
    목록: dict[str, dict] = {}
    현행행들, 완결1 = c.목록전량(종류)
    for 행 in 현행행들:
        행["현행연혁코드"] = "현행"
        목록[str(행["법령일련번호"])] = 행
    현행수 = len(목록)

    예정행들, 완결2 = c.목록전량(
        종류, target="eflaw", nw=2, 행키=("법령일련번호", "시행일자")
    )
    for 행 in 예정행들:
        키 = str(행["법령일련번호"])
        if 키 in 목록:
            continue  # 현행 목록에 이미 있으면 그쪽이 이긴다
        행["현행연혁코드"] = "시행예정"
        목록[키] = 행
    return 목록, 현행수, 완결1 and 완결2


def 수집(
    conn,
    c: 원천.Client,
    로그=print,
    표본: int | None = None,
    전량: bool = False,
) -> dict[str, int]:
    수치 = {"목록": 0, "현행": 0, "시행예정": 0, "승격": 0, "본문": 0, "실패": 0, "없음": 0, "정리": 0}

    목록, 현행수, 완결 = 목록받기(c)
    수치["목록"] = len(목록)
    수치["현행"] = 현행수
    수치["시행예정"] = len(목록) - 현행수
    로그(f"  목록 {len(목록):,}건 (현행 {현행수:,} · 시행예정 {len(목록)-현행수:,}){'' if 완결 else ' ⚠️ 불완결 — 정리·승격을 건너뛴다'}")

    # ⚠️ **목록에서 사라진 버전을 지운다.** 개정되면 새 법령일련번호가 발급되고 옛 것은
    #    목록에서 빠지는데, 안 지우면 같은 법령ID 에 현행이 두 행 남는다(A11).
    # ⚠️ **여기서 직접 DELETE 하지 마라.** 종전에는 `완결` 하나만 보고 지웠는데, 그것은
    #    "덜 받았나"만 답하지 "원천이 줄었나"는 안 답한다 — 원천이 반토막 난 목록을 완결로
    #    주면 코퍼스의 절반이 사라진다. 크기·연속 누락 가드는 `적재.정리한다` 가 진다.
    # ⚠️ 목록이 비어도 부른다 — 원천이 0건을 준 날 `정리` 기록이 안 남으면 A25 도 초록이다.
    수치["정리"], 기준선갱신 = 정리.정리한다(
        conn, 종류, "법령", "법령일련번호", 목록, 완결, 로그)
    저장.기준선기록(conn, 종류, len(목록), 기준선갱신, 완결)

    # ⚠️ **시행예정은 시간이 지나면 현행이 된다.** 그런데 재개 조건이 "본문 테이블에
    #    없는 것" 뿐이라, 이미 `시행예정` 으로 저장된 MST 가 나중에 현행 목록에 나타나도
    #    **본문도 상태도 갱신하지 않고 건너뛴다.** 실측: 시행예정 804행 중 100행이
    #    이미 시행일이 지나 있었다. 조문 조회에 `현행연혁코드='현행'` 을 거는 것이 관용인데,
    #    그러면 **이미 시행된 법이 조회에서 통째로 빠진다.**
    #    본문을 다시 받을 필요는 없다 — 같은 MST 면 조문이 같다. 상태만 갈아 끼운다.
    if 완결:
        with 연결.트랜잭션(conn):
            for 키, 행 in 목록.items():
                conn.execute(
                    "UPDATE 법령 SET 현행연혁코드=? WHERE 법령일련번호=? AND 현행연혁코드<>?",
                    (행["현행연혁코드"], 키, 행["현행연혁코드"]),
                )
            수치["승격"] = conn.total_changes
    이미 = {r[0] for r in conn.execute("SELECT 법령일련번호 FROM 법령")}
    없음 = 저장.없음인것(conn, 종류)
    대상 = [k for k in 목록 if 전량 or (k not in 이미 and k not in 없음)]
    if 표본:
        대상 = 대상[:표본]
    로그(f"  본문 대상 {len(대상):,}건")
    if not 대상:
        return 수치

    진행 = 원천.진행자(로그, f"{종류} 본문", len(대상), c)
    처리 = 0
    for 식별값, 몸통, 오류 in c.본문여럿(종류, 대상):
        처리 += 1
        진행(처리)
        if 오류 is not None:
            종류이름 = "없음" if isinstance(오류, 원천.원천에없음) else "네트워크"
            저장.record_failure(conn, 종류, 식별값, 종류이름, str(오류))
            수치["없음" if 종류이름 == "없음" else "실패"] += 1
            continue
        try:
            법령행, 자식 = 본문파싱(몸통, 목록[식별값])
            저장.저장(conn, 종류, 법령행, 자식)
        except Exception as e:  # noqa: BLE001 — 한 건의 실패로 배치를 버리지 않는다
            저장.record_failure(conn, 종류, 식별값, "파싱", str(e))
            수치["실패"] += 1
            continue
        수치["본문"] += 1

    return 수치
