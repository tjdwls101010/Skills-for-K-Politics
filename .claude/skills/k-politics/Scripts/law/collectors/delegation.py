"""조문 → 하위 규범. `lsDelegated` 가 주는 위임 그래프를 `위임` 에 넣는다.

**이 DB 에서 규범과 규범을 잇는 유일한 자리다.** 여기가 없던 동안 개인정보 보호법 (011357)과 그 시행령(011468)은 스키마상 아무 관계도 아니었고, "이 조를 구체화한 시행령 조문"을 물으면 답할 길이 없었다.

⚠️ **의율조문과 방향이 반대다.** 의율조문은 `판단 → 조문`, 위임은 `조문 → 하위 규범`이다. 섞으면 "이 조문을 인용한 것"과 "이 조문이 위임한 것"이 한 덩어리가 된다.

⚠️ **`법령일련번호`(버전) 단위로 받는다.** 위임 관계는 그 버전 본문의 성질이라 개정되면 달라진다. 새 버전은 새 MST 를 받으므로, **한 번 받은 MST 는 다시 받을 필요가 없다** — 그게 재개 판정의 근거다.

⚠️ **`위임.순서` 는 안정 식별자가 아니다.** 원천에 순서 필드가 없어 응답 순서로 매긴 것이라 재수집하면 값이 바뀐다. 밖에서 이 값을 붙들면 조용히 다른 행을 가리키게 된다.

⚠️ **`대상제목` 은 원천 제목 그대로가 아니다.** 원천은 위임 한 덩어리에 제목 하나만 붙이는데 그 아래 잎이 다른 규범을 가리키는 일이 있다. 그때는 **잎의 `근거문구` 가 말하는 규범**을 담고 `대상일련번호` 는 비운다 — 제목을 그대로 붙이면 실재하는 다른 규범의 실재하는 조문을 가리키는 행이 되고 **조인마저 성공한다.** 근거문구 안의 「법령명」을 쓰고, 낫표가 없으면 **그 법 자신**으로 읽는다(한국 법률에서 낫표 없는 `제29조` 는 그 법의 제29조다).
"""

