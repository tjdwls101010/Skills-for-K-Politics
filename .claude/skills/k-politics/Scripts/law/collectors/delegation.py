def _하나(값):
    """스칼라면 그대로. 배열이면 **값이 하나로 모일 때만** 그 값, 아니면 None.

    ⚠️ **이 파서에서 가장 위험한 자리다.** 원천이 `위임법령제목`·`위임법령일련번호`·
    `위임구분` 을 배열로 주면서 `위임법령조문정보` 와 **길이가 다르다** — 실측에
    (구분 2개, 조문정보 8개) 같은 조합이 있다. 짝지을 근거가 없는데 인덱스로 맞추면
    **다른 법의 조문을 가리키는 행**이 조용히 만들어진다. 그건 0건보다 나쁘다.

    실측: 표본 61개 법령에서 위임 덩어리의 6%가 이 모양이고 전부 `인용법령` 이라,
    버려도 이 테이블의 목적(법률↔시행령↔시행규칙↔행정규칙)은 다치지 않는다.
    그리고 버린 대상은 `근거문구` 의 「법령명」에 남는다.
    """
    if not isinstance(값, list):
        return 값
    남 = {v for v in 값 if v not in (None, "")}
    return next(iter(남)) if len(남) == 1 else None


# 잎이 **스스로 규범을 지목하는** 링크텍스트. 두 꼴이 실재한다:
#   「관세법」  ·  대법원규칙 / 중앙선거관리위원회규칙 / 헌법재판소규칙
# ⚠️ `대통령령`·`부령` 은 여기 안 들어간다 — 그건 규범 이름이 아니라 **위임 문구**다.
#    포함시키면 시행령 위임이 통째로 비워진다.
_규범링크 = re.compile(r"^(?:「(?P<낫표>[^」]+)」|(?P<주체>[가-힣]{2,}?)(?:규칙|규정|고시|훈령|예규))$")


def _같은규범인가(링크이름: str, 제목: str) -> bool:
    """⚠️ **중점과 마침표를 접고 본다.** 원천이 같은 법을 `설치ㆍ운영` 과 `설치.운영`
    두 표기로 준다(실측 11/92). 이걸 다른 법으로 보면 멀쩡한 연결이 비워진다.

    포함 관계면 같은 규범으로 본다 — `헌법재판소규칙` 의 주체 `헌법재판소` 가
    `헌법재판소 개인정보 보호 규칙` 안에 있으면 그건 같은 규범을 가리키는 것이다.
    """
    접기 = lambda s: s.replace(".", "·").replace(" ", "")  # noqa: E731
    a, b = 접기(링크이름), 접기(제목)
    return bool(a) and bool(b) and (a in b or b in a)


_낫표 = re.compile(r"「([^」]+)」")


def _경쟁규범(잎들: list[dict]) -> int:
    """이 위임정보 안에서 **낫표 없이** 규범을 지목하는 링크가 몇 종이나 경쟁하나.

    ⚠️ **`대법원규칙` 은 규범 이름이기도 하고 위임 문구이기도 하다.** `대법원규칙으로
    정하는` 은 후자이고, 그때 대상은 원천이 준 제목이 맞다(실측: 원격영상재판에 관한
    특례법 제5조 → 원격영상재판에관한규칙). 하나뿐일 때 제목을 버리면 **멀쩡한 시행규칙
    위임을 잃는다.** 둘 이상이 경쟁할 때만 제목 하나로는 못 가른다는 뜻이 된다.
    """
    이름들 = set()
    for 잎 in 잎들:
        m = _규범링크.match(정규화.씻는다(잎.get("링크텍스트")))
        if m and m.group("주체"):
            이름들.add(m.group("주체"))
    return len(이름들)


def _잎의대상(잎: dict, 제목, 번호, 이법: tuple[str | None, str | None], 경쟁: int):
    """이 잎의 대상이 위임정보의 제목·일련번호가 맞는가. **아니면 잎을 따른다.**

    ⚠️ **원천이 위임정보 하나에 제목 하나만 붙여 놓고 그 아래 여러 규범의 잎을 담는다.**
    실측 표본 150개 법률 3,344잎 중 81잎(2.4%)이 제목과 다른 규범을 가리킨다 —
    `관세법` 아래의 `「조세범처벌법」`, `헌법재판소 개인정보 보호 규칙` 아래의
    `대법원규칙`·`중앙선거관리위원회규칙`. 제목을 그대로 붙이면 **실재하는 다른 규범의
    실재하는 조문**을 가리키는 행이 되고, 조인마저 성공한다. 0건보다 나쁘다.

    ⚠️ **그때 일련번호는 물려주지 않는다.** 이름은 잎이 말해 주지만 그 규범의 MST 는
    응답 어디에도 없다. 옆 잎의 것을 쓰면 거짓이 된다.

    ⚠️ **되찾기는 이 잎의 `라인텍스트` 안에서만 한다.** 옆 잎의 법명을 끌어 쓰면
    `「통합방위법」 제2조제13호` 인 잎이 군사기지법으로 간다 — 교차 구현이 실제로 그랬다.
    """
    링크 = 정규화.씻는다(잎.get("링크텍스트"))
    m = _규범링크.match(링크)
    # 낫표는 언제나 인용이다. 낫표 없는 `대법원규칙` 류는 경쟁자가 있을 때만 지목으로 읽는다.
    지목 = bool(m) and (bool(m.group("낫표")) or 경쟁 >= 2)
    if 지목 and 제목 and not _같은규범인가(m.group("낫표") or m.group("주체"), 제목):
        return 링크.strip("「」"), None
    if 제목:
        return 제목, 번호
    # 위임정보의 제목을 못 쓰는 자리(병렬 배열)다. 근거문구가 대상을 말해 주는지 본다.
    이름들 = set(_낫표.findall(정규화.씻는다(잎.get("라인텍스트"))))
    if len(이름들) == 1:
        return next(iter(이름들)), None
    if 이름들:
        return None, None           # 한 문구가 두 법을 가리킨다 — 고를 근거가 없다
    # ⚠️ **낫표 없는 `제29조` 는 그 법 자신의 제29조다.** 한국 법률의 관용이고,
    #    이걸 비우면 자기 인용이 통째로 사라진다(실측 719행 중 25행).
    return 이법


def _정수(값) -> int | None:
    """`'22'` → 22 · `'0'` → None · 없으면 None.

    ⚠️ **`'0'` 을 0 으로 담으면 안 된다.** 원천이 대상 조를 모를 때 이 값을 준다
    (실측 278/1,939). 그대로 담으면 **제0조**를 가리키는 행이 되고, 조인은 0건인데
    집계는 '연결이 있다'로 센다.
    """
    s = 정규화.씻는다(_하나(값))
    if not s.isdigit():
        return None
    return int(s) or None


def 파싱(응답: dict) -> list[dict]:
    """`lsDelegated` 응답 → `위임` 행. **네트워크를 타지 않는다.**

    한 행이 조문정보 잎 하나다 — `(위임한 조·항·호·목) → (대상 규범·조)` 한 쌍.
    """
    법 = ((응답 or {}).get("lsDelegated") or {}).get("법령") or {}
    정보 = 법.get("법령정보") or {}
    # 낫표 없는 조 인용이 가리키는 곳. 응답이 이 값을 안 주면 되찾지 않는다.
    이법 = (정규화.씻는다(정보.get("법령명")) or None,
           정규화.씻는다(정보.get("법령일련번호")) or None)
    if not 이법[0]:
        이법 = (None, None)
    행들: list[dict] = []
    for 항목 in 원천.행들(법.get("위임조문정보")):
        조 = 항목.get("조정보") or {}
        조문번호 = _정수(조.get("조문번호"))
        if 조문번호 is None:
            continue  # 위임한 조를 모르면 걸 자리가 없다
        가지 = _정수(조.get("조문가지번호")) or 0
        for 위 in 원천.행들(항목.get("위임정보")):
            구분 = 정규화.씻는다(_하나(위.get("위임구분"))) or None
            for 키 in _자식키:
                if 키 not in 위:
                    continue
                제목필드, 번호필드 = _대상필드[키]
                # 법령 계열은 위임정보 쪽에, 나머지는 자식 행 안에 대상 식별자가 있다.
                바깥제목 = _하나(위.get(제목필드))
                바깥번호 = _하나(위.get(번호필드))
                잎들 = 원천.행들(위.get(키))
                경쟁 = _경쟁규범(잎들)
                for 자식 in 잎들:
                    제목 = 정규화.씻는다(_하나(자식.get(제목필드)) or 바깥제목) or None
                    번호 = 정규화.씻는다(_하나(자식.get(번호필드)) or 바깥번호) or None
                    제목, 번호 = _잎의대상(자식, 제목, 번호, 이법, 경쟁)
                    행들.append({
                        "순서": len(행들),
                        "조문번호": 조문번호,
                        "조문가지번호": 가지,
                        "위임한자리": 정규화.씻는다(자식.get("조항호목")) or None,
                        "위임구분": 구분,
                        "대상제목": 제목,
                        "대상일련번호": 번호,
                        "대상조문번호": _정수(자식.get("위임법령조문번호")),
                        "대상조문가지번호": _정수(자식.get("위임법령조문가지번호")) or 0,
                        "근거문구": 정규화.씻는다(자식.get("라인텍스트")) or None,
                        "링크문구": 정규화.씻는다(자식.get("링크텍스트")) or None,
                    })
    return 행들


def 수집(conn, c: 원천.Client, 로그=print, 표본=None, 전량=False) -> dict[str, int]:
    """`법령` 에 있는 **모든 버전**에 대해 위임을 받는다.

    ⚠️ **현행만 받으면 시행예정 804행이 위임 0행이 된다.** 이 DB 가 시행예정을 담는
    이유가 "내년부터 바뀌는 조문"이라(D3), 그 버전의 위임을 안 받으면
    "새 법이 무엇을 시행령에 미루나"에 **0건**이 나오고 0건은 "없다"로 읽힌다.

    ⚠️ **재개는 `수집상태` 가 안다**(D19). MST 는 버전 식별자라 한 번 받은 MST 의
    위임은 다시 바뀌지 않는다. 다만 "받았나"만 물으면 안 된다 — 판정 규칙은
    `받을대상()` 에 있고 왜 그런지도 거기 적혀 있다.
    """
    수치 = {"대상": 0, "받음": 0, "행": 0, "실패": 0, "정리": 0}
    사전 = 참조파서.법령사전(conn)

    # ⚠️ 목록에서 빠진 버전의 흔적을 **둘 다** 치운다. 진행 기록만 지우면 실패 원장에
    #    남은 행이 영영 재시도도 완료도 안 되고, A3 이 고칠 수 없는 빨간불로 굳는다.
    with 연결.트랜잭션(conn):
        수치["정리"] = conn.execute(
            "DELETE FROM 수집상태 WHERE 자료종류=? AND 단계=?"
            " AND 키 NOT IN (SELECT 법령일련번호 FROM 법령)", (종류, 단계)
        ).rowcount
        수치["정리"] += conn.execute(
            "DELETE FROM 수집실패 WHERE 자료종류='위임'"
            " AND 자료ID NOT IN (SELECT 법령일련번호 FROM 법령)"
        ).rowcount

    대상 = 받을대상(conn, 전량)
    if 표본:
        대상 = 대상[:표본]
    수치["대상"] = len(대상)
    전체수 = conn.execute("SELECT COUNT(*) FROM 법령").fetchone()[0]
    로그(f"  위임 대상 {len(대상):,}건 (이미 {전체수 - len(대상):,})")
    if not 대상:
        return 수치

    def 하나(mst: str):
        try:
            return mst, 받는다(c, mst), None
        except 원천.인증실패:
            raise  # 전체가 잘못된 것이다. 계속 돌면 6,411건을 헛되이 두드린다
        except Exception as e:  # noqa: BLE001 — 부르는 쪽이 분류한다
            return mst, None, e

    진행 = 원천.진행자(로그, "위임", len(대상), c)
    처리 = 0
    for 식별값, 몸통, 오류 in 원천.맵(하나, 대상, c.워커):
        처리 += 1
        진행(처리)
        if 오류 is not None:
            # ⚠️ **404 를 '위임 없음'으로 확정하지 마라.** `source.py` 는 본문의 4xx 를
            #    "원천의 답"으로 다루는데, 이 엔드포인트에서는 **실측이 반대다** —
            #    전량 수집에서 404 로 실패한 93건을 재시도하니 91건이 데이터를 돌려줬다
            #    (7,804행). 완료로 찍었다면 그 행들이 영영 사라진다. 위임 없음의 신호는
            #    404 가 아니라 **봉투는 멀쩡한데 `위임조문정보` 가 없는 응답**뿐이다.
            저장.record_failure(conn, "위임", 식별값, "네트워크", str(오류))
            수치["실패"] += 1
            continue
        try:
            행들 = 파싱(몸통)
            for 행 in 행들:
                # ⚠️ **`대상일련번호` 로 조문에 닿으려 하지 마라.** 원천이 주는 MST 가
                #    우리 법령에 있는 비율이 60%뿐이다(옛 버전을 가리킨다). 제목으로
                #    현행 법령ID 를 되찾는 경로가 86%로 더 낫다.
                행["대상법령ID"] = (
                    None if 행["위임구분"] == "위임행정규칙"
                    else 참조파서.법령ID해석(사전, 행["대상제목"] or "")
                )
            _완료(conn, 식별값, 행들)
        except Exception as e:  # noqa: BLE001 — 한 건의 실패로 배치를 버리지 않는다
            저장.record_failure(conn, "위임", 식별값, "파싱", f"{type(e).__name__}: {e}")
            수치["실패"] += 1
            continue
        수치["받음"] += 1
        수치["행"] += len(행들)
        if 수치["받음"] % 500 == 0:
            로그(f"    위임 {수치['받음']:,}/{len(대상):,} · {수치['행']:,}행")
    return 수치


def 해결대상(conn, 전량: bool = False) -> list[str]:
    """ID 를 아직 못 풀었고 원천의 부재도 확인하지 않은 행정규칙 판본.

    ⚠ '없음' 기록은 **원천에** 없다는 뜻이지 우리 표에 없다는 뜻이 아니다 — 그 일련번호가 나중에
    우리 `행정규칙` 에 들어오면(재수집·복귀) 호출 없이 채울 수 있으므로 대상에 남긴다.
    `전량` 이면 '없음' 도 다시 묻는다(원천이 되살린 판본).
    """
    return [r[0] for r in conn.execute(
        "SELECT DISTINCT y.대상일련번호 FROM 위임 y"
        " WHERE y.위임구분='위임행정규칙' AND y.대상행정규칙ID IS NULL"
        " AND y.대상일련번호 IS NOT NULL AND y.대상일련번호 <> ''"
        " AND (? OR EXISTS (SELECT 1 FROM 행정규칙 r WHERE r.행정규칙일련번호=y.대상일련번호)"
        "      OR NOT EXISTS (SELECT 1 FROM 수집실패 f"
        "        WHERE f.자료종류='위임행정규칙' AND f.실패종류='없음'"
        "          AND f.자료ID=y.대상일련번호))", (int(전량),)
    )]


def 해결(conn, c: 원천.Client, 로그=print, 표본=None, 전량=False) -> dict[str, int]:
    """옛 일련번호 → 불변 ID. 채운 값과 확인된 부재가 재개 위치다."""
    대상 = 해결대상(conn, 전량)
    if 표본:
        대상 = 대상[:표본]
    수치 = {"대상": len(대상), "ID": 0, "없음": 0, "실패": 0}
    로그(f"  위임해결 대상 {len(대상):,}건")
    # ⚠ DB 는 메인 스레드에서만 읽고 쓴다. 워커에는 본문 호출만 보낸다.
    있는것 = dict(conn.execute(
        "SELECT 행정규칙일련번호, 행정규칙ID FROM 행정규칙"
        " WHERE 행정규칙일련번호 IN (SELECT 대상일련번호 FROM 위임"
        "   WHERE 위임구분='위임행정규칙' AND 대상행정규칙ID IS NULL)"
    ))

    def 하나(번호):
        try:
            if 번호 in 있는것:
                ID = 있는것[번호]
            else:
                몸통 = c.본문하나("행정규칙", 번호)
                ID = _하나([기본.get("행정규칙ID")
                          for 기본 in 원천.행들(몸통.get("행정규칙기본정보"))])
            ID = 정규화.씻는다(ID)
            if not ID:
                raise ValueError("행정규칙기본정보.행정규칙ID 가 없거나 하나로 모이지 않는다")
            return 번호, ID, None
        except 원천.인증실패:
            raise  # 전체가 잘못된 것이다 — 수집() 과 같은 계약. 삼키면 수천 건이 '네트워크' 로 굳는다
        except Exception as e:  # noqa: BLE001 — 부르는 쪽이 분류한다
            return 번호, None, e

    for 번호, ID, 오류 in 원천.맵(하나, 대상, getattr(c, "워커", 1)):
        with 연결.트랜잭션(conn):
            if 오류 is not None:
                구분 = "없음" if isinstance(오류, 원천.원천에없음) else "네트워크"
                저장.record_failure(conn, "위임행정규칙", 번호, 구분, str(오류))
                수치["없음" if 구분 == "없음" else "실패"] += 1
            else:
                conn.execute(
                    "UPDATE 위임 SET 대상행정규칙ID=?"
                    " WHERE 위임구분='위임행정규칙' AND 대상일련번호=?", (ID, 번호)
                )
                저장.clear_failure(conn, "위임행정규칙", 번호)
                수치["ID"] += 1
    return 수치


def 받을대상(conn, 전량: bool = False) -> list[str]:
    """아직 못 받았거나, **받았다고 적힌 만큼 남아 있지 않은** 법령 버전.

    ⚠️ **"받았나"가 아니라 "받은 만큼 있나"를 묻는다.** `저장()` 이 `INSERT OR REPLACE`
    라 법령 한 건을 다시 적재하면 부모 행이 한 번 지워지고, `위임` 의 `ON DELETE CASCADE`
    가 함께 터져 그 법의 위임이 통째로 사라진다. 조문·부칙은 `저장()` 이 자식으로 같이
    다시 넣지만 **위임은 별도 API 호출이라 다시 넣을 것이 없다.**
    완료 표시만 보면 그 법은 **영영 빈 채로 완료**다 — `--전량` 한 번이면 벌어진다.

    건수를 대조하는 이 술어는 원인을 가리지 않는다. 행이 왜 없어졌든 다시 받는다.
    """
    return [r[0] for r in conn.execute(
        "SELECT l.법령일련번호 FROM 법령 l WHERE ? OR NOT EXISTS ("
        "  SELECT 1 FROM 수집상태 s WHERE s.자료종류=? AND s.단계=? AND s.키=l.법령일련번호"
        "    AND s.상태='완료'"
        "    AND s.건수 = (SELECT COUNT(*) FROM 위임 y WHERE y.법령일련번호=l.법령일련번호))",
        (1 if 전량 else 0, 종류, 단계),
    )]


def 받는다(c: 원천.Client, 법령일련번호: str) -> dict:
    """`lsDelegated` 는 여섯 자료종류의 봉투 체계 밖이라 `분류()` 를 못 쓴다.

    ⚠️ **그래도 인증 검사는 반드시 거친다.** 인증 실패도 HTTP 200 이고, 그걸 안 보면
    `파싱()` 이 빈 리스트를 돌려주며 **"위임이 없는 법"으로 6,411건이 조용히 확정된다.**

    ⚠️ 위임이 정말 없는 법이 흔하다(실측 표본 61건 중 12건 = 20%). 그때는 봉투 안에
    `위임조문정보` 키가 아예 없다 — 실패가 아니라 빈 결과다.

    ⚠️ **그래서 봉투를 여기서 확인한다.** `파싱()` 은 모르는 응답에 `[]` 를 주는데,
    그건 "위임 없음"을 흔한 정상으로 다루기 위한 관용이다. 봉투를 안 보면 **원천이
    형식을 바꾼 날 6,411건이 조용히 '위임 없음'으로 확정된다** — 완료로 찍히므로
    다시 받지도 않는다. 빈 결과와 못 알아본 응답을 가르는 것은 이 검사뿐이다.
    """
    payload = 원천.인증확인(
        c._json(원천.본문, {"target": "lsDelegated", "MST": 법령일련번호}),
        f"위임/{법령일련번호}",
    )
    if not payload:
        # ⚠️ **키가 하나도 없는 `{}` 는 형식 변경이 아니라 '여기 아무것도 없다'다.**
        #    실측 6,411건 중 2건(221823·229741)이고 재시도해도 같은 `{}` 였다.
        #    빈 봉투로 정규화해 '위임 없음'으로 흘린다 — 실패로 적으면 매일 다시
        #    두드리고 A3 이 고칠 수 없는 빨간불로 굳는다.
        return {"lsDelegated": {"법령": {}}}
    if not isinstance((payload.get("lsDelegated") or {}).get("법령"), dict):
        raise 원천.API오류(
            f"위임/{법령일련번호}: lsDelegated.법령 봉투가 없다 — 받은 키 {list(payload)}"
        )
    return payload


def _완료(conn, 법령일련번호: str, 행들: list[dict]) -> None:
    """한 법의 위임을 **통째로 갈아 끼운다.**

    ⚠️ **지우고 다시 넣어야 한다.** 개정이 아니라 원천의 링크 정비만으로도 위임이
    줄 수 있는데, 부분 갱신은 사라진 위임을 남긴다 — 없는 관계가 계속 조회에 걸린다.
    `저장()` 이 자식을 지우고 다시 넣는 것과 같은 이유다.
    """
    with 연결.트랜잭션(conn):
        conn.execute("DELETE FROM 위임 WHERE 법령일련번호=?", (법령일련번호,))
        for 행 in 행들:
            저장._삽입(conn, "위임", {"법령일련번호": 법령일련번호, **행})
        conn.execute(
            "INSERT INTO 수집상태 (자료종류, 단계, 키, 상태, 건수, 갱신일시)"
            " VALUES (?, ?, ?, '완료', ?, ?)"
            " ON CONFLICT(자료종류, 단계, 키) DO UPDATE SET"
            "   상태='완료', 건수=excluded.건수, 갱신일시=excluded.갱신일시",
            (종류, 단계, 법령일련번호, len(행들), 연결.now_kst()),
        )
        conn.execute("DELETE FROM 수집실패 WHERE 자료종류='위임' AND 자료ID=?", (법령일련번호,))
