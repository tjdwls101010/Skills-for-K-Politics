def 수집(conn, c: 원천.Client, 로그=print, 표본=None, 전량=False, 자료=None) -> dict[str, int]:
    from law.collectors import loop as 루프

    합 = {"목록": 0, "본문": 0, "실패": 0, "없음": 0, "정리": 0}
    for 종류 in 자료 or 종류들:
        키필드 = 원천.봉투[종류].목록식별자
        행들, 완결 = c.목록전량(종류)
        목록 = {str(r[키필드]): r for r in 행들}
        로그(f"  {종류} 목록 {len(목록):,}건{'' if 완결 else ' ⚠️ 불완결'}")
        # ⚠️ 판례와 같은 이유로 정리를 켠다 — 안 켜면 적재 등식이 어긋난 채 굳는다.
        수치 = 루프.수집루프(conn, c, 종류, 목록, 파싱[종류], 로그, 표본, 전량,
                          정리=True, 검증된목록=완결, 진행자=원천.진행자)
        for k, v in 수치.items():
            합[k] = 합.get(k, 0) + v
    return 합
