# 자료종류 → [(출처필드 컬럼, 파서, 대상 테이블)]
# ⚠️ **출처 이름은 `의율조문.출처` 의 CHECK 세 값 안이어야 한다.** 컬럼 이름을 그대로
#    쓰면 `참조조문` 셋이 한 이름으로 모이는데, 헌재의 `심판대상조문`(위헌 여부를 다툰
#    조문)과 `참조조문`(근거로 든 조문)은 **다른 것을 뜻한다** — 합치면 "이 조가 위헌
#    심판을 받았나"를 못 묻는다.
_출처 = {
    "판례": [("참조조문", 참조조문, "의율조문"), ("참조판례", 참조판례, "인용판례")],
    "헌재결정례": [
        ("심판대상조문", 참조조문, "의율조문"),
        ("참조조문", 참조조문, "의율조문"),
        ("참조판례", 참조판례, "인용판례"),
    ],
    "법령해석례": [("안건명", 안건명, "의율조문")],
}
_ID컬럼 = {
    "판례": "판례ID",
    "헌재결정례": "헌재결정례ID",
    "법령해석례": "법령해석례ID",
}


_주소키 = ("쟁점번호", "법령명원문", "부칙여부", "조", "가지", "항", "호", "호가지", "목")


def _중복제거(행들: list[dict]) -> list[dict]:
    """한 문서가 같은 조문을 여러 번 언급해도 한 행이다.

    한 참조 문자열이 같은 조를 여러 번 언급하면 그대로 담길 때 그 판단이 "여러 번 다퉜다"로
    세어져 의율 집계가 부푼다. `COUNT(DISTINCT 자료ID)` 로 피할 수 있지만, 그 규율을 매
    질의에 요구하는 것보다 **여기서 한 번 거르는 쪽이 안전하다.**
    """
    본, 나온다 = set(), []
    for r in 행들:
        키 = tuple(r.get(k) for k in (_주소키 if "조" in r else ("쟁점번호", "피인용법원", "피인용선고일", "피인용사건번호")))
        if 키 in 본:
            continue
        본.add(키)
        나온다.append(r)
    return 나온다


# 실패 목록을 `result.json` 에 싣는 상한. 넘으면 수치만 남는다 — 요약이 읽을 수 있는
# 크기를 지키는 것이 목적이고, 전수가 필요하면 재파싱을 다시 돌리면 된다.
실패상한 = 500


def _피인용종류(피인용법원: str | None) -> str | None:
    """선례가 어느 표의 것인가. **NULL 은 못 정했다는 뜻이고 그때 `피인용자료ID` 도 NULL 이다.**

    ⚠️ 헌법재판소만 이름으로 갈린다. 그 밖의 법원은 전부 `판례` 이고, 법원명이 아예 없으면
    고를 근거가 없다 — 한쪽으로 몰면 그 절반이 조용히 틀린다.
    """
    if not 피인용법원:
        return None
    return "헌재결정례" if 피인용법원 == "헌법재판소" else "판례"


def 재파싱(conn, 로그=print, 자료=None) -> tuple[dict[str, int], list[dict]]:
    """저장된 원문에서 참조를 다시 뽑는다. **원문이 DB 에 있으므로 네트워크를 안 탄다.**

    돌려주는 것은 `(수치, 실패목록)` 이다. 파서를 고쳤을 때 20만 건을 다시 받지 않아도
    되게 하려고 이 단계를 분리했다.

    ⚠️ **실패는 DB 가 아니라 반환값이다.** `run.py` 가 `result.json` 에 싣고 요약이 읽는다.
    표로 담으면 조회자가 매 세션 읽는 `.schema` 에 수집기 내부 사정이 한 표로 서고, 정작
    그 표를 읽는 코드는 감사 보고값 둘뿐이었다.
    """
    사전 = 법령사전(conn)
    수치 = {"의율조문": 0, "인용판례": 0, "파싱실패": 0, "법령ID미해결": 0, "조문부존재": 0}
    실패: list[dict] = []
    종류들 = 자료 or list(_출처)

    def 적는다(종류, 자료ID, 출처, 원문, 사유):
        수치["파싱실패"] += 1
        # ⚠️ **원문을 통째로 싣지 않는다.** `result.json` 은 워크플로 아티팩트라 판례
        #    참조조문 평균 길이로 수만 건을 실으면 요약이 못 읽을 크기가 된다.
        if len(실패) < 실패상한:
            실패.append({"자료종류": 종류, "자료ID": 자료ID, "출처": 출처,
                        "원문": str(원문)[:200], "사유": 사유})

    # 조문 존재 확인용. (법령ID, 조, 가지) 만 본다 — 항·호까지 보려면 항호목 분해가
    # 있어야 하는데 그 표를 안 담고, 조 단위 확인만으로도 '틀린 성공'의 대부분이 걸린다.
    있는조 = {
        (r[0], r[1], r[2])
        for r in conn.execute("SELECT 법령ID, 조, 가지 FROM 조문")
    }

    # ⚠️ **지우기와 다시 채우기가 한 트랜잭션이어야 한다.** 나누면 다시 채우다 끊겼을 때
    #    참조가 0행인 DB 가 남고, 그건 에러가 아니라 **"그 법을 인용한 판례가 없다"** 로
    #    조회된다. 자료종류별로 나누는 것도 같은 병이다 — 판례는 채워졌는데 헌재는
    #    지워지기만 한 절반 상태가 된다. 다음 실행이 언젠가 고치지만 그동안 하루가 간다.
    with 연결.트랜잭션(conn):
        for 종류 in 종류들:
            conn.execute("DELETE FROM 의율조문 WHERE 자료종류=?", (종류,))
            conn.execute("DELETE FROM 인용판례 WHERE 자료종류=?", (종류,))

        for 종류 in 종류들:
            키 = _ID컬럼[종류]
            필드들 = _출처[종류]
            열 = ", ".join(f for f, _, _ in 필드들)
            건수 = 0
            for 행 in conn.execute(
                f"SELECT {키}, {열} FROM {저장.본문테이블[종류][0]}"
            ).fetchall():
                자료ID = 행[0]
                for i, (출처, 파서, 테이블) in enumerate(필드들):
                    원문 = 행[i + 1]
                    if not 원문:
                        continue
                    나온것 = _중복제거(파서(원문))
                    if not 나온것:
                        적는다(종류, 자료ID, 출처, 원문, "패턴 불일치")
                        continue
                    for r in 나온것:
                        if 테이블 == "의율조문":
                            법령ID = 법령ID해석(사전, r["법령명원문"])
                            if 법령ID is None:
                                수치["법령ID미해결"] += 1
                            elif r["부칙여부"] == 0 and (
                                법령ID, r["조"], r["가지"]
                            ) not in 있는조:
                                # ⚠️ 패턴은 맞았는데 그 조가 법에 없다 — **틀린 성공**이다.
                                #    행은 남기되(구법 참조일 수 있다) 반드시 세어 둔다.
                                수치["조문부존재"] += 1
                                적는다(종류, 자료ID, 출처, r["원문조각"], "조문 부존재")
                            conn.execute(
                                "INSERT INTO 의율조문 (자료종류, 자료ID, 출처, 쟁점번호,"
                                " 법령명원문, 법령ID, 부칙여부, 조, 가지, 항, 호, 호가지, 목, 원문조각)"
                                " VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                                (종류, 자료ID, 출처, r["쟁점번호"], r["법령명원문"], 법령ID,
                                 r["부칙여부"], r["조"], r["가지"], r["항"], r["호"],
                                 r["호가지"], r["목"], r["원문조각"]),
                            )
                            수치["의율조문"] += 1
                        else:
                            conn.execute(
                                "INSERT INTO 인용판례 (자료종류, 자료ID, 쟁점번호, 피인용종류,"
                                " 피인용법원, 피인용선고일, 피인용사건번호, 원문조각)"
                                " VALUES (?,?,?,?,?,?,?,?)",
                                (종류, 자료ID, r["쟁점번호"], _피인용종류(r["피인용법원"]),
                                 r["피인용법원"], r["피인용선고일"],
                                 r["피인용사건번호"], r["원문조각"]),
                            )
                            수치["인용판례"] += 1
                건수 += 1
            로그(f"  {종류} {건수:,}건 파싱")

    # 사건번호로 피인용 자료를 잇는다. 실패가 흔한 것이 정상이다 —
    # 적재 범위(대법원 출처) 밖이거나 원천에 없는 옛 선례가 많다.
    with 연결.트랜잭션(conn):
        # ⚠️ **사건번호는 유일하지 않다.** 실측: 중복 사건번호가 1,823 그룹이고 법원·선고일이
        #    다른 것도 있다. 그냥 scalar subquery 로 이으면 SQLite 가 **임의의 한 행**을 골라
        #    인용 그래프를 거짓으로 연결하는데, `피인용자료ID` 가 NULL 이 아니어서 고아
        #    게이트에는 오히려 **정상 해소로 보인다.** 후보가 정확히 하나일 때만 잇는다.
        # ⚠️ **술어는 `피인용종류` 다.** 판례와 헌재결정례는 일련번호가 겹칠 수 있어, 법원명을
        #    매번 다시 해석하면 이 UPDATE 와 정리의 링크 해제가 갈릴 수 있다.
        conn.execute(
            "UPDATE 인용판례 SET 피인용자료ID = ("
            "  SELECT p.판례ID FROM 판례 p WHERE p.사건번호 = 인용판례.피인용사건번호)"
            " WHERE 피인용종류 = '판례'"
            "   AND (SELECT COUNT(*) FROM 판례 p WHERE p.사건번호 = 인용판례.피인용사건번호) = 1"
        )
        conn.execute(
            "UPDATE 인용판례 SET 피인용자료ID = ("
            "  SELECT d.헌재결정례ID FROM 헌재결정례 d"
            "  WHERE d.사건번호 = 인용판례.피인용사건번호)"
            " WHERE 피인용종류 = '헌재결정례'"
            "   AND (SELECT COUNT(*) FROM 헌재결정례 d WHERE d.사건번호 = 인용판례.피인용사건번호) = 1"
        )
    return 수치, 실패
