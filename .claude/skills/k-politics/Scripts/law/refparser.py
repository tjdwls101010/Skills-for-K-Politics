# ── 1. 괄호 주석 제거 (§1-2) ─────────────────────────────────
#
# **여기가 틀린 성공의 최대 산지다.** 괄호 안에 조문처럼 생긴 것이 들어 있다.
#   구 소득세법(1994. 12. 22. 법률 제4803호로 개정되기 전의 것)  → '제4803호' 가 호=4803 이 된다
#   제23조 제1항(현행 제94조 참조)                                → '제94조' 가 별개 조가 된다
#   헌법재판소법(憲法裁判所法) 제40조                              → 한자가 법령명에 붙는다
#   대법원 1968.6.18. … 판결(집16(2) 민144)                       → 중첩 괄호
#
# 실측: 참조조문 159건 중 구법 표기 33건(21%) · (현행 … 참조) 10건(6%).

# ⚠️ `(나)목` 은 조문 주소의 일부라 지우면 안 된다. 제거 대상에서 먼저 뺀다.
_목괄호 = re.compile(r"\(\s*([가-힣])\s*\)\s*목")


def 괄호제거(s: str) -> str:
    """괄호를 **깊이를 세며** 지운다. `(집16(2) 민144)` 를 `\\([^)]*\\)` 로 지우면
    ` 민144)` 가 남아 다음 토큰 인식이 어긋난다."""
    s = _목괄호.sub(lambda m: f"\x00{m.group(1)}\x01목", s)  # 잠시 빼 둔다
    결과: list[str] = []
    깊이 = 0
    for ch in s:
        if ch == "(":
            깊이 += 1
        elif ch == ")":
            깊이 = max(0, 깊이 - 1)
        elif 깊이 == 0:
            결과.append(ch)
    return "".join(결과).replace("\x00", "(").replace("\x01", ")")


# ⚠️ 대괄호는 **세** 가지다. `[1]` 은 쟁점 번호, `[직권조사사항]` 은 편집자 주석,
#    그리고 `[별표 1]` 은 **실체 주소**다.
#
#    `독점규제 및 공정거래에 관한 법률 시행령 제36조 제1항 [별표 1] 제2호 (가)목`
#
#    `[별표 1]` 을 주석으로 지우면 **별표 안의 호·목이 본칙 제36조 제1항에 붙는다.**
#    전혀 다른 규정을 가리키는 행이 되고 아무 에러도 안 난다. 이 스키마는 별표 안의
#    주소를 담지 못하므로 **거기서 조문 추출을 끊는다** — 앞의 조·항까지만 남긴다.
_별표 = re.compile(r"\[\s*(?:별표|별지|서식|부록)[^\]]*\]|(?:별표|별지|서식)\s*\d+")
_주석대괄호 = re.compile(r"\[[^\]]*[^\d\]][^\]]*\]")

# ⚠️ 전각·이형 괄호가 실재한다(`［1］`·`〔2〕`). ASCII 만 보면 그 쟁점이 전부 NULL 이 되고,
#    `GROUP BY 자료ID, 쟁점번호` 에서 서로 다른 쟁점이 하나로 합쳐진다.
_쟁점괄호정규 = {ord(a): b for a, b in zip("［］〔〕【】", "[][][]")}
_쟁점대괄호 = re.compile(r"\[\s*(\d+)\s*\]")

# ⚠️ `가.` 는 쟁점 표기이고 `가족관계의 등록 등에 관한 법률` 은 법령명이다.
#    **한 글자 + 마침표**일 때만 쟁점으로 본다.
#    ⚠️ 이걸 `[가-하]` 로 쓰면 안 된다 — 유니코드에서 그 범위는 한글 음절 수천 개다.
#    `대.` 같은 것이 걸리고, 뒤에서 목록 index 를 부르는 순간 터진다.
_한글쟁점자 = "가나다라마바사아자차카타파하"
_쟁점한글 = re.compile(rf"^\s*([{_한글쟁점자}])\s*\.\s*(?=[^\s.]|$)")

# 쟁점 경계는 `/` 만이 아니다 — 개행만으로 갈린 것이 실재한다. 공백 collapse 를
# 쟁점 분리보다 먼저 하면 그 경계가 사라진다.
_경계표시 = "\x02"


def 정규화(원문) -> str:
    """§1-1. **어떤 파싱도 시작하기 전에** 한 번 통과시킨다.

    ⚠️ **공백 collapse 전에 개행을 쟁점 경계로 박아 둔다.** 먼저 뭉개면
    `가.소원법 …\\n나. 지하철도건설촉진법 …` 이 한 쟁점이 되고, `나.` 가 법령명 앞에
    붙어 조각을 통째로 못 쓰게 만든다.
    """
    s = 정규화모듈.씻는다(원문)  # HTML 태그 · 엔티티 · 중점 통일
    s = s.translate(_쟁점괄호정규)
    s = 괄호제거(s)
    s = _별표.sub(_경계표시, s)
    s = _주석대괄호.sub(" ", s)
    s = re.sub(r"[\n\r]+", _경계표시, s)
    return re.sub(r"[^\S\n]+", " ", s).strip()


# ── 2. 쟁점 분리 (§2 ①·①-2) ─────────────────────────────────


def 쟁점분리(s: str) -> list[tuple[list[int], str]]:
    """`/` 로 자르고 각 조각 앞의 쟁점 표기를 **전부** 뽑는다.

    실측 159건에서 `[N]` 은 33% · `가./나.` 는 11% 다. **`가.` 를 모르면 그 11%에서
    쟁점번호가 전부 NULL 이 되고, "함께 다퉈진 조문"이 거짓으로 넓어진다.**

    ⚠️ **`[1][2][3]` 처럼 연달아 붙는다.** 첫 번호만 읽으면 나머지 쟁점의 인용이 사라진다.
    """
    나온다: list[tuple[list[int], str]] = []
    밀린번호: list[int] = []
    for 조각 in re.split(rf"[/{_경계표시}]", s):
        조각 = 조각.strip()
        if not 조각:
            continue  # `<br/>` 뒤의 `,,` 같은 빈 조각
        번호들: list[int] = []
        while m := _쟁점대괄호.match(조각):
            번호들.append(int(m.group(1)))
            조각 = 조각[m.end():].strip()
        # ⚠️ **한글 쟁점도 연달아 붙는다** — `가.나.다. 민사소송법 제1조`(실측 2,732건).
        #    한 번만 소비하면 `나.다. 민사소송법` 이 **거짓 법령명**이 된다.
        while not (번호들 and _쟁점대괄호.match(조각)) and (m := _쟁점한글.match(조각)):
            번호들.append(_한글쟁점자.index(m.group(1)) + 1)
            조각 = 조각[m.end():].strip()
        if 조각:
            나온다.append((밀린번호 + 번호들, 조각))
            밀린번호 = []
        elif 번호들:
            # ⚠️ `[1] <br/>대법원 …` — 쟁점 표기와 내용 사이에 경계가 들어간다.
            #    여기서 버리면 그 인용의 쟁점번호가 통째로 NULL 이 된다.
            밀린번호 = 번호들
    return 나온다


# ── 3. 법령 경계 (§3 ②) ─────────────────────────────────────
#
# 헌재 참조조문에는 법령 사이에 구분자가 전혀 없다.
#   `헌법 제10조, 제80조상훈법 제2조` → `제80조` 와 `상훈법` 사이가 경계다
#
# ⚠️ 조문 표기 뒤의 한글이 전부 법령명인 것은 아니다 — `제23조 제1항 본문`, `제58조제1항중`.
#    **뒤따르는 한글 덩어리가 법령명처럼 끝나고 그 뒤에 조문 표기가 올 때만** 자른다.
#    못 뽑는 쪽이 잘못 뽑는 쪽보다 낫다.
# ⚠️ `규약`·`협정`·`의정서` 를 빠뜨리면 `시민적및정치적권리에관한국제규약 제18조` 가
#    법령명으로 인식되지 않아 **직전 법령(헌법)을 상속한 거짓 행**이 된다. 실측에서 나왔다.
_법령꼬리 = r"(?:법|법률|령|규칙|규정|조례|헌법|헌장|협약|조약|규약|협정|의정서|준칙|고시|훈령|예규|지침)"
_경계 = re.compile(
    r"(제\s*\d+\s*조(?:\s*의\s*\d+)?(?:\s*제\s*\d+\s*[항호](?:\s*의\s*\d+)?)*)"
    rf"(?=[가-힣][^,/]{{0,40}}?{_법령꼬리}\s*(?:부칙\s*)?제\s*\d+\s*조)"
)


# ⚠️ 중점이 조문 표기 **사이**에 오면 그건 접속이지 법령명의 일부가 아니다.
#    `제196조 제1항·제2항`(원문은 `&#8228;`)의 `제2항` 을 잃지 않으려면 여기서 갈라야 한다.
#    ⚠️ 그렇다고 `·` 를 통째로 구분자로 쓰면 안 된다 — `오수·분뇨및축산폐수의처리에관한법률`
#    처럼 **법령명 안에 중점이 들어간다.** 앞이 조·항·호이고 뒤가 `제` 일 때만 자른다.
_중점접속 = re.compile(r"(?<=[조항호])\s*·\s*(?=제\s*\d)")

# ⚠️ **`및`·`와`·`과` 도 조문을 잇는다** — `「건축법」 제69조 및 제69조의2`.
#    구분자로 안 보면 뒤 조문이 통째로 사라진다(실측: 해석례 안건명 219건).
_접속사 = re.compile(r"(?<=[조항호목])\s*(?:및|와|과)\s+(?=제\s*\d)")


def 경계삽입(s: str) -> str:
    return _접속사.sub(",", _중점접속.sub(",", _경계.sub(r"\1,", s)))


# ── 4. 조문 주소 (§1) ────────────────────────────────────────

_주소 = re.compile(
    r"(?:제\s*(?P<조>\d+)\s*조(?:\s*의\s*(?P<가지>\d+))?)?"
    r"\s*(?:제\s*(?P<항>\d+)\s*항)?"
    r"\s*(?:제\s*(?P<호>\d+)\s*호(?:\s*의\s*(?P<호가지>\d+))?)?"
    r"\s*(?:\(?\s*(?P<목>[가-힣])\s*\)?\s*목)?"
)
# `제` 없는 조. 실측 159건 중 1건뿐이라 **조각이 그것으로 시작할 때만** 받는다.
_제없는조 = re.compile(r"^(?P<조>\d+)\s*조(?:\s*의\s*(?P<가지>\d+))?")
_공포번호 = re.compile(r"^(?:법률|대통령령|총리령|[가-힣]*부령)\s*제\s*\d+\s*호$")

# ⚠️ **헌재 `심판대상조문` 은 인용 목록이 아니라 조문 원문을 통째로 옮겨 적은 것이 많다.**
#    `형사소송법 제196조(사법경찰관리)① 생략②경사, 순경은 사법경찰리로서 …` 처럼.
#    그걸 인용 목록으로 읽으면 법령명 자리에 **문장 조각**이 들어앉는다 — 실측:
#      '의 규정에 위반한 자2. 삭제② 생략구 약사법'
#      '"3급"으로 기재된 것은 "6급"으로 변경 기재된 것으로 본다.구 국가유공자 예우 등에 관한 법률 시행령'
#    §08 §3 이 "조문 형식이 아니면 파싱하지 말고 기록한다"고 정한 그 경우다.
#    **후보 이름에 조문 원문의 표지가 있으면 그 조각을 통째로 버린다.** 진짜 규범명에는
#    이 표지들이 사실상 안 들어간다(실측 30,531개 중 원문자 1 · 따옴표 36 — 전부 행정규칙명이고
#    참조조문에 인용되지 않는다).
#    **술어는 전부 실제 규범명 30,531개(법령 + 행정규칙)에 먼저 재 봤다.** 오탐이 0 이거나,
#    오탐이 있어도 그 이름들이 `의율조문` 에 한 번도 인용된 적 없는 것만 남겼다.
#    `audit.py` 의 A7 이 **이 목록을 그대로 가져다 쓴다** — 두 곳에 적으면 어긋난 쪽을
#    아무도 모른다.
잔해술어: list[tuple[str, str]] = [
    (r"[①-⑳㉑-㉟㊱-㊿]", "원문자 — 조문 원문을 옮겨 적은 것 (실제 규범명 오탐 1)"),
    (r"생략|삭제", "'생략'·'삭제' — 조문 원문의 축약 표기"),
    (r"제\s*\d+\s*[조항호]\s*\S", "이름 안에 조문 표기"),
    # ⚠️ 여기서도 `[가-하]` 를 쓰면 안 된다 — 유니코드에서 그 범위는 한글 음절 수천 개라
    #    `대. 민법 제1조` 의 `대. 민법` 이 잔해로 판정돼 정상 참조가 통째로 버려진다.
    #    (실제로 한 번 그렇게 썼고 `test_한글쟁점자를_유니코드_범위로_쓰지_않는다` 가 잡았다.)
    (rf"^\s*[{_한글쟁점자}]\s*\.\s", "쟁점 표기가 이름에 붙었다 (오탐 0)"),
    (r"^제\s*\d+\s*의\s*\d+", "가지번호형 주소로 시작 (오탐 0)"),
    (r"^제\s*\d+(\s*의\s*\d+)?\s*(호|항)", "호·항 주소로 시작 (오탐 0)"),
    (r"^제\s*\d+\s*(내지|,)", "'제N 내지' 로 시작 (오탐 0)"),
    (r"\d+\.\s", "번호 매긴 목록 (법령명 오탐 0 · 행정규칙명 4개는 인용된 적 없다)"),
    (r"다음과 같|- 다", "문장 (오탐 0)"),
    (r"[\"'“”]", "따옴표"),
]
_원문잔해 = re.compile("|".join(f"(?:{p})" for p, _ in 잔해술어))


def _이름인가(후보: str) -> bool:
    """법령명 후보가 이름인가, 조문 원문 조각인가."""
    return bool(후보) and not _원문잔해.search(후보)


def _주소들(s: str):
    """조각 안의 주소를 **왼쪽부터 차례로** 내준다. 빈 매치에서 멈춘다."""
    위치 = 0
    while 위치 < len(s):
        m = _주소.match(s, 위치)
        if not m or not m.group(0).strip():
            break
        yield m
        위치 = m.end() if m.end() > 위치 else 위치 + 1


# 실측: 이 DB 의 `조문요소` 에서 최대 호번호는 144 다(100 초과가 110행뿐).
# 그보다 훨씬 큰 호는 원천의 오타이거나 파서가 공포번호를 물은 것이다 —
# 실측 `관세법 제197조,제126조제600호,…` 는 원천이 그렇게 적어 놓은 것이다.
# **애매하면 버린다** — 조까지는 살리고 호만 떨어뜨린다.
호상한 = 200


def _정수(m, 이름) -> int | None:
    v = m.group(이름) if m else None
    return int(v) if v else None


# ── 5. 참조조문 (§2·§3) ─────────────────────────────────────


def 참조조문(원문) -> list[dict]:
    """판례 `참조조문` · 헌재 `참조조문`/`심판대상조문` 을 의율조문 행으로."""
    행들: list[dict] = []
    for 번호들, 본문 in 쟁점분리(정규화(원문)):
        # ⚠️ `[1][2][3] 민법 제1조` 는 **세 쟁점 전부**에서 그 조문을 의율한 것이다.
        #    첫 번호만 쓰면 쟁점 2·3 의 의율이 사라진다(실측 119건). 인용판례와 같은 규칙이다.
        쟁점들 = 번호들 or [None]
        법령명 = None
        조 = 가지 = 항 = 호 = 호가지 = None
        부칙상속 = 0
        for 조각 in 경계삽입(본문).split(","):
            조각 = 조각.strip().strip(".·")
            if not 조각:
                continue

            새법령 = None
            남은 = 조각
            부칙 = 부칙상속
            if m := re.match(rf"^(.*?{_법령꼬리})\s*(?=(?:부칙\s*)?제?\s*\d+\s*조)", 조각):
                새법령 = m.group(1).strip()
                남은 = 조각[m.end():].strip()
            elif m := re.match(rf"^([^,/]*?{_법령꼬리})(?:\s|$)", 조각):
                # 조문 없이 법령명만 있는 조각. `헌법 전문` 이 그런 예다 —
                # '전문'은 조가 아니라 버리지만, **뒤에 오는 `제4조` 가 상속할 법령명은
                # 여기서 정해진다.** 이걸 놓치면 그 조문들이 통째로 사라진다.
                후보 = m.group(1).strip()
                if not _공포번호.match(후보) and _이름인가(후보):
                    법령명, 조, 가지, 항, 호, 호가지 = 후보, None, None, None, None, None
                continue
            elif re.match(r"^[가-힣]", 조각) and not 조각.startswith(("제", "부칙")):
                continue  # 법령명도 조문도 아닌 조각. 버린다

            if 새법령:
                # `법률 제7246호` 는 공포번호이지 법령명이 아니다(M14).
                # 조문 원문이 섞인 조각도 버린다 — 잘못 뽑는 것보다 못 뽑는 것이 낫다.
                if _공포번호.match(새법령) or not _이름인가(새법령):
                    continue
                법령명, 조, 가지, 항, 호, 호가지 = 새법령, None, None, None, None, None
                부칙 = 부칙상속 = 0

            # ⚠️ 부칙 여부도 상속된다 — `부칙 제7조, 제8조` 에서 뒤 조각은 `부칙` 을 생략한다.
            #    새 법령명이 나오면 리셋된다(위에서 이미 0 으로 돌린다).
            if m := re.match(r"^부칙\s*", 남은):
                부칙 = 부칙상속 = 1
                남은 = 남은[m.end():].strip()

            if _제없는조.match(남은):
                남은 = "제" + 남은

            # ⚠️ **한 조각 안에 조가 연달아 오기도 한다** — `시가지계획령 제43조제47조`.
            #    첫 주소만 보면 뒤가 통째로 사라진다(실측에서 나왔다).
            for m in _주소들(남은):
                새조, 새가지 = _정수(m, "조"), _정수(m, "가지")
                새항, 새호 = _정수(m, "항"), _정수(m, "호")
                새호가지, 새목 = _정수(m, "호가지"), m.group("목")
                if 새호 is not None and 새호 > 호상한:
                    새호 = 새호가지 = None

                # 위 단계가 새로 지정되면 아래 단계는 상속하지 않고 리셋한다.
                # `국유재산법 시행령 제29조 제2항 제1호, 제6항` 의 마지막은 조=29 항=6 호=NULL 이다.
                if 새조 is not None:
                    조, 가지, 항, 호, 호가지 = 새조, 새가지 or 0, 새항, 새호, 새호가지 or 0
                elif 새항 is not None:
                    항, 호, 호가지 = 새항, 새호, 새호가지 or 0
                elif 새호 is not None:
                    호, 호가지 = 새호, 새호가지 or 0
                elif 새목 is None:
                    continue

                if 조 is None or 법령명 is None:
                    continue
                for _쟁점 in 쟁점들:
                    행들.append(
                        {
                            "쟁점번호": _쟁점,
                            "법령명원문": 법령명,
                            "부칙여부": 부칙,
                            "조": 조,
                            "가지": 가지 or 0,
                            "항": 항,
                            "호": 호,
                            "호가지": 호가지 or 0,
                            "목": 새목,
                            "원문조각": 조각,
                        }
                    )
    return 행들


# ── 6. 참조판례 (§6) ────────────────────────────────────────

# ⚠️ **사건번호의 연도가 두 자리인 것이 옛 판례의 기본형이다** — `84다카1957` · `98마626` ·
#    `68다573`. `\d{4}` 로 받으면 1990년대 이전 인용이 통째로 사라지는데, 판례 코퍼스는
#    수십 년치라 그 비중이 작지 않다. 실측 표본의 M5~M9 가 전부 이 형태였다.
#
# ⚠️ **쉼표 뒤 숫자가 병합번호인지 새 사건인지 갈라야 한다.**
#    `2010헌바354, 2011헌바36` 에서 `, 2011` 을 병합번호로 먹으면 `2010헌바2011` 이라는
#    **존재하지 않는 사건번호**가 만들어진다. 뒤에 사건부호가 이어지면 새 사건이다.
#    반대로 `2011스191, 192` 의 `192` 는 같은 사건의 병합번호라 앞의 연도·부호를 상속한다.
#    **둘을 가르는 것은 "쉼표 뒤에 연도+사건부호가 다시 오는가" 하나뿐이다.**
_사건 = r"(?P<사건들>\d{2,4}[가-힣]{1,3}\d+(?:\s*[,·]\s*(?:\d{2,4}[가-힣]{1,3})?\d+)*)"
_사건하나 = re.compile(r"(?:(?P<연도>\d{2,4})(?P<부호>[가-힣]{1,3}))?(?P<번호>\d+)")
# ⚠️ **법원 약칭이 실재한다** — `서울고법`·`부산지법`. `[가-힣]+법원` 만 보면 이것들을
#    못 잡고, 그러면 법원명 없이 날짜부터 매치돼 **직전 법원(대개 대법원)을 상속한다.**
#    가짜 법원이 붙는 것이라 A7 로도 안 잡힌다.
# ⚠️ **`헌재` 를 빠뜨리면 헌재의 인용 그래프가 통째로 빈다.** 헌재는 자기를 약칭으로
#    인용한다 — `헌재 1997. 3. 27. 95헌가17, 판례집 9-1, 219, 232`. 실측: 이걸 모르던
#    동안 헌재 38,672건 중 인용판례가 있는 것이 508건(1%)뿐이었다.
_법원명 = r"헌재|대법원|헌법재판소|[가-힣]{2,10}(?:법원|고법|지법)"
# 스키마가 `'대법원' '헌법재판소'` 로 정한다. 약칭을 그대로 담으면 같은 재판소가 두
# 이름으로 갈려 집계가 쪼개진다.
_법원정규 = {"헌재": "헌법재판소"}
# ⚠️ **앞 인용의 `판결` 이 법원명에 붙는다** — `… 96다2606 판결대법원 1998. …` 처럼
#    구분자가 없으면 `[가-힣]{2,10}법원` 이 `판결대법원` 을 통째로 잡는다. 그 인용은
#    대법원으로 집계되지 않는데 **에러는 안 난다**(실측: `판결대법원` 501행 · `결정대법원` 8행).
#    두 규칙이 다 필요하다. 발령어가 붙은 것은 떼고(`판결서울고등법원`), **`대법원`·
#    `헌법재판소` 는 단일 기관이라 접두가 있으면 그게 무엇이든 앞 인용의 꼬리다**
#    (`다대법원`). 뒤 규칙만 두면 `판결서울고등법원` 이 남고, 앞 규칙만 두면 `다대법원` 이 남는다.
_발령잔재 = re.compile(r"^(?:판결|결정|명령|전원합의체)\s*")
_붙은법원 = re.compile(r"^.+(?P<진짜>대법원|헌법재판소)$")
_인용 = re.compile(
    rf"(?:(?P<법원>{_법원명})\s*)?"
    r"(?P<연>\d{4})\s*\.\s*(?P<월>\d{1,2})\s*\.\s*(?P<일>\d{1,2})\s*\.?\s*"
    # `고지` 는 옛 결정의 발령어다(`1963.2.15. 고지 62마25 결정`).
    # ⚠️ **헌재 형식에는 발령어가 아예 없다.** 그렇다고 그냥 선택으로 두면 본문 속 아무
    #    날짜+숫자 조합이 인용이 되므로, **법원명이 있을 때만** 생략을 허용한다(아래 코드).
    r"(?P<발령>선고|자|고지)?\s*" + _사건
)
# 인식하지 못한 법원 토큰이 날짜 앞에 있으면 **상속하지 말고 비운다.**
# 모르는 법원을 직전 법원으로 채우는 것이 가장 나쁘다.
_모르는법원 = re.compile(r"([가-힣]{2,12}(?:법원|법정|재판소))\s*$")


def 참조판례(원문) -> list[dict]:
    """판례·헌재의 `참조판례` 를 인용판례 행으로.

    ⚠️ **법원명 생략 이어쓰기가 실측 23% 다.** `대법원 …, 1972.6.27. 선고 72다700 판결` 에서
    둘째부터는 법원명이 없다. 상속을 구현 안 하면 그 23%에서 **첫 건만 남고 나머지가
    통째로 사라진다.**
    """
    행들: list[dict] = []
    법원 = None  # ⚠️ 쟁점 경계를 넘어 상속된다 — `나.1983.6.14. 선고 …` 가 실재한다
    for 번호들, 본문 in 쟁점분리(정규화(원문)):
        쟁점 = 번호들 or [None]
        for m in _인용.finditer(본문):
            if not m.group("발령") and not m.group("법원"):
                continue  # 발령어도 법원명도 없으면 인용이라 볼 근거가 없다
            if m.group("법원"):
                이름 = _발령잔재.sub("", m.group("법원")) or m.group("법원")
                if m2 := _붙은법원.match(이름):
                    이름 = m2.group("진짜")
                법원 = _법원정규.get(이름, 이름)
            elif _모르는법원.search(본문[: m.start()]):
                법원 = None  # 모르는 법원을 직전 것으로 채우면 가짜가 된다
            # ⚠️ **여기서 손으로 조립하지 마라.** 저장 형태를 정하는 곳은 `적재.날짜()`
            #    하나여야 한다 — 즉석 f-string 이 하나라도 남으면 그 컬럼만 다른 형식으로
            #    저장되고, 범위 조건이 그 행들을 조용히 빠뜨린다.
            선고일 = 정규화모듈.날짜(
                f"{m.group('연')}.{m.group('월')}.{m.group('일')}"
            )
            연도 = 부호 = None
            for 토막 in re.split(r"\s*[,·]\s*", m.group("사건들")):
                mm = _사건하나.fullmatch(토막.strip())
                if not mm:
                    continue
                if mm.group("연도"):
                    연도, 부호 = mm.group("연도"), mm.group("부호")
                if 연도 is None:
                    continue
                for n in 쟁점:
                    행들.append(
                        {
                            "쟁점번호": n,
                            "피인용법원": 법원,
                            "피인용선고일": 선고일,
                            "피인용사건번호": f"{연도}{부호}{mm.group('번호')}",
                            "원문조각": m.group(0).strip(),
                        }
                    )
    return 행들


# ── 7. 안건명 (§4) ──────────────────────────────────────────

# ⚠️ **꼬리를 `[^,)」]*` 로 열어 두면 안 된다.** `「` 이 제외 집합에 없어서 다음 인용의
#    **여는 낫표까지 삼킨다** — `「민법」 제750조에 따르면 … 「민법」 제751조` 에서 첫 매치가
#    `… 「민법` 까지 먹고 둘째 인용이 통째로 사라진다. 평균 6,000자짜리 행정심판례 `이유`
#    에서는 그렇게 **인용의 절반이 조용히 없어진다.** 주소 문법만 정확히 받는다.
_낫표 = re.compile(
    r"(?P<구>구\s*)?「(?P<법령명>[^」]+)」\s*"
    # ⚠️ 낫표 뒤에 조문이 **여럿** 이어진다 — `제32조제1항, 제2항 및 제91조의3제5항`.
    #    첫 주소만 받으면 나머지가 조용히 사라진다.
    r"(?P<뒤>(?:부칙\s*)?제\s*\d+\s*조(?:\s*의\s*\d+)?"
    r"(?:\s*제\s*\d+\s*[항호](?:\s*의\s*\d+)?)*"
    r"(?:\s*\(?\s*[가-힣]\s*\)?\s*목)?"
    r"(?:\s*(?:,|및|와|과)\s*제\s*\d+\s*(?:조(?:\s*의\s*\d+)?|[항호](?:\s*의\s*\d+)?)"
    r"(?:\s*제\s*\d+\s*[항호](?:\s*의\s*\d+)?)*)*)"
)


def 안건명(원문) -> list[dict]:
    """법령해석례 `안건명` 을 의율조문 행으로. 반환 모양은 `참조조문` 과 같다.

    ⚠️ `등 관련` 의 `등` 은 "여기 적힌 것 말고 더 있다"는 뜻이다. 여기서 뽑은 것은
    **완전하지 않다.**
    """
    s = 정규화모듈.씻는다(원문)
    행들: list[dict] = []
    for m in _낫표.finditer(s):
        # ⚠️ **낫표 안에도 괄호가 들어온다** — 실측:
        #    `「건설기술관리법(2004. 12. 31. 법률 제7305호로 개정되어 … 이전의 것)」`.
        #    참조조문 경로는 정규화에서 괄호를 떼지만 안건명은 괄호가 구조의 일부라
        #    통째로 못 뗀다. **법령명 자리에서만** 뗀다 — 안 떼면 개정 연혁이 통째로
        #    법령명이 되어 어떤 법령ID 와도 안 맞고 `법령명원문` 집계를 오염시킨다.
        법령명 = 괄호제거(m.group("법령명")).strip()
        부칙 = 0
        # ⚠️ **부칙이 낫표 **안**에 들어오기도 한다** — `「지방세법 부칙」 제6조`.
        #    뒤쪽만 보면 법령명이 '지방세법 부칙' 이 되어 어떤 법령ID 와도 안 맞고,
        #    부칙 제6조가 본칙 제6조와 구분되지도 않는다.
        if m2 := re.search(r"\s*부칙\s*$", 법령명):
            부칙, 법령명 = 1, 법령명[: m2.start()].strip()
        법령명 = ("구 " if m.group("구") else "") + 법령명
        if not _이름인가(법령명):
            continue
        뒤 = 괄호제거(m.group("뒤"))
        if m2 := re.match(r"^부칙\s*", 뒤):
            부칙, 뒤 = 1, 뒤[m2.end():]

        # ⚠️ **낫표 하나에 조문이 여럿 이어진다** — `제32조제1항, 제2항 및 제91조의3제5항`.
        #    첫 주소만 받으면 나머지가 조용히 사라진다(실측: 해석례 안건명 219건 ·
        #    행정심판례 이유 7,707건이 이 형태다). 참조조문과 같은 상속 규칙을 쓴다.
        조 = 가지 = 항 = 호 = 호가지 = None
        for 조각 in re.split(r"\s*(?:,|및|와|과)\s*", 뒤.strip()):
            a = _주소.match(조각.strip())
            if not a or not a.group(0).strip():
                continue
            새조, 새가지 = _정수(a, "조"), _정수(a, "가지")
            새항, 새호 = _정수(a, "항"), _정수(a, "호")
            새호가지, 새목 = _정수(a, "호가지"), a.group("목")
            # ⚠️ 참조조문 경로와 같은 상한을 여기도 건다. 안 걸면 낫표 뒤에 이어진
            #    `및 제4244호`(공포번호 조각)가 호=4244 로 들어온다 — 실측 1건.
            if 새호 is not None and 새호 > 호상한:
                새호 = 새호가지 = None
            if 새조 is not None:
                조, 가지, 항, 호, 호가지 = 새조, 새가지 or 0, 새항, 새호, 새호가지 or 0
            elif 새항 is not None:
                항, 호, 호가지 = 새항, 새호, 새호가지 or 0
            elif 새호 is not None:
                호, 호가지 = 새호, 새호가지 or 0
            elif 새목 is None:
                continue
            if 조 is None:
                continue
            행들.append(
                {
                    "쟁점번호": None,
                    "법령명원문": 법령명,
                    "부칙여부": 부칙,
                    "조": 조,
                    "가지": 가지 or 0,
                    "항": 항,
                    "호": 호,
                    "호가지": 호가지 or 0,
                    "목": 새목,
                    "원문조각": m.group(0).strip(),
                }
            )
    return 행들


# ── 9. 법령명 → 법령ID 해석 (§5) ─────────────────────────────


def 법령사전(conn) -> dict[str, str]:
    """정규화한 법령명·약칭 → 법령ID.

    ⚠️ **접두 일치를 쓰지 마라.** `상법시행령` 이 `법령` 테이블에 없을 때 접두 후보
    `상법` 을 고르면 **상법 제15조를 가리키는 행**이 생기고, 상법에도 제15조가 실재하므로
    A7 로도 안 걸린다. 정확·약칭·공백제거 일치만 허용하고 나머지는 NULL 이다.

    ⚠️ 한 이름이 여러 법령ID 를 가리키면(폐지·재제정) **버린다.** 하나를 고르면 그게
    거짓일 확률이 절반이다.

    분류 필터가 없는 이유는 `법령` 의 모든 행이 현행이기 때문이다 — 시행 대기 판본은 행이
    아니라 `시행예정일련번호` 두 컬럼이라 여기 섞일 수가 없다.
    """
    사전: dict[str, set[str]] = {}
    for 명, 약칭, 법령ID in conn.execute(
        "SELECT 법령명, 법령약칭, 법령ID FROM 법령"
    ):
        for 이름 in (명, 약칭):
            for 후보 in (이름, (이름 or "").replace(" ", "")):
                if 후보:
                    사전.setdefault(후보, set()).add(법령ID)
    return {k: next(iter(v)) for k, v in 사전.items() if len(v) == 1}


def 법령ID해석(사전: dict[str, str], 법령명: str) -> str | None:
    이름 = 정규화모듈.씻는다(법령명)
    return 사전.get(이름) or 사전.get(이름.replace(" ", ""))


