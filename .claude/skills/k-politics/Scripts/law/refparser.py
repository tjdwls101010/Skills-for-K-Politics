"""판단이 어느 조문을 의율했고 어느 선례를 인용했는지 뽑는다. 네트워크를 타지 않는다.

**원칙 하나: 못 뽑은 것보다 잘못 뽑은 것이 훨씬 나쁘다.** 미파싱은 `재파싱()` 의 반환값에 세어져 `result.json` 으로 나가지만, 잘못 뽑은 참조는 `의율조문` 에 그럴듯한 행으로 앉아 아무 에러도 안 낸다. **애매하면 버리고 기록하라.**

⚠️ **파싱 실패를 DB 표에 담지 않는다.** 읽는 코드가 감사 보고값 둘뿐이었는데 실측 18,617행 7MB 를 차지했고, 무엇보다 **조회자가 읽는 `.schema` 에 수집기 내부 사정이 한 표로 서 있었다.** 실패는 이 실행의 산물이라 이 실행의 결과 파일이 그 자리다.

단계를 코드 구조에 드러낸다 — 순서가 규칙만큼 중요하기 때문이다.

    정규화 → 괄호 제거 → 쟁점 분리 → 법령 경계 → 조각 분리 → 상속 → 주소 추출

⚠️ **헌재 전문의 주문·이유 표지는 한 종류가 아니다.** `[주 문]` 반각 · `【주 문】` 전각 · 괄호 없는 옛 포맷이 섞이고, 공백도 일반 공백과 U+3000 이 섞인다(`【주　　　문】`). 직접 파싱할 일이 있으면 **공백을 전부 지우고 괄호 유무와 무관하게** 찾아라 — 반각만 보면 절반이 안 보인다.

⚠️ **`판례.참조조문`·`참조판례` 와 헌재의 대응 필드를 지우지 마라.** 재파싱이 그 원문들을 다시 읽어 `의율조문`·`인용판례` 를 통째로 만든다 — 파서를 고쳤을 때 전량 재수집 없이 되돌아올 수 있는 경로가 그것뿐이다.
"""

