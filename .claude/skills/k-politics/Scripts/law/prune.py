def 정리한다(conn, 종류: str, 테이블: str, 키컬럼: str, 목록,
            검증된목록: bool, 로그=print) -> tuple[int, bool]:
    """완결 목록에서 사라진 것을 지운다. 돌려주는 것은 `(지운 행 수, 기준선 갱신 자격)`.

    치우는 대상이 둘이고 규칙이 다르다.

    1. **본문 행이 있는데 목록에 없는 것** — 연속 누락을 쌓고 상한을 채우면 본문·파생 행과
       그 원장 행을 함께 지운다. 되돌릴 수 없으므로 크기 가드 뒤에 있다.
    2. **본문 행이 없고 원장에만 있는 것**('없음'·'재시도'·'본문없음'·'철회') — 목록에서
       사라지면 원장 행을 곧바로 지운다. 유예가 필요 없다. 그 행이 말하던 것이 "목록에는
       있는데 본문이 없다"인데, 목록에서도 빠졌으면 그 문장 자체가 사실이 아니게 된다.
       **안 지우면 적재 등식의 좌변만 남아 고칠 수 없는 빨간불이 된다** — 이미 '없음'이라
       재시도 대상이 아니고 정리는 본문 테이블만 봤기 때문에 다시 수집해도 안 풀린다.
       이 규칙 덕분에 완결 수신 뒤에는 '철회' 행이 전부 목록 안의 자료다.
    """
    def 멈춘다(상태: str, 이유: str, 기준선유지: bool) -> tuple[int, bool]:
        # ⚠️ **`'건너뜀'` 과 `'기준선없음'` 을 한 상태로 묶지 마라.** 건너뜀만 세는 게이트가
        #    있는데, 첫 수집(기준선 수립)까지 '건너뜀' 으로 적으면 **새 DB 의 첫 실행이
        #    무조건 빨간불**이고, 늑대를 부르는 게이트는 곧 무시된다.
        상태기록(conn, 종류, "정리", 상태, len(사라진), 이유)
        if 사라진 or 상태 == "건너뜀":
            로그(f"  ⚠️ 정리를 건너뛴다 — {이유} (후보 {len(사라진):,}행)")
        return 0, not 기준선유지

    # ⚠️ **빈 목록에도 여기까지 와야 한다.** 부르는 쪽이 `if 목록:` 으로 걸러 버리면
    #    원천이 0건을 준 날 `정리` 단계 기록이 아예 안 남고, 옛 '완료' 가 그대로 남아
    #    **게이트가 전부 초록인 채 아무것도 안 받은 실행이 정상으로 끝난다.**
    if not 목록:
        사라진 = set()
        return 멈춘다("건너뜀", "목록이 비었다 — 원천이 아무것도 주지 않았다",
                    기준선유지=True)

    # 목록에 다시 나타난 후보는 **덜 받은 목록에서도** 연속을 끊는다. 왜인지는
    # `목록누락복귀` 가 진다 — 존재의 증거와 부재의 증거는 대칭이 아니다.
    목록누락복귀(conn, 종류, 목록, 완결=검증된목록)

    # ⚠️ IN (?,?,…) 로 하지 마라. 8만 건이면 SQLite 의 변수 상한을 넘는다.
    conn.execute("CREATE TEMP TABLE IF NOT EXISTS _살아있는(키 TEXT PRIMARY KEY)")
    conn.execute("DELETE FROM _살아있는")
    conn.executemany("INSERT OR IGNORE INTO _살아있는 VALUES (?)", [(k,) for k in 목록])
    사라진 = {
        r[0] for r in conn.execute(
            f"SELECT {키컬럼} FROM {테이블} WHERE {키컬럼} NOT IN (SELECT 키 FROM _살아있는)")
    }
    떠난원장 = {
        r[0] for r in conn.execute(
            "SELECT 자료ID FROM 수집실패 WHERE 자료종류=? AND 실패종류 IN (?,?,?,'재시도')"
            " AND 자료ID NOT IN (SELECT 키 FROM _살아있는)", (종류, *본문없는실패))
    }

    if not 검증된목록:
        # ⚠️ 부분 수신에서 지우면 멀쩡한 수집물을 날린다. **연속 횟수도 세지 않는다** —
        #    네트워크가 이틀 흔들린 것만으로 삭제 조건이 채워지면 이 문이 무력해진다.
        # ⚠️ **이걸 게이트로 올리지 마라.** 부분 수신은 네트워크가 흔들린 날마다 나는
        #    평범한 사건이라, 게이트로 올리면 흔한 날에 빨개지고 **늑대를 부르는 게이트는
        #    곧 무시된다.** 여기 남긴 상태는 보고값이 읽는다. 며칠째 이 상태로 멈춰
        #    있는지는 `상태시작일시` 가 진다 — `갱신일시` 는 매 실행 덮인다.
        return 멈춘다("부분", "목록을 다 못 받았다", 기준선유지=True)
    if (막는것 := 정리막는것(conn, 종류, len(목록), len(사라진))):
        갈래, 이유 = 막는것
        return 멈춘다("건너뜀" if 갈래 == "이상" else "기준선없음", 이유,
                    기준선유지=(갈래 == "이상"))

    # ⚠️ **원장 갱신·상태 기록·DELETE 가 한 트랜잭션이어야 한다.** 따로 커밋되면 삭제가
    #    실패한 실행이 "후보 2회 · 정리 완료" 를 남기고, 그 조합에서는 건너뜀 게이트도
    #    초록이고 적재 등식도 남은 본문을 누락이 상쇄해 초록이다 — **실패가 양쪽 게이트에
    #    다 가려진다.**
    지운수 = 0
    with 트랜잭션(conn):
        지울것 = 누락기록(conn, 종류, 사라진)
        상태기록(conn, 종류, "정리", "완료", len(지울것) + len(떠난원장))
