# ⚠️ **교체와 소멸을 가르던 `판본묶음` 은 사라졌다.** 법령이 판본이 아니라 법령ID 단위로
#    한 행이 되면서 개정은 목록 이탈이 아니라 같은 행의 갱신이 됐다 — 가를 것이 없다.
#    판례·헌재결정례·법령해석례에는 애초에 판본이 없다. 한 사건은 한 번 나오고 고쳐
#    나오지 않으므로 목록 이탈은 전부 소멸이고 삭제상한이 그대로 지킨다.


def 누락기록(conn: sqlite3.Connection, 종류: str, 사라진: set[str],
           이번시각: str | None = None) -> set[str]:
    """이번 목록에 없는 것을 `수집실패('목록누락')` 로 쌓고, **연속 상한을 채운 것만** 돌려준다.

    연속 횟수는 `시도횟수` 컬럼이 진다 — 실패 원장의 다른 종류와 같은 자리를 쓰므로, 한
    자료가 '재시도'와 '목록누락'을 동시에 갖는 일이 구조적으로 없다.

    ⚠️ **하루에 몇 번을 돌려도 한 번으로 센다.** 호출 횟수로 세면 워크플로 재시도나 사람이
    손으로 한 번 더 돌린 것만으로 "이틀 연속"이 채워져, **하루짜리 원천 누락을 흡수한다는
    설계가 통째로 우회된다.** 날짜와 간격을 **둘 다** 봐야 하는 이유는 `정리기준` 이 진다.

    ⚠️ **못 센 실행은 `최종일시` 도 안 옮긴다.** 옮기면 짧은 간격으로 자주 도는 수집이
    매번 "아직 간격이 안 찼다" 로 판정되어 **연속이 영영 안 차고 진짜 삭제가 멈춘다.**
    기준점은 마지막으로 **센** 시각이다.

    ⚠️ **다른 실패종류에서 넘어온 자료는 1 부터 다시 센다.** '재시도' 3회를 쌓은 자료가
    목록에서 빠졌을 때 그 3을 물려받으면 **첫 누락에서 이미 상한이 채워져** 하루를 유예
    한다는 설계가 우회된다.
    """
    지난 = 이번시각 or 지금()
    이어짐 = "수집실패.실패종류 = '목록누락'"
    간 = ("date(수집실패.최종일시) <> date(excluded.최종일시) AND"
         " julianday(excluded.최종일시) - julianday(수집실패.최종일시)"
         f" >= {정리기준['누락간격시간']}/24.0")
    conn.executemany(
        "INSERT INTO 수집실패 (자료종류, 자료ID, 실패종류, 메시지, 시도횟수, 최초일시, 최종일시)"
        " VALUES (?, ?, '목록누락', '완결 목록에 없다', 1, ?, ?)"
        " ON CONFLICT(자료종류, 자료ID) DO UPDATE SET"
        "   실패종류='목록누락', 메시지=excluded.메시지,"
        # ⚠️ COALESCE 가 없으면 못 읽는 시각 하나가 `시도횟수 + NULL` 로 NOT NULL 을 깨서
        #    **정리 전체가 예외로 죽는다.** 못 재면 세지 않되 기준점은 새로 잡아 스스로 낫는다.
        f"   시도횟수=CASE WHEN {이어짐} THEN 수집실패.시도횟수 + COALESCE({간}, 0) ELSE 1 END,"
        f"   최초일시=CASE WHEN {이어짐} THEN 수집실패.최초일시 ELSE excluded.최초일시 END,"
        f"   최종일시=CASE WHEN NOT ({이어짐}) OR COALESCE({간}, 1)"
        "     THEN excluded.최종일시 ELSE 수집실패.최종일시 END",
        [(종류, k, 지난, 지난) for k in sorted(사라진)],
    )
    return {
        r[0] for r in conn.execute(
            "SELECT 자료ID FROM 수집실패 WHERE 자료종류=? AND 실패종류='목록누락'"
            " AND 시도횟수>=?", (종류, 정리기준["연속누락"]))
    }



def 정리막는것(conn: sqlite3.Connection, 종류: str, 목록건수: int,
             삭제수: int) -> tuple[str, str] | None:
    """정리를 **멈춰야 하는 이유**를 `(갈래, 설명)` 으로. 멈출 게 없으면 `None`.

    ⚠️ 되돌릴 수 없는 DELETE 앞의 마지막 문이라 **판정을 못 하겠으면 멈추는 쪽**이다.

    ⚠️ **갈래를 가르는 이유가 기준선에 있다.** `'이상'` 이면 이번 목록을 새 기준선으로
    삼아서는 안 된다 — 삼으면 다음 실행이 그 낮은 값과 비교해 통과하고, 가드가 삭제를
    **하루 늦추는 것 이상을 못 한다.** 반대로 `'기준선없음'` 은 목록이 이상하다는 뜻이
    아니라 잴 것이 없다는 뜻이므로, 기준선을 세워야 다음 실행이 정상으로 돈다.
    """
    앞 = 기준선읽기(conn, 종류)
    if not 앞:
        return ("기준선없음", "직전 목록 건수가 없어 줄었는지 잴 수 없다")
    감소율 = (앞 - 목록건수) / 앞
    if 감소율 > 정리기준["감소율상한"]:
        return ("이상", f"목록이 {앞:,} → {목록건수:,} 로 {감소율:.1%} 줄었다"
                        f" (상한 {정리기준['감소율상한']:.0%})")
    if 삭제수 > 정리기준["삭제상한"]:
        return ("이상", f"삭제 후보가 {삭제수:,}행이다 (상한 {정리기준['삭제상한']:,})")
    return None



