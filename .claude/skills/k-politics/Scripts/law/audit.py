def _백업모듈():
    """`backup.py` 를 **파일 하나만 이름 붙여** 불러온다.

    ⚠️ **레포 루트를 `sys.path` 에 올리지 마라** — 네 스킬의 `Scripts/` 에 같은 이름이
    여럿 있어, 먼저 import 된 쪽이 다른 스킬을 조용히 깨뜨린다(테스트에서 실측했다).
    """
    if "backup" in sys.modules:
        return sys.modules["backup"]
    경로 = 연결.SKILL_DIR / "Scripts" / "backup.py"
    if not 경로.is_file():
        return None
    명세 = importlib.util.spec_from_file_location("backup", 경로)
    sys.modules["backup"] = m = importlib.util.module_from_spec(명세)
    명세.loader.exec_module(m)
    return m


# 기준선 세대가 지금 DB 에 없는 표를 기록하고 있을 때 그 사실을 실어 나르는 표지.
# **`None`(세대 없음)과 다른 사건이다** — 견줄 세대는 있는데 견줄 수 없는 것이다.
_스키마가갈림 = "스키마가갈림"


def _직전정상(conn) -> tuple[str | None, list]:
    """`(견준 세대 이름 | None, 급감한 표들)`. 세대가 없으면 `(None, [])`.

    ⚠️ **스키마가 갈린 세대와는 견주지 않는다.** 표를 지우는 재설계를 하면 옛 세대의
    `행수` 는 **다른 코퍼스의 수**가 된다 — 같은 이름으로 남은 표도 담는 정책이 바뀌어
    (판본 전부 → 현행 하나, 위임 전부 → 시행령·시행규칙) 그 감소가 사고인지 설계인지
    이 축은 구별할 수 없다. 그런데 새 세대는 이 게이트가 빨개서 감사통과로 못 올라가므로,
    견주기를 강행하면 **영원히 빨간 채로 굳는다 — 그리고 고칠 수 없는 빨간불은 표 전체를
    무시하게 만든다.**

    판정 근거는 **지금 DB 에 없는 표를 그 세대가 기록하고 있는가** 하나다. 재설계 다음
    세대부터는 표 집합이 같아져 축이 저절로 되살아난다 — 사람이 끌 것이 없다.
    """
    if (있는것 := _직전캐시.get(id(conn))) is not None:
        return 있는것
    답: tuple[str | None, list] = (None, [])
    if (백업 := _백업모듈()) and (기준 := 백업.기준선(_코퍼스이름)):
        이름, 전 = 기준
        지금, 사라진 = {}, []
        for t in 전:
            try:
                지금[t] = conn.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
            except sqlite3.OperationalError:
                사라진.append(t)      # 표가 없다 — 갈린 것이거나 A0 가 진다
        답 = ((_스키마가갈림, 이름, 사라진), []) if 사라진 else (
            이름, 백업.급감표(_코퍼스이름, 전, 지금))
    _직전캐시[id(conn)] = 답
    return 답


def _급감수(conn) -> int:
    # ⚠️ **원장은 세지 않는다.** 일이 끝나면 줄어드는 표라 급감으로 세면 가장 잘 돌아간
    #    날이 가장 빨갛다. 그래도 눈에서 없애지는 않는다 — 상세는 아래가 전부 낸다.
    return sum(1 for *_, 원장 in _직전정상(conn)[1] if not 원장)


def _급감상세(conn) -> str:
    이름, 난것 = _직전정상(conn)
    if 이름 is None:
        # ⚠️ **"기준선 없음" 과 "견줘 봤는데 0" 을 같은 얼굴로 내면 안 된다.** 백업이
        #    멈춘 날 이 축이 조용히 아무것도 안 지키는데 게이트는 초록이다.
        return "기준선 없음 — 검증된 백업 세대가 아직 없다"
    if isinstance(이름, tuple):
        # ⚠️ **세 번째 얼굴이다.** 세대는 있는데 그 세대가 다른 스키마의 코퍼스라
        #    견줄 수 없다. 다음 세대부터 저절로 되살아나므로 사람이 할 일은 없지만,
        #    **그동안 이 축이 아무것도 안 지킨다는 사실**은 보여야 한다.
        _, 세대, 사라진 = 이름
        return (f"{세대} 는 스키마가 다른 코퍼스다 — 견주지 않았다"
                f" (그 세대에만 있는 표: {' · '.join(sorted(사라진))})."
                " 이 축은 다음 백업 세대부터 되살아난다")
    if not 난것:
        return f"{이름} 대비 급감 없음"
    return f"{이름} 대비 " + " · ".join(
        f"{t} {옛:,}→{새:,} ({(1 - 새 / 옛) * 100:.1f}% 감소)"
        + (" (원장 — 판정 아님)" if 원장 else "")
        for t, 옛, 새, 원장 in 난것
    )


def _뷰이름들(schema: str) -> list[str]:
    """`SCHEMA` 가 만드는 뷰 이름 전부. **목록을 손으로 적지 않는 이유가 이것이다** —
    뷰를 하나 더한 날 그 목록만 낡으면 새 뷰는 아무도 안 지킨다.
    """
    return re.findall(r"CREATE VIEW (\S+) AS", schema)


# ⚠️ **빈 것도 위반이다 — 뷰는 사는데 필터가 전부를 걸러내는 상태가 실재하고, 그러면
# ⚠️ **빈 것도 위반이다 — 뷰는 사는데 필터가 전부를 걸러내는 상태가 실재하고, 그러면
#    "이 조를 다룬 판단이 없다"가 조용히 0건으로 나온다.** 다만 **입력이 비어서 비는 것**은
#    뷰의 결함이 아니다. 표본 빌드나 첫 수집이 그 상태라, 그때까지 세면 흔한 날에 빨개지고
#    늑대를 부르는 게이트는 곧 무시된다. 예외는 뷰마다 **무엇이 비었을 때인지**를 명시한다.
