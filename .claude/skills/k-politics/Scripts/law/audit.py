def _깨진뷰상세(conn) -> tuple[int, list[str]]:
    """`(뷰 수, 문제가 있는 뷰들)`. **조회해 보는 것 말고 확인할 방법이 없다** —
    뷰가 가리키는 컬럼이 사라져도 `PRAGMA integrity_check` 는 통과하고 `sqlite_master`
    에도 멀쩡히 앉아 있다.
    """
    이름들 = _뷰이름들(스키마.SCHEMA)
    난것 = []
    for v in 이름들:
        try:
            # ⚠️ **`COUNT(*)` 로 묻지 마라.** 이 게이트가 묻는 것은 "비었나"인데 COUNT 는
            #    뷰 전체를 만들어 낸다 — 집계 뷰에서 그 차이가 0.00초 대 수십 초다.
            #    `LIMIT 1` 은 첫 행에서 멈춘다.
            빈가 = conn.execute(f'SELECT 1 FROM "{v}" LIMIT 1').fetchone() is None
        except sqlite3.Error as e:
            난것.append(f"{v}({e})")
            continue
        if not 빈가:
            continue
        _, 입력 = 비어도되는뷰.get(v, (None, None))
        if 입력 and conn.execute(입력).fetchone() is None:
            continue          # 입력이 비어서 빈 것이다 — 뷰의 결함이 아니다
        난것.append(f"{v}(비었다)")
    return len(이름들), 난것


def _적재등식SQL() -> str:
    """자료종류마다 `|본문 키 ∪ 본문 없는 실패 키| − 목록누락 = 목록 기준선` 인가.

    ⚠️ **합이 아니라 합집합이다.** 두 집합이 같은 키를 가질 수 있는데(법령은 옛 판본 본문과
    새 판본 실패가 공존한다) 합으로 세면 그 행을 두 번 기대해 **고칠 수 없는 빨간불**이 된다.

    ⚠️ **'철회'가 '없음'과 같은 자리에 든다.** 둘 다 "목록에는 있는데 원천이 본문을 안 준다"
    이고, 철회는 본문 요청이 부재로 답할 때 확정되므로 확정 시점에 목록 안이다. 목록 밖으로
    나가면 정리가 '없음'과 똑같은 규칙으로 원장 행을 지운다.

    ⚠️ **'재시도'는 세지 않는다.** 그건 다음 실행이 치우는 큐라 우변에 더하면 실패가
    영구 상태로 굳는다 — 그 잔존은 따로 게이트가 있다.

    ⚠️ **목록누락은 빼서 맞춘다.** 본문 쪽에 이미 들어 있고(그 행은 아직 안 지웠다) 마지막
    완결 목록에는 없다. 안 빼면 하루를 유예한다는 설계가 매번 빨간불로 나온다.
    """
    자리 = ", ".join(f"'{v}'" for v in 저장.본문없는실패)
    조각 = []
    for 종, (테, 키, _) in 저장.본문테이블.items():
        조각.append(
            f"SELECT '{종}' 자료종류,"
            f" (SELECT COUNT(*) FROM (SELECT {키} k FROM {테} UNION"
            f"    SELECT 자료ID FROM 수집실패 WHERE 자료종류='{종}'"
            f"      AND 실패종류 IN ({자리}))) 있는것,"
            f" (SELECT COUNT(*) FROM 수집실패 WHERE 자료종류='{종}'"
            f"    AND 실패종류='목록누락') 목록누락"
        )
    return (
        "SELECT COUNT(*) FROM (" + " UNION ALL ".join(조각) + ") a"
        " JOIN 수집상태 s ON s.자료종류=a.자료종류 AND s.단계='목록'"
        " WHERE s.기준선 > 0 AND a.있는것 - a.목록누락 <> s.기준선"
    )


