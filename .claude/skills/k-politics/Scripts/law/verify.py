def 필드모음(행들) -> dict[str, list[str]] | None:
    """`{"항상": 전 행에 있던 것, "가끔": 일부 행에만 있던 것}`. 빈 응답이면 `None`.

    ⚠️ **원천은 값이 NULL 인 필드를 행에서 통째로 뺀다**(`법령약칭명`·`공동부령정보` 류).
    합집합만 재면 표본이 바뀌는 날 그 희소 필드가 "사라졌다"로 읽히고, **원천이 그대로인데
    `law-collect.yml` 이 그날 수집을 통째로 건너뛴다.** 전 행에 있던 것만 게이트로 삼는다.

    ⚠️ **표본 1행에서는 "전 행에 있다"가 아무것도 뜻하지 않는다** — 2행 미만이면 전부
    '가끔' 이다. 안 그러면 그 한 행의 희소 필드가 통째로 게이트가 되어 같은 함정에 빠진다.

    ⚠️ 0행을 "필드가 전부 사라졌다"로 읽으면 빈 응답 사고를 두 번 세면서 원인을 흐린다.
    """
    if not 행들:
        return None
    전부 = {k for r in 행들 for k in r}
    항상 = set.intersection(*({*r} for r in 행들)) if len(행들) > 1 else set()
    return {"항상": sorted(항상), "가끔": sorted(전부 - 항상)}


def 필드본다(이름: str, 행들) -> None:
    """이번 실행이 본 필드를 적어 둔다. **이미 받아 둔 행을 쓴다 — 요청을 안 늘린다.**

    ⚠️ 같은 이름으로 여러 번 부르면 **합친다.** 마지막 응답만 남기면 그 응답이 마침 짧아
    필드가 덜 온 날 전부 "사라짐"이 된다.
    """
    if (본것 := 필드모음(행들)) is None:
        return
    옛것 = _잰필드.get(이름)
    if 옛것 is None:
        _잰필드[이름] = 본것
        return
    # ⚠️ **'항상' 은 합치는 게 아니라 교집합이다.** 한 호출에만 있던 필드를 '항상' 으로
    #    올리면 그 필드가 다음 날 다른 표본에 없을 때 빨간불이 된다.
    항상 = sorted(set(옛것["항상"]) & set(본것["항상"]))
    전부 = set(옛것["항상"] + 옛것["가끔"] + 본것["항상"] + 본것["가끔"])
    _잰필드[이름] = {"항상": 항상, "가끔": sorted(전부 - set(항상))}


def 필드기준선() -> dict[str, list[str]]:
    """커밋된 기준선.

    ⚠️ **실행 때마다 새로 만들면 비교 대상이 자기 자신이 되어 아무 변화도 안 잡힌다.**
    정당한 변화는 `--기준선갱신` 으로 다시 쓴 뒤 **커밋해서** diff 로 남긴다.
    ⚠️ 파일이 없으면 빈 기준선이다 — 예외를 내면 처음 돌리는 사람이 아무 진단도 못 받는다.
    """
    try:
        날것 = json.loads(필드기준선경로.read_text(encoding="utf-8"))
    except (FileNotFoundError, json.JSONDecodeError):
        return {}
    # ⚠️ **모양이 어긋난 항목 하나로 진단 전체가 죽으면 안 된다.** 그 항목만 게이트에서
    #    빠지고 나머지는 계속 돈다 ('항상' 이 비므로 재기 전까지 아무것도 안 막는다).
    성한것 = {}
    for 이름, v in (날것 or {}).items():
        if isinstance(v, dict) and isinstance(v.get("항상"), list) and isinstance(v.get("가끔"), list):
            성한것[이름] = v
        elif isinstance(v, list):
            성한것[이름] = {"항상": [], "가끔": sorted(v)}
    return 성한것


def 필드대조(기준: dict, 지금: dict) -> tuple[dict[str, list[str]], dict[str, list[str]]]:
    """`(사라진 것, 새로 생긴 것)` — **양쪽에 다 있는 이름만** 본다.

    ⚠️ **안 잰 것과 사라진 것은 다르다.** 이번 실행이 그 종류에 안 갔다는 이유로 전 필드를
    빨갛게 만들면 다음 사람은 표를 통째로 무시하게 된다. 기준선에 없는 이름도 "전부 새
    필드"가 아니라 **아직 기준선이 없는 것**이다.
    """
    사라짐, 새것 = {}, {}
    for 이름 in 기준.keys() & 지금.keys():
        옛, 새 = 기준[이름], 지금[이름]
        옛전부 = set(옛["항상"]) | set(옛["가끔"])
        새전부 = set(새["항상"]) | set(새["가끔"])
        # ⚠️ **게이트는 "항상 있던 것이 이제 아무 행에도 없다" 뿐이다.** 희소 필드가 오늘
        #    표본에 안 온 것과 원천이 필드를 없앤 것은 다르고, 앞의 것으로 수집을 멈추면
        #    원천이 그대로인 날 코퍼스가 낡는다.
        if 간 := sorted(set(옛["항상"]) - 새전부):
            사라짐[이름] = 간
        if 온 := sorted(새전부 - 옛전부):
            새것[이름] = 온
    return 사라짐, 새것


