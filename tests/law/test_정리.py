class Test교체는_코퍼스_축소가_아니다:
    """⚠️ **둘을 같은 숫자로 세면 완결성이 깨진다.**

    법이 개정되면 새 법령일련번호가 발급되고 옛 것이 목록에서 빠진다 — 코퍼스는 줄지
    않고 **같은 법의 판본이 갈린 것**이다. 그런데 삭제상한은 이것도 「삭제 후보」로 세서,
    개정이 흔한 날(실측 2026-08-28 정리 후보 924건 중 **869건이 이 교체**) 상한 100 에
    걸려 **반드시 해야 할 갱신까지 멈춘다.** 그 결과가 같은 법령ID 에 '현행' 이 두 행
    남는 것이고(A11 111건), A1 도 함께 어긋난다.

    ⚠️ **상한을 키우는 것으로는 못 가른다** — 교체 869건을 통과시키려면 상한이 900이
    되어야 하고, 그러면 **진짜 소멸 900건도 함께 통과한다.** 가드가 있는 이유가 없어진다.
    """

    def test_판본_교체는_상한이_막지_않는다(self):
        conn = _DB()
        _법령들(conn, [(f"L{i:04d}", f"I{i:04d}") for i in range(200)])
        저장.상태기록(conn, "법령", "목록", "전체", "완료", 200)
        # 150건이 개정돼 새 일련번호를 받았다. 목록 크기는 그대로 200 이다.
        목록 = {f"N{i:04d}": {"법령ID": f"I{i:04d}"} for i in range(150)}
        목록 |= {f"L{i:04d}": {"법령ID": f"I{i:04d}"} for i in range(150, 200)}
        for _ in range(정리모듈.정리기준["연속누락"]):
            _법령정리(conn, 목록)
        남은 = {r[0] for r in conn.execute("SELECT 법령일련번호 FROM 법령")}
        assert 남은 == {f"L{i:04d}" for i in range(150, 200)}, \
            f"교체된 옛 판본이 안 지워졌다 ({len(남은)}행 남음)"

    def test_교체_판정은_DB_가_아니라_목록을_본다(self):
        """⚠️ **정리는 본문 수집보다 먼저 돈다** — 그 시점에 새 판본은 아직 DB 에 없다.
        "같은 법령ID 의 다른 행이 DB 에 남는가"로 물으면 **모든 교체가 소멸로 세어진다.**
        """
        conn = _DB()
        _법령들(conn, [(f"L{i:04d}", f"I{i:04d}") for i in range(200)])
        저장.상태기록(conn, "법령", "목록", "전체", "완료", 200)
        목록 = {f"N{i:04d}": {"법령ID": f"I{i:04d}"} for i in range(200)}   # 전부 새 판본
        assert not conn.execute(
            "SELECT 1 FROM 법령 WHERE 법령일련번호 LIKE 'N%'").fetchone(), \
            "이 검사의 전제 — 새 판본은 아직 DB 에 없다"
        for _ in range(정리모듈.정리기준["연속누락"]):
            _법령정리(conn, 목록)
        assert conn.execute("SELECT COUNT(*) FROM 법령").fetchone()[0] == 0

    def test_소멸이_상한을_넘으면_여전히_막는다(self):
        """가드가 지켜야 할 것은 그대로 지킨다 — 법이 통째로 사라지는 것은 상한이 센다."""
        conn = _DB()
        _법령들(conn, [(f"L{i:04d}", f"I{i:04d}") for i in range(200)])
        저장.상태기록(conn, "법령", "목록", "전체", "완료", 200)
        # 101개 법령ID 가 통째로 빠지고 그만큼 새 법이 생겼다 — 목록 크기는 200 이라
        # 감소율 가드는 통과한다. 막아야 하는 것은 삭제상한이다.
        목록 = {f"L{i:04d}": {"법령ID": f"I{i:04d}"} for i in range(101, 200)}
        목록 |= {f"X{i:04d}": {"법령ID": f"J{i:04d}"} for i in range(101)}
        for _ in range(정리모듈.정리기준["연속누락"] + 1):
            _법령정리(conn, 목록)
        assert conn.execute("SELECT COUNT(*) FROM 법령").fetchone()[0] == 200, \
            "소멸 101건이 상한 100 을 넘었는데 지워졌다"
        상태 = conn.execute("SELECT 상태 FROM 수집상태 WHERE 자료종류='법령'"
                          " AND 단계='정리' AND 키='전체'").fetchone()
        assert 상태 == ("건너뜀",)

    def test_행정규칙도_같은_계약을_쓴다(self):
        """⚠️ `판본묶음` 에 이름만 올려 두고 검사가 없으면, 그 자료종류의 계약이
        **말로만 있는 상태**가 된다 — `행정규칙ID` 가 법령의 `법령ID` 처럼 판본을 가로질러
        불변이라는 전제가 깨져도 아무도 모른다."""
        conn = _DB()
        conn.executemany(
            "INSERT INTO 행정규칙 (행정규칙일련번호, 행정규칙ID, 행정규칙명, 수집일시)"
            " VALUES (?, ?, '규칙', 'x')",
            [(f"S{i:04d}", f"A{i:04d}") for i in range(200)])
        저장.상태기록(conn, "행정규칙", "목록", "전체", "완료", 200)
        목록 = {f"T{i:04d}": {"행정규칙ID": f"A{i:04d}"} for i in range(150)}
        목록 |= {f"S{i:04d}": {"행정규칙ID": f"A{i:04d}"} for i in range(150, 200)}
        for _ in range(정리모듈.정리기준["연속누락"]):
            _시각[0] += datetime.timedelta(days=1)
            with 시각(_찍기(_시각[0])):
                정리모듈.정리한다(conn, "행정규칙", "행정규칙", "행정규칙일련번호", 목록,
                          True, lambda *a: None)
        남은 = {r[0] for r in conn.execute("SELECT 행정규칙일련번호 FROM 행정규칙")}
        assert 남은 == {f"S{i:04d}" for i in range(150, 200)}, f"{len(남은)}행 남음"
