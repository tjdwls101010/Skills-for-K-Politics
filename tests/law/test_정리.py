def test_감소율은_작아도_양이_크면_멈춘다() -> None:
    """⚠️ **감소율만으로는 큰 코퍼스에서 샌다** — 판례 89,000건의 2% 는 1,780건이다.
    절대 상한이 함께 있어야 "비율은 작지만 양이 큰" 삭제가 막힌다."""
    conn = _DB()
    많은 = [f"P{i:05d}" for i in range(20_000)]
    _행정규칙(conn, *많은)
    저장.상태기록(conn, "행정규칙", "목록", "전체", "완료", len(많은))
    지울 = set(많은[:150])                      # 0.75% — 감소율은 통과한다
    목록 = {i: {} for i in 많은 if i not in 지울}
    for _ in range(정리모듈.정리기준["연속누락"] + 1):
        _돈다(conn, 목록)
    assert _본문수(conn) == len(많은)


def test_기준선이_없으면_그_실행에서는_정리하지_않는다() -> None:
    """첫 수집이거나 상태가 유실된 뒤다. **비교할 것이 없으면 크기를 잴 수 없고,
    잴 수 없으면 지우지 않는다.**

    ⚠️ 다만 "이상하다"와는 다르다 — 목록 자체는 멀쩡하므로 **기준선은 세운다.**
    안 세우면 다음 실행도 잴 것이 없어 정리가 영원히 안 돈다."""
    conn = _DB()
    _행정규칙(conn, *[f"R{i:04d}" for i in range(_모집단)])   # 기준선을 안 남긴다
    목록 = {f"R{i:04d}": {} for i in range(_모집단 - 1)}

    _돈다(conn, 목록)
    assert _본문수(conn) == _모집단
    assert conn.execute("SELECT COUNT(*) FROM 정리후보").fetchone()[0] == 0, \
        "잴 수 없는 실행에서는 연속 횟수도 세지 않는다"
    assert conn.execute(
        "SELECT 상태, 건수 FROM 수집상태 WHERE 자료종류='행정규칙'"
        " AND 단계='목록' AND 키='전체'").fetchone() == ("완료", _모집단 - 1)


def test_하루짜리_누락은_흡수한다() -> None:
    """⚠️ **원천은 하루 빠뜨렸다가 다음 날 되돌려 준다.** 첫 누락에서 지우면 그
    하루 때문에 멀쩡한 자료가 사라지고, 되돌아온 것은 본문을 다시 받아야 한다."""
    conn = _DB()
    빠진목록 = _코퍼스(conn, 빠질것=["R0001"])
    전체목록 = {**빠진목록, "R0001": {}}

    _돈다(conn, 빠진목록)
    assert _본문수(conn) == _모집단, "첫 누락에서 지웠다"

    _돈다(conn, 전체목록)                     # 다음 날 되돌아왔다
    assert _본문수(conn) == _모집단
    assert conn.execute("SELECT COUNT(*) FROM 정리후보").fetchone()[0] == 0, \
        "돌아온 것이 원장에 남으면 언젠가 연속으로 세져 지워진다"

    _돈다(conn, 빠진목록)                     # 또 빠졌지만 연속이 아니다
    assert _본문수(conn) == _모집단


