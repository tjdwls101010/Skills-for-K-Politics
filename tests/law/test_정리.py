def test_같은_날_여러_번_돌아도_하루로_센다() -> None:
    """⚠️ **호출 횟수로 세면 가드가 통째로 우회된다.** 워크플로 재시도나 사람이 손으로
    한 번 더 돌린 것만으로 "연속 2일"이 채워지고, 삭제 뒤 A1 은 초록이라 아무도 모른다."""
