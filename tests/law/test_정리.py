class 철회원천:
    """`목록전량` 과 `본문하나` 만 있는 최소 스탠드.

    ⚠️ **`본문하나` 가 이 검사의 전부다.** 목록에서 빠졌다는 것과 원천이 거뒀다는 것을
    가르는 증거가 그것뿐이라, 목록만 보는 스탠드로는 이 명령이 무엇을 확인하는지
    검사가 구별하지 못한다.
    """

    def __init__(self, 키들, 본문있는것=()):
        self.키들 = list(키들)
        self.본문있는것 = set(본문있는것)
        self.물어본것 = []

    def 목록전량(self, 종류, **kw):
        return [{"판례일련번호": k} for k in self.키들], True

    def 본문하나(self, 종류, 식별값, **kw):
        self.물어본것.append(식별값)
        if 식별값 in self.본문있는것:
            return {"판례일련번호": 식별값}
        raise 원천.원천에없음(f"{종류}/본문: 없습니다")


