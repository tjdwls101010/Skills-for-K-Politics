def test_부분_수신이_복귀를_증명하면_연속이_끊긴다() -> None:
    """⚠️ **존재의 증거와 부재의 증거는 대칭이 아니다.** "목록에 있다"는 완결과 무관하게
    유효하지만 "목록에 없다"는 완결일 때만 유효하다. 이 비대칭을 놓치면
    `정상(누락) → 부분(존재) → 정상(누락)` 이 연속 2회로 세져 **복귀가 증명된 자료가
    지워진다.**"""
    conn = _DB()
    목록 = _코퍼스(conn, 빠질것=["R0001"])
    _돈다(conn, 목록)                                   # 없다 (완결)
    _돈다(conn, {**목록, "R0001": {}}, 완결=False)      # 있다 (부분)
    _돈다(conn, 목록)                                   # 다시 없다 (완결)
    assert _본문수(conn) == _모집단, "부분 수신의 복귀 증거가 무시됐다"


