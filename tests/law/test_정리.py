class 본문원천:
    """본문을 주거나 「없다」고 답하는 최소 스탠드. `수집루프` 가 쓰는 것만 갖췄다."""

    def __init__(self, 본문있는것=()):
        self.본문있는것 = set(본문있는것)
        self.물어본것 = []

    def 본문여럿(self, 종류, 대상):
        for k in 대상:
            self.물어본것.append(k)
            if k in self.본문있는것:
                yield k, {"행정규칙일련번호": k}, None
            else:
                yield k, None, 원천.원천에없음("없습니다")


