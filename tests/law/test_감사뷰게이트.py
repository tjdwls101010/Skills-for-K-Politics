"""`audit.py` 의 뷰 게이트(A24)와 그 상세(R26).

⚠️ **깨진 뷰는 조회할 때야 터진다.** `PRAGMA integrity_check` 도 통과하고 `sqlite_master`
   에도 멀쩡히 앉아 있다 — 뷰가 가리키는 컬럼이 사라져도 SQLite 는 아무 말을 안 한다.
   **실제로 조회해 보는 것 말고 확인할 방법이 없다.**

이 DB 의 뷰는 고정 조인을 대신 지는 인터페이스라 조용히 죽으면 그 조인이 통째로 손으로
돌아온다 — `조문판단` 이 없으면 "이 조를 다룬 판례"가 자료종류마다 다른 조인이 되고,
`조문판단수` 가 없으면 "한 번도 판단받지 않은 조문"이 `NOT IN` 으로 미끄러진다.
"""

from __future__ import annotations

import pytest

감사 = pytest.importorskip("law.audit")
스키마 = pytest.importorskip("law.schema")


_뷰 = ["위임대상조문", "조문판단", "조문판단수", "신선도"]


@pytest.fixture
def 채운(conn):
    """뷰 넷이 전부 **비지 않도록** 최소한을 넣는다 — 빈 것도 위반이기 때문이다."""
    conn.executemany(
        "INSERT INTO 법령 (법령ID,법령일련번호,법령명,법종구분,시행일자,수집일시)"
        " VALUES (?,?,?,?,'2020-01-01','2026-09-12 00:00:00')",
        [("L1", "100", "테스트법", "법률"), ("L2", "200", "테스트법 시행령", "대통령령")])
    conn.executemany(
        "INSERT INTO 조문 (법령ID,순서,조,가지,제목,전문) VALUES (?,0,1,0,'목적',?)",
        [("L1", "제1조 법"), ("L2", "제1조 영")])
    conn.execute(
        "INSERT INTO 위임 (법령ID,순서,조,가지,위임한자리,위임구분,대상제목,"
        "대상법령ID,대상조,대상가지,근거문구)"
        " VALUES ('L1',0,1,0,'제1조','시행령','테스트법 시행령','L2',1,0,'대통령령으로 정하는')")
    conn.execute(
        "INSERT INTO 판례 (판례ID,사건번호,법원명,선고일자,수집일시)"
        " VALUES ('P1','2024다1','대법원','2024-01-01','2026-09-12 00:00:00')")
    conn.execute(
        "INSERT INTO 의율조문 (자료종류,자료ID,출처,법령명원문,법령ID,부칙여부,조,가지,"
        "원문조각) VALUES ('판례','P1','참조조문','테스트법','L1',0,1,0,'조각')")
    return conn


def test_뷰가_다_차_있으면_초록이다(채운):
    전부, 난것 = 감사._깨진뷰상세(채운)
    assert 난것 == [] and 전부 == len(_뷰)


@pytest.mark.parametrize("뷰", _뷰)
def test_뷰_하나를_지우면_빨갛다(채운, 뷰):
    """**조회가 깨지는 것은 예외 없이 위반이다** — 비어도 되는 뷰까지 포함해서."""
    채운.execute(f"DROP VIEW {뷰}")
    assert 감사._깨진뷰(채운) >= 1
    assert any(x.startswith(뷰) for x in 감사._깨진뷰상세(채운)[1])


@pytest.mark.parametrize("뷰, 비우기", [
    ("위임대상조문", "DELETE FROM 위임"),
    ("조문판단", "DELETE FROM 의율조문"),
    ("조문판단수", "DELETE FROM 조문"),
])
def test_입력이_비어서_빈_뷰는_초록이다(채운, 뷰, 비우기):
    """⚠️ **흔한 날에 빨개지는 게이트는 곧 무시된다.** 표본 빌드와 첫 수집이 이 상태라,
    입력이 비어서 비는 것까지 세면 새 DB 의 첫 실행이 무조건 빨갛다."""
    채운.execute(비우기)
    assert 채운.execute(f'SELECT COUNT(*) FROM "{뷰}"').fetchone()[0] == 0
    assert not [x for x in 감사._깨진뷰상세(채운)[1] if x.startswith(뷰)]


def test_입력이_있는데_비면_빨갛다(채운):
    """필터가 전부를 걸러내는 상태가 실재하고, 그러면 "이 조를 다툰 판례가 없다"가
    조용히 0건이 된다. 입력이 있느냐가 그 둘을 가르는 유일한 근거다."""
    채운.execute("DROP VIEW 조문판단")
    채운.execute("CREATE VIEW 조문판단 AS SELECT 법령ID, 조 FROM 의율조문 WHERE 0")
    assert "조문판단(비었다)" in 감사._깨진뷰상세(채운)[1]


def test_신선도는_예외_목록에_없다(채운):
    """빈 DB 에서도 값이 NULL 인 한 행이라 비는 일이 구조적으로 없다 — 비었으면 진짜 결함이다."""
    assert "신선도" not in 감사.비어도되는뷰


def test_예외에는_이유와_입력_질의가_붙어_있다(채운):
    """이유 없는 예외는 다음 사람이 지울지 남길지 판단할 근거가 없고, 입력 질의가 없으면
    예외가 "언제나 비어도 된다"로 넓어진다."""
    assert set(감사.비어도되는뷰) <= set(_뷰)
    for 뷰, (이유, 입력) in 감사.비어도되는뷰.items():
        assert len(이유) > 5, 뷰
        채운.execute(입력)          # 질의가 실제로 도는가


def test_A24_가_뷰_검사를_들고_있다():
    """게이트 표에서 뷰 검사가 빠지면 위 함수들이 아무것도 안 지킨다."""
    항목 = {번호: sql for 번호, _, sql in 감사.게이트}
    assert 항목["A24"] is 감사._깨진뷰


def test_목록을_SCHEMA_에서_뽑는다():
    """⚠️ 손으로 적으면 뷰를 더한 날 그 뷰만 아무도 안 지킨다."""
    assert set(감사._뷰이름들(스키마.SCHEMA)) == set(_뷰)


def test_빨간_게이트마다_해석이_붙는다():
    """⚠️ **게이트 이름은 "무엇을 셌나"이지 "그래서 무슨 일이 났나"가 아니다.**
    해석을 지면에 적으면 게이트를 고친 날 지면만 낡는다."""
    번호들 = {번호 for 번호, _, _ in 감사.게이트}
    없는것 = set(감사._해석) - 번호들
    assert not 없는것, f"없는 게이트의 해석이 남아 있다: {sorted(없는것)}"
