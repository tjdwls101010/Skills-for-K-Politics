"""헌재가 자기 결정을 인용하는 형식.

명세 `08 §6` 은 판례 형식(`대법원 YYYY.M.D. 선고 N다N 판결`)만 규정했고 **헌재가 자기를
인용하는 형식은 없다.** 그래서 헌재 38,672건 중 인용판례가 있는 것이 508건(1%)뿐이었다.

    헌재 1997.  3. 27. 95헌가17, 판례집 9-1, 219, 232

두 가지가 다르다 — 법원명이 `헌재`(약칭)이고, `선고`·`자`·`고지` 같은 발령어가 없다.
"""

from __future__ import annotations

import pytest

참조파서 = pytest.importorskip("law.refparser")


def 인용들(행들):
    return [(r["피인용법원"], r["피인용선고일"], r["피인용사건번호"]) for r in 행들]


def test_헌재_자기인용을_읽는다() -> None:
    r = 참조파서.참조판례(
        "1. 헌재 1997.  3. 27. 95헌가17, 판례집 9-1, 219, 232"
        "헌재 1989. 12. 22. 88헌가13, 판례집 1, 357")
    assert 인용들(r) == [
        ("헌법재판소", "1997-03-27", "95헌가17"),
        ("헌법재판소", "1989-12-22", "88헌가13"),
    ]


def test_판례집_쪽수가_사건번호로_새지_않는다() -> None:
    """⚠️ `판례집 15-2하, 1, 7-10` 이 뒤에 붙는다. 사건번호 꼬리가 이걸 삼키면
    **존재하지 않는 사건번호**가 생긴다."""
    r = 참조파서.참조판례("헌재 2003. 10. 30. 2002헌가24, 판례집 15-2하, 1, 7-10")
    assert 인용들(r) == [("헌법재판소", "2003-10-30", "2002헌가24")]


def test_등이_붙어도_사건번호를_바르게_끊는다() -> None:
    r = 참조파서.참조판례("헌재 1997. 3. 27. 95헌가14등, 판례집 9-1, 193, 204")
    assert 인용들(r) == [("헌법재판소", "1997-03-27", "95헌가14")]


def test_법원명도_발령어도_없으면_읽지_않는다() -> None:
    """⚠️ 발령어를 그냥 선택으로 만들면 본문 속 아무 날짜+숫자 조합이 인용이 된다.
    **법원명이 있을 때만** 발령어를 생략할 수 있다."""
    assert 참조파서.참조판례("1997. 3. 27. 95헌가17 을 보면") == []


def test_날짜_없는_사건번호_나열은_읽지_않는다() -> None:
    """⚠️ `2000헌마252003헌마30` 은 `2000헌마25`+`2003헌마30` 인지
    `2000헌마2520`+`03헌마30` 인지 **가를 수 없다.** 실측 1,492건이 이 형태다.
    못 뽑는 쪽이 잘못 뽑는 쪽보다 낫다."""
    assert 참조파서.참조판례("2000헌마252003헌마302001헌마788") == []


def test_앞_인용의_판결이_법원명에_붙지_않는다() -> None:
    """⚠️ 실측 버그다 — `… 판결대법원 1998. …` 처럼 구분자가 없으면
    `[가-힣]{2,10}법원` 이 `판결대법원` 을 통째로 잡는다. 그러면 그 인용이
    대법원으로 집계되지 않는다(현 DB 에 `판결대법원` 501행 · `결정대법원` 8행)."""
    r = 참조파서.참조판례(
        "대법원 1997. 5. 9. 선고 96다2606 판결대법원 1998. 3. 13. 선고 97다45259 판결")
    assert 인용들(r) == [
        ("대법원", "1997-05-09", "96다2606"),
        ("대법원", "1998-03-13", "97다45259"),
    ]


def test_판례_형식은_그대로_읽는다() -> None:
    """헌재를 더하면서 기존 경로가 깨지지 않았는지."""
    r = 참조파서.참조판례("대법원 1972. 6. 27. 선고 72다700 판결, 1985.2.23자 83모37, 38 결정")
    assert 인용들(r) == [
        ("대법원", "1972-06-27", "72다700"),
        ("대법원", "1985-02-23", "83모37"),
        ("대법원", "1985-02-23", "83모38"),
    ]


def test_대법원_헌법재판소_앞에_붙은_것은_전부_앞_인용의_꼬리다() -> None:
    """`판결`·`결정` 만 지우면 꼬리가 남는다 — 실측에 `다대법원` 6행이 있었다.
    **단일 기관이라 접두가 있을 수 없다**는 규칙으로 일반화한다.
    `서울고등법원` 처럼 접두가 정상인 법원에는 적용하지 않는다."""
    r = 참조파서.참조판례("대법원 1997. 5. 9. 선고 96다2606 판결다대법원 1998. 3. 13. 선고 97다45259 판결")
    assert [x["피인용법원"] for x in r] == ["대법원", "대법원"]
    r2 = 참조파서.참조판례("서울고등법원 2020. 1. 1. 선고 2019나1 판결")
    assert [x["피인용법원"] for x in r2] == ["서울고등법원"]


def test_발령어가_붙은_하급심_법원명도_떼어낸다() -> None:
    """⚠️ 단일 기관 규칙만으로는 `판결서울고등법원`(실측 6행)이 안 잡힌다 —
    `서울고등법원` 은 접두가 정상인 법원이라 그 규칙을 못 쓴다. 발령어를 따로 뗀다."""
    r = 참조파서.참조판례(
        "대법원 2019. 1. 1. 선고 2018다1 판결서울고등법원 2020. 1. 1. 선고 2019나1 판결")
    assert [x["피인용법원"] for x in r] == ["대법원", "서울고등법원"]
