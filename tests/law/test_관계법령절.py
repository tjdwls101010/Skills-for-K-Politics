def test_열거_문법을_벗어나면_거기서_멈춘다() -> None:
    """⚠️ **이게 이 파일에서 가장 중요하다.** 절 끝 표지를 못 찾으면 산문이 딸려 오는데,
    산문에는 `같은 법 제5조` 처럼 **당사자 주장 속 조문**이 섞여 있다. 재결이 의율한
    조문과 당사자가 언급한 조문을 구별 못 하는 것이 §7 이 경계한 바로 그 오류다.
    열거 문법이 끊기는 자리에서 스캔을 멈춰 그걸 막는다."""
    r = 참조파서.관계법령절(
        "가. 관계법령\n먹는물관리법 제9조제1항 내지 제3항의 규정에 의하면, 먹는샘물제조업을 "
        "위하여 개발하고자 하는 자는 환경부장관의 허가를 받아야 하고, 같은 법 제36조제1항에 "
        "따라 청구인은 이를 위반하였다고 주장한다.")
    assert 주소들(r) == [
        ("먹는물관리법", 9, 0, 1, None),
        ("먹는물관리법", 9, 0, 2, None),
        ("먹는물관리법", 9, 0, 3, None),
    ], "산문 속 '같은 법 제36조' 가 딸려 들어왔다"


