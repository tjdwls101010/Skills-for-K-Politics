"""행정심판례 `이유` 의 `가. 관계법령` 절.

계획서 §7 은 **낫표 있는 것만** 뽑기로 했고 그 근거가 "재표본 12건 전부의 `이유` 에
낫표가 있다"였다. **전량에서는 틀렸다** — 의율조문이 0건인 재결 18,099건 중
17,061건(94%)에 낫표가 아예 없다. 0단계가 잡았던 헌재 표본 오류와 같은 형태다.

낫표 없이 본문을 뒤지면 거짓 양성이 폭증한다는 §7 의 판단은 **그대로 맞다.** 그래서
`가. 관계법령` 이라는 **라벨 안에서만** 맨 법령명을 허용한다. 그 절은 산문이 아니라
순수 열거다 — 중앙값 79자, 산문 신호가 든 것이 0.3%(실측 14,797절).

여기 있는 원문은 전부 DB 에서 그대로 꺼낸 것이고, 기대값은 손으로 읽어 적었다.
"""

from __future__ import annotations

import pytest

참조파서 = pytest.importorskip("법제처.참조파서")


def 주소들(행들):
    return [(r["법령명원문"], r["조"], r["가지"], r["항"], r["호"]) for r in 행들]


def test_구분자_없이_붙은_법령명이_경계가_된다() -> None:
    """⚠️ `제2항동법시행령` — **구분자가 없다.** 이 경계를 못 보면 뒤 법령이 통째로
    사라지거나 앞 법령의 조문으로 잘못 붙는다."""
    r = 참조파서.관계법령절("가. 관계법령\n고용보험법 제16조제2항동법시행령 제19조제1항동법시행규칙 제27조\n나. 판 단")
    assert 주소들(r) == [
        ("고용보험법", 16, 0, 2, None),
        ("고용보험법시행령", 19, 0, 1, None),
        ("고용보험법시행규칙", 27, 0, None, None),
    ]


def test_동법은_앞_법령의_본체를_물려받는다() -> None:
    """`동법시행령` 은 대용 표현이 아니라 **기계적 참조**다 — 절의 58.1%에 나온다.
    앞이 이미 `…시행령` 이면 본체(`…법`)로 되돌린 뒤 붙인다."""
    r = 참조파서.관계법령절(
        "가. 관계법령\n행정심판법 제2조 및 제3조국유재산법 제24조, 제25조, 제28조, 제28조의2동법시행령 제27조\n나. 판단")
    assert 주소들(r) == [
        ("행정심판법", 2, 0, None, None),
        ("행정심판법", 3, 0, None, None),
        ("국유재산법", 24, 0, None, None),
        ("국유재산법", 25, 0, None, None),
        ("국유재산법", 28, 0, None, None),
        ("국유재산법", 28, 2, None, None),
        ("국유재산법시행령", 27, 0, None, None),
    ]


def test_별표는_행이_아니고_상속을_끊는다() -> None:
    """⚠️ `별표 6` 은 조문이 아니다(M13). 그리고 **별표 뒤의 항·호를 앞 조에 물리면
    거짓이 된다** — `[별표3] 제1호사목` 의 제1호는 별표3의 것이지 앞 조의 것이 아니다."""
    r = 참조파서.관계법령절(
        "가. 관계법령\n건설산업기본법 제29조제2항 및 제82조제2항동법시행령 제80조제1항·제2항 및 별표 6\n나. 판 단")
    assert 주소들(r) == [
        ("건설산업기본법", 29, 0, 2, None),
        ("건설산업기본법", 82, 0, 2, None),
        ("건설산업기본법시행령", 80, 0, 1, None),
        ("건설산업기본법시행령", 80, 0, 2, None),
    ]

    r2 = 참조파서.관계법령절(
        "가. 관계법령\n어떤규칙 제2조, 제3조제1항제3호, 제2항, 제4항 및 [별표3] 제1호사목\n나. 판단")
    assert ("어떤규칙", 3, 0, None, 1) not in 주소들(r2), "별표의 제1호가 앞 조에 붙었다"


