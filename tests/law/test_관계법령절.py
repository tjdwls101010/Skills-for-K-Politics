def test_괄호_속_날짜가_절_끝_판정을_깨지_않는다() -> None:
    """⚠️ `구 건설기술관리법(1995. 1. 5. 법률 제N호로 개정되기 전의 것)` 안의 `5. 법률` 이
    항목 표지처럼 보인다. 괄호를 먼저 떼지 않으면 절이 거기서 잘려 뒤 법령이 사라진다."""
    r = 참조파서.관계법령절(
        "가. 관계법령\n구 건설기술관리법(1995. 1. 5. 법률 제4920호로 개정되기 전의 것) "
        "제28조동법시행령 제3조\n나. 판 단")
    assert 주소들(r) == [
        ("구 건설기술관리법", 28, 0, None, None),
        ("구 건설기술관리법시행령", 3, 0, None, None),
    ]


