def test_본문낫표가_낫표와_관계법령절을_함께_준다() -> None:
    """`_출처` 는 행정심판례에 `본문낫표` 하나를 걸어 둔다. 두 경로가 거기서 합쳐진다."""
    글 = ("「행정심판법」 제5조에 따라 살피건대 …\n"
          "가. 관계법령\n고용보험법 제16조제2항\n나. 판 단")
    assert ("행정심판법", 5, 0, None, None) in 주소들(참조파서.본문낫표(글))
    assert ("고용보험법", 16, 0, 2, None) in 주소들(참조파서.본문낫표(글))
