class Test수집루프:
    def test_이미_있는_것은_다시_받지_않는다(self, conn):
        저장.저장(conn, "판례", {"판례일련번호": "1", "사건번호": "x"})
        받은 = []

        class 가짜:
            워커 = 1

            def 본문여럿(self, 종류, 대상):
                받은.extend(대상)
                for v in 대상:
                    yield v, {"사건번호": "y"}, None

        루프.수집루프(conn, 가짜(), "판례", {"1": {}, "2": {"판례일련번호": "2"}},
                     lambda 몸통, 행: ({"판례일련번호": "2", "사건번호": "y"}, None),
                     로그=lambda *_: None)
        assert 받은 == ["2"]

    def test_없음으로_확정된_것도_건너뛴다(self, conn):
        """⚠️ 재시도하면 매일 수만 건을 헛되이 두드린다."""
        저장.record_failure(conn, "판례", "1", "없음", "일치하는 판례가 없습니다")
        받은 = []

        class 가짜:
            def 본문여럿(self, 종류, 대상):
                받은.extend(대상)
                return iter(())

        루프.수집루프(conn, 가짜(), "판례", {"1": {}}, None, 로그=lambda *_: None)
        assert 받은 == []
