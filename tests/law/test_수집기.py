class Test수집루프:
    def test_이미_있는_것은_다시_받지_않는다(self, conn):
        저장.저장(conn, "판례", {"판례ID": "1", "사건번호": "x"})
        받은 = []

        class 가짜:
            워커 = 1

            def 본문여럿(self, 종류, 대상):
                받은.extend(대상)
                for v in 대상:
                    yield v, {"사건번호": "y"}, None

        루프.수집루프(conn, 가짜(), "판례", {"1": {}, "2": {"판례일련번호": "2"}},
                     lambda 몸통, 행: ({"판례ID": "2", "사건번호": "y"}, None),
                     로그=lambda *_: None)
        assert 받은 == ["2"]

    def test_없음으로_확정된_것도_건너뛴다(self, conn):
        """⚠️ 재시도하면 매일 수만 건을 헛되이 두드린다."""
        저장.record_failure(conn, "판례", "1", "없음", "일치하는 판례가 없습니다")
        받은 = []

        class 가짜:
            def 본문여럿(self, 종류, 대상):
                받은.extend(대상)
                return iter(())

        루프.수집루프(conn, 가짜(), "판례", {"1": {}}, None, 로그=lambda *_: None)
        assert 받은 == []

    @pytest.mark.parametrize("실패종류", ["없음", "본문없음", "철회"])
    def test_본문이_없다고_확정된_것은_건너뛴다(self, conn, 실패종류):
        """⚠️ 셋 다 "원천이 본문을 안 준다"의 기록이라 다시 물어도 같은 답이 온다.
        재시도하면 매일 수만 건을 헛되이 두드린다. '철회'만은 목록에 돌아오면 다시 묻는다 —
        그건 목록이 답을 바꿨다는 증거이기 때문이고, 아래 테스트가 그 예외를 잠근다."""
        저장.record_failure(conn, "판례", "1", 실패종류, "…")
        받은 = []

        class 가짜:
            def 본문여럿(self, 종류, 대상):
                받은.extend(대상)
                return iter(())

        루프.수집루프(conn, 가짜(), "판례", {}, None, 로그=lambda *_: None)
        assert 받은 == []

    def test_파서가_본문없음을_올리면_적재_대신_표지를_남긴다(self, conn):
        class 가짜:
            def 본문여럿(self, 종류, 대상):
                for v in 대상:
                    yield v, {}, None

        def 파싱(몸통, 행):
            raise 루프.본문없음("전문·판시사항·결정요지가 모두 비었다")

        수치 = 루프.수집루프(conn, 가짜(), "헌재결정례", {"1": {}}, 파싱, 로그=lambda *_: None)
        assert 수치["본문"] == 0 and 수치["없음"] == 1
        assert conn.execute("SELECT COUNT(*) FROM 헌재결정례").fetchone()[0] == 0
        assert conn.execute(
            "SELECT 실패종류 FROM 수집실패 WHERE 자료ID='1'").fetchone()[0] == "본문없음"

    def test_철회는_목록에_돌아오면_다시_묻는다(self, conn):
        """본문 API 의 답이 바뀌었는지는 물어봐야 알고, 성공했을 때만 `저장()` 이 표지를
        지운다 — 목록 복귀만으로 걷으면 본문 없는 자료가 정상으로 되돌아온다."""
        저장.record_failure(conn, "판례", "1", "철회", "본문 API 가 부재로 답했다")
        받은 = []

        class 가짜:
            def 본문여럿(self, 종류, 대상):
                받은.extend(대상)
                for v in 대상:
                    yield v, {"사건번호": "y"}, None

        루프.수집루프(conn, 가짜(), "판례", {"1": {}},
                     lambda m, r: ({"판례ID": "1", "사건번호": "y"}, None),
                     로그=lambda *_: None)
        assert 받은 == ["1"]
        assert 저장.철회된것(conn, "판례") == set()

    def test_철회_재수신이_실패하면_표지가_남는다(self, conn):
        """⚠️ '철회'를 '재시도'로 덮으면 그 자료가 "원천이 거둬들였다"는 사실을 잃고,
        적재 등식의 우변에서도 빠져 **본문 없는 행 하나가 영구히 어긋난다.**"""
        저장.record_failure(conn, "판례", "1", "철회", "본문 API 가 부재로 답했다")

        class 가짜:
            def 본문여럿(self, 종류, 대상):
                for v in 대상:
                    yield v, None, RuntimeError("타임아웃")

        루프.수집루프(conn, 가짜(), "판례", {"1": {}}, None, 로그=lambda *_: None)
        assert 저장.철회된것(conn, "판례") == {"1"}
