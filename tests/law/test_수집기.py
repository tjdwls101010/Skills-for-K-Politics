class Test적재기가_만든_키는_전부_실제_컬럼이다:
    """⚠️ **`적재._삽입()` 은 모르는 키를 조용히 버린다.** 원천이 필드를 더 주는 일이
    잦아서 그렇게 만들어 뒀는데, 그 관용이 **우리 실수도 함께 삼킨다** — 컬럼을 지우고
    적재기의 매핑을 안 지우면 에러 없이 그냥 안 들어간다. 오타도 마찬가지다.

    본문파싱들이 만드는 dict 는 손으로 적은 것이라 **전부 실제 컬럼이어야 한다.**
    """

    @pytest.mark.parametrize(
        "종류, 파싱, 몸통, 목록행",
        [("판례", lambda m, l: 판례.본문파싱(m, l), {}, {"판례일련번호": "1"}),
         ("헌재결정례", lambda m, l: 결정례.헌재파싱(m, l), {"전문": "…"},
          {"헌재결정례일련번호": "1"}),
         ("법령해석례", lambda m, l: 결정례.해석례파싱(m, l), {}, {"법령해석례일련번호": "1"})],
    )
    def test_본문파싱(self, conn, 종류, 파싱, 몸통, 목록행):
        행, _ = 파싱(몸통, 목록행)
        테이블 = 저장.본문테이블[종류][0]
        assert set(행) <= set(저장.컬럼들(conn, 테이블)), \
            f"{테이블} 에 없는 키: {sorted(set(행) - set(저장.컬럼들(conn, 테이블)))}"

    def test_법령은_자식까지(self, conn):
        행, 자식 = 법령.본문파싱(
            {"기본정보": {"법령명_한글": "x", "법령ID": "1"},
             "조문": {"조문단위": [{"조문키": "0001001", "조문번호": "1",
                                "조문여부": "조문", "조문내용": "제1조"}]}},
            {"법령일련번호": "1", "법령ID": "1",
             "시행예정일련번호": None, "시행예정일": None},
        )
        assert set(행) <= set(저장.컬럼들(conn, "법령"))
        for 테이블, 행들 in 자식.items():
            여분 = {k for r in 행들 for k in r} - set(저장.컬럼들(conn, 테이블))
            assert not 여분, f"{테이블} 에 없는 키: {sorted(여분)}"


