"""`신선도` 뷰 — "이 답은 언제 기준인가"가 한 질의로 끝난다.

컬럼은 국회 쪽과 같다. 스킬이 두 DB 에 같은 질의를 주입하므로 모양이 갈리면 주입 줄도 갈린다.
빈 DB 에서도 한 행이어야 하는 이유는 `tests/congress/test_신선도.py` 에 적혀 있다.
"""


def 신선도(conn):
    행들 = conn.execute("SELECT * FROM 신선도").fetchall()
    assert len(행들) == 1, f"{len(행들)}행이다 — 신선도는 항상 한 행이다"
    return 행들[0]


def _수집상태(conn, 자료종류, 단계, 상태, 건수=None, 상세=None, 갱신일시="2026-09-12 08:21:44"):
    conn.execute(
        "INSERT INTO 수집상태 (자료종류,단계,상태,건수,상세,갱신일시,상태시작일시)"
        " VALUES (?,?,?,?,?,?,?)",
        (자료종류, 단계, 상태, 건수, 상세, 갱신일시, 갱신일시),
    )


def test_빈_DB_에서도_한_행이고_값은_전부_NULL(conn):
    행 = 신선도(conn)
    assert tuple(행) == (None, None, None, None, None)


def test_통과한_감사는_감사통과_1_이고_상세가_없다(conn):
    _수집상태(conn, "전체", "수집", "완료", 갱신일시="2026-09-12 08:21:44")
    _수집상태(conn, "전체", "감사", "완료", 건수=0, 갱신일시="2026-09-12 08:25:10")
    행 = 신선도(conn)
    assert 행["적재기준시각"] == "2026-09-12 08:21:44"
    assert 행["감사통과"] == 1
    assert 행["감사시각"] == "2026-09-12 08:25:10"
    assert 행["감사상세"] is None


def test_위반이_남은_감사는_감사통과_0_과_게이트_이름을_준다(conn):
    """상세는 게이트 번호가 아니라 이름이다 — `.schema` 만 읽는 조회자가 'A1=3' 을 못 푼다."""
    _수집상태(conn, "전체", "감사", "완료", 건수=3,
             상세="적재 건수가 목록과 안 맞는 자료종류=1 · 재시도 실패 잔존=2",
             갱신일시="2026-09-11 08:25:10")
    행 = 신선도(conn)
    assert 행["감사통과"] == 0
    assert 행["감사상세"] == "적재 건수가 목록과 안 맞는 자료종류=1 · 재시도 실패 잔존=2"


def test_감사가_완료가_아니면_감사통과_0_이다(conn):
    """건수 NULL 은 "위반 0" 이 아니라 "재지 못했다" 다 — 통과로 읽으면 안 돈 감사를 통과로 본다."""
    _수집상태(conn, "전체", "감사", "부분")
    assert 신선도(conn)["감사통과"] == 0


def test_건너뛴_정리가_있으면_경고가_그_자료종류를_말한다(conn):
    _수집상태(conn, "판례", "정리", "건너뜀")
    경고 = 신선도(conn)["경고"]
    assert "판례" in 경고
    assert "사라진 자료가 남아 있을 수 있다" in 경고


def test_정리를_다_한_실행에는_경고가_없다(conn):
    _수집상태(conn, "판례", "정리", "완료", 건수=0)
    assert 신선도(conn)["경고"] is None
