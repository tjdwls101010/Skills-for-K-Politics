class Test형식과_전원합의체:
    """원천 `판결유형` 한 문자열을 두 값으로 가른다. **선고 컬럼을 대신한 것이다** —
    실측 선고 6종(`선고` 84,681 · `자` 4,430 · `선고,` 246 …)은 전부 형식에서 유도되고,
    `= '선고'` 가 250건을 에러 없이 놓치던 자리였다.

    ⚠️ **전원합의체는 이 문자열에서만 건질 수 있다.** 실측 812건 중 **559건은 판례내용
    본문에 그 말이 없어**, 컬럼을 안 만들면 판례 변경의 표지가 통째로 사라진다.
    """

    @pytest.mark.parametrize("판결유형, 기대", [
        ("판결", ("판결", 0)),
        ("전원합의체판결", ("판결", 1)),
        ("결정", ("결정", 0)),
        ("전원합의체결정", ("결정", 1)),
        ("명령", ("명령", 0)),
        ("심판", ("심판", 0)),
        ("", (None, 0)),
        (None, (None, 0)),
        ("알 수 없는 표기", (None, 0)),
    ])
    def test_한_문자열에서_둘을_낸다(self, 판결유형, 기대):
        assert 정규화.형식과전원합의체(판결유형) == 기대

    def test_결정을_판결보다_먼저_본다(self):
        """순서를 뒤집으면 `'재판'` 같은 표기가 '판결'에 먼저 걸린다."""
        assert 정규화.형식과전원합의체("전원합의체결정")[0] == "결정"

    def test_분류하지_못한_표기는_판결로_몰지_않는다(self):
        """실측 11건. 억지로 '판결'에 몰면 그만큼이 거짓이 되고, NULL 은 보고값이 센다."""
        assert 정규화.형식과전원합의체("기타")[0] is None

    def test_멱등이다(self):
        """⚠️ 변환 스크립트가 같은 규칙을 다시 먹인다 — 두 번째가 값을 바꾸면
        재실행마다 값이 달라진다."""
        형식, 전합 = 정규화.형식과전원합의체("전원합의체판결")
        assert 정규화.형식과전원합의체(형식) == (형식, 0)
        assert 전합 == 1
