"""`refparser.py` — `08-참조-파서-명세.md` §8 의 경계 사례 전부.

**여기 있는 입력은 전부 실제 응답에서 뽑은 것이다.** 지어낸 것이 없다.

원칙 하나: **못 뽑은 것보다 잘못 뽑은 것이 훨씬 나쁘다.** 그래서 "몇 행이 나오나"보다
"틀린 행이 없나"를 먼저 본다.
"""

import pytest

from law import refparser as 참조파서


def 주소(행):
    return (행["법령명원문"], 행["조"], 행["가지"], 행["항"], 행["호"], 행["목"])


class Test조문주소:
    @pytest.mark.parametrize(
        "원문, 기대",
        [
            ("민법 제15조", (15, 0, None, None, None)),
            ("민법 제18조의2", (18, 2, None, None, None)),
            ("민법 제15조 제1항", (15, 0, 1, None, None)),
            ("민법 제15조 제1항 제4호", (15, 0, 1, 4, None)),
            ("민법 제55조의8 제3항", (55, 8, 3, None, None)),
            ("민법 제15조제1항제4호", (15, 0, 1, 4, None)),      # 공백 없이 붙는다
            ("헌법 제 10조", (10, 0, None, None, None)),          # '제' 뒤 공백
            ("헌법 제200조의 2", (200, 2, None, None, None)),     # '의' 뒤 공백
            ("민법 제2조 제1호 (나)목", (2, 0, None, 1, "나")),   # 괄호 친 목
            ("민법 제2조 제1호 가목", (2, 0, None, 1, "가")),
        ],
    )
    def test_표기_변형을_모두_받는다(self, 원문, 기대):
        행 = 참조파서.참조조문(원문)
        assert len(행) == 1
        assert (행[0]["조"], 행[0]["가지"], 행[0]["항"], 행[0]["호"], 행[0]["목"]) == 기대

    def test_호가지번호(self):
        (행,) = 참조파서.참조조문("민법 제3조 제1항 제1호의2")
        assert (행["호"], 행["호가지"]) == (1, 2)


