class Test적재전_검증이_찾은_것:
    """전량 수집이 파싱 단계에 닿기 전에 표본으로 미리 돌려 잡은 것."""

    def test_낫표_안의_괄호도_뗀다(self):
        """⚠️ 참조조문 경로는 정규화에서 괄호를 떼지만 안건명은 괄호가 구조의 일부라
        통째로 못 뗀다. **법령명 자리에서만** 떼야 개정 연혁이 법령명이 되지 않는다."""
        행 = 참조파서.안건명(
            "「건설기술관리법(2004. 12. 31. 법률 제7305호로 개정되어 2005. 7. 1. 시행되기 이전의 것)」 제33조제1항제5호"
        )
        assert [주소(r) for r in 행] == [("건설기술관리법", 33, 0, 1, 5, None)]

    def test_한_문서가_같은_조문을_여러_번_말해도_한_행이다(self):
        """⚠️ 한 참조 문자열이 같은 조를 여러 번 언급하면 그대로 담길 때 그 판단이
        "여러 번 다퉜다"로 세어져 집계가 부푼다."""
        원문 = "「민법」 제750조에 따르면 … 「민법」 제750조는 … 「민법」 제750조의 취지는"
        assert len(참조파서.안건명(원문)) == 3
        assert len(참조파서._중복제거(참조파서.안건명(원문))) == 1

    def test_중복제거가_다른_주소는_남긴다(self):
        원문 = "「민법」 제750조 … 「민법」 제751조 … 「민법」 제750조"
        남은 = 참조파서._중복제거(참조파서.안건명(원문))
        assert [r["조"] for r in 남은] == [750, 751]


