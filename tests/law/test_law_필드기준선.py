"""법제처 원천의 **필드 집합**과 **조문 표본** — 국회 쪽과 같은 축이다.

⚠️ 국회는 회의 종류마다 구조가 갈렸지만(`class_id` 2·3·4·5), 법제처의 조문 JSON 은
법률·대통령령이 **같은 키를 준다**(실측 2026-08-28: 개인정보 보호법 · 상법 ·
개인정보 보호법 시행령 셋의 조문단위 키가 완전히 동일). 그래도 표본을 하나로 두면
원천이 **한 법종만** 바꾸는 날을 못 본다 — 그리고 리터럴로 박아 두는 한 다음에 또 몰린다.
"""

import pytest

from 법제처 import 검증


class Test조문표본이_데이터다:
    def test_법종이_섞여_있다(self):
        """법률만 보면 시행령·시행규칙 쪽 변화를 못 본다."""
        assert len({법종 for _, _, 법종, _ in 검증.조문표본}) >= 2

    def test_첫_표본이_기존_것이다(self):
        """V5·V5b·V6 의 기준값이 `01-원천-실측.md` 와 이어져 있다."""
        assert 검증.조문표본[0][0] == "270351"

    def test_표본마다_근거가_붙어_있다(self):
        assert all(설명.strip() for _, _, _, 설명 in 검증.조문표본)


def _잼(항상=(), 가끔=()):
    return {"항상": sorted(항상), "가끔": sorted(가끔)}


class Test필드대조:
    기준 = {"법령 목록": _잼(["법령ID", "법령명한글"], ["법령약칭명"]),
            "판례 목록": _잼(["판례일련번호"])}

    def test_그대로면_아무것도_안_난다(self):
        사라짐, 새것 = 검증.필드대조(self.기준, {"법령 목록": _잼(["법령명한글", "법령ID"], ["법령약칭명"])})
        assert 사라짐 == {} and 새것 == {}

    def test_사라진_필드를_짚는다(self):
        사라짐, _ = 검증.필드대조(self.기준, {"법령 목록": _잼(["법령ID"])})
        assert 사라짐 == {"법령 목록": ["법령명한글"]}

    def test_희소_필드가_이번_표본에_안_와도_안_잡는다(self):
        """⚠️ **원천은 NULL 필드를 행에서 뺀다.** 기준선 뜨던 날 표본에만 있던
        `법령약칭명` 이 오늘 표본에 없다고 빨개지면, 원천이 그대로인데 그날 수집이
        통째로 건너뛰어진다(`law-collect.yml`)."""
        사라짐, _ = 검증.필드대조(self.기준, {"법령 목록": _잼(["법령ID", "법령명한글"])})
        assert 사라짐 == {}

    def test_새_필드도_짚는다(self):
        _, 새것 = 검증.필드대조(self.기준, {"법령 목록": _잼(["법령ID", "법령명한글"], ["AI요약"])})
        assert 새것 == {"법령 목록": ["AI요약"]}

    def test_이번에_안_잰_것은_비교하지_않는다(self):
        """⚠️ **안 잰 것과 사라진 것은 다르다.**"""
        사라짐, 새것 = 검증.필드대조(self.기준, {"법령 목록": _잼(["법령ID", "법령명한글"], ["법령약칭명"])})
        assert 사라짐 == {} and 새것 == {}


class Test필드모음:
    def test_항상과_가끔을_가른다(self):
        assert 검증.필드모음([{"A": 1}, {"A": 2, "B": 3}]) == {"항상": ["A"], "가끔": ["B"]}

    def test_한_행뿐이면_전부_항상이_아니다(self):
        """⚠️ 표본 1행에서 '전 행에 있다'는 아무것도 뜻하지 않는다."""
        assert 검증.필드모음([{"A": 1}]) == {"항상": [], "가끔": ["A"]}

    def test_빈_응답은_아예_안_잰다(self):
        """⚠️ 0행을 '필드가 전부 사라졌다'로 읽으면 같은 사고를 두 번 세게 된다."""
        assert 검증.필드모음([]) is None


class Test기준선파일:
    def test_레포에_담겨_있고_정렬돼_있다(self):
        기준 = 검증.필드기준선()
        assert 기준, "원천필드.json 이 비었다"
        assert all(set(v) == {"항상", "가끔"} for v in 기준.values())
        assert all(칸 == sorted(칸) for v in 기준.values() for 칸 in v.values())

    def test_조문_속_항호목까지_잰다(self):
        """⚠️ **최상위 키만 재면 본문이 통째로 빠져도 초록이다.** 실제 검색·열람의 단위인
        `전문` 은 `항내용`·`호내용`·`목내용` 을 이어 붙여 만든다 — 원천이 `항내용` 만
        없애고 `항` 배열과 호를 남기면 조문단위 키 집합도, 항 보유 조 수도, 제목뿐 비율도
        전부 그대로라 V22·V23 이 아무 말도 안 한다. 그러면 검색 본문이 조용히 사라진다."""
        있는것 = set(검증.필드기준선())
        for 칸 in ("법령 조문 항", "법령 조문 호", "법령 조문 목"):
            assert 칸 in 있는것, f"{칸} 을 기준선에 안 담았다 — 본문 손실이 안 보인다"

    def test_파일이_없으면_빈_기준선이다(self, tmp_path, monkeypatch):
        monkeypatch.setattr(검증, "필드기준선경로", tmp_path / "없다.json")
        assert 검증.필드기준선() == {}
