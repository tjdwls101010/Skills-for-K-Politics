     --   직렬화 규칙: 안쪽 리스트는 원소를 그대로 이어 붙이고, 바깥 리스트는 개행으로 잇는다.
     --   str(list) 를 그대로 넣지 마라 — "[['[별표 1] …'], …]" 가 검색에 걸린다
  파일링크     TEXT, PDF링크 TEXT,  -- 상대경로다('/LSW/flDownload.do?flSeq=…'). 도메인을 붙여야 열린다
  PRIMARY KEY (행정규칙일련번호, 별표키)
);

CREATE TABLE IF NOT EXISTS 의율조문 (
  -- 판단(판례·헌재·행정심판·해석례) 하나가 어느 조문을 가리켰는가. 한 참조가 한 행이다.
  -- 원천은 이걸 자연어에 가까운 문자열로만 준다. 파싱 규칙은 08-참조-파서-명세.md 에 있다.
  --
  -- ⚠ 네 자료를 한 테이블에 담는다. '이 조문에 대한 모든 판단'이 지배적 질문이라
  --   나누면 그게 매번 4-way UNION 이 되고 한 갈래를 빠뜨려도 에러가 안 난다.
  --   FK 를 걸 수 없는 대가를 치른다 → audit 이 고아 행을 센다
  --
  -- ⚠ **안정 식별자가 없는 것이 의도다.** 재파싱마다 행이 통째로 다시 만들어지므로
  --   어떤 대리키도 실행마다 값이 바뀐다. 그런 키를 두면 밖에서 그걸 붙들게 되고,
  --   붙든 값이 조용히 다른 행을 가리킨다
  자료종류     TEXT NOT NULL,     -- '판례'|'헌재결정례'|'행정심판례'|'법령해석례'
  자료ID       TEXT NOT NULL,     -- 각 테이블의 일련번호
  출처필드     TEXT NOT NULL,     -- '참조조문'|'심판대상조문'|'안건명'|'이유' — 어디서 뽑았나
  쟁점번호     INTEGER,
     -- 참조조문의 '[1] [2] [3]' 이다. 판시사항의 쟁점 번호와 대응한다.
     -- ⚠ 단순 목록이 아니라 '쟁점 2번에 대해 이 조문들을 의율했다'는 구조다.
     --   무시하고 평평하게 담으면 '함께 다퉈진 조문'이 거짓으로 넓어진다. 없으면 NULL
  법령명원문   TEXT NOT NULL,     -- 파싱된 그대로. '자본시장과 금융투자업에 관한 법률'
  법령ID       TEXT,
     -- 법령명원문을 법령 테이블에 맞춰 본 결과. ⚠ 실패하면 NULL 이다.
     --   구법('구 민법')·약칭·폐지법은 못 맞춘다. NULL 을 '그런 법이 없다'로 읽지 마라
  부칙여부     INTEGER NOT NULL DEFAULT 0,
     -- ⚠ 1 이면 부칙의 조문이다. 부칙 제7조와 본칙 제7조는 전혀 다른 조문인데
     --   조 번호만 담으면 하나로 합쳐진다. 실측: 해석례 안건명에
     --   '「진실ㆍ화해를 위한 과거사정리 기본법」 부칙 제7조제1항' 이 있고,
     --   판례 참조조문 159건 표본 중 6건(4%)이 부칙 조문을 가리킨다.
     --   ⚠ 부칙 테이블에는 조 단위 행이 없다 → 부칙여부=1 인 행은 A7(조문 존재 확인) 대상이 아니다
  조           INTEGER,           -- 조 단위까지만 뽑힌 참조가 흔하다. 항·호가 NULL 인 것이 정상
  가지         INTEGER DEFAULT 0,
  항           INTEGER,
  호           INTEGER,
  호가지       INTEGER DEFAULT 0, -- 제1호의2. 조문요소.호가지번호 와 조인하려면 필요하다
  목           TEXT,
  원문조각     TEXT NOT NULL      -- 이 행을 만든 입력 문자열. 파서 개선 시 재현용
);
CREATE INDEX IF NOT EXISTS idx_의율_조문 ON 의율조문(법령ID, 조, 가지, 항, 호);
CREATE INDEX IF NOT EXISTS idx_의율_자료 ON 의율조문(자료종류, 자료ID);
CREATE INDEX IF NOT EXISTS idx_의율_명   ON 의율조문(법령명원문);

CREATE TABLE IF NOT EXISTS 인용판례 (
  -- 선례 인용 그래프. 판례의 참조판례, 헌재의 참조판례에서 나온다.
  -- ⚠ 의율조문과 같은 이유로 대리키를 두지 않는다(위 주석 참조).
  자료종류     TEXT NOT NULL,     -- '판례'|'헌재결정례'
  자료ID       TEXT NOT NULL,     -- 인용한 쪽
  쟁점번호     INTEGER,
  피인용법원   TEXT,              -- '대법원' '헌법재판소'
  피인용선고일 TEXT,              -- '2022. 10. 14.' → 'YYYY-MM-DD' 로 정규화
  피인용사건번호 TEXT NOT NULL,   -- '2018다244488'
  피인용자료ID TEXT,
     -- 사건번호로 판례 테이블을 맞춰 본 결과. ⚠ 실패하면 NULL.
     --   적재 범위 밖(대법원 출처 아님)이거나 원천에 없는 선례가 있다
  원문조각     TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_인용_피인용 ON 인용판례(피인용사건번호);
CREATE INDEX IF NOT EXISTS idx_인용_자료   ON 인용판례(자료종류, 자료ID);

CREATE TABLE IF NOT EXISTS 수집상태 (
  -- 어디까지 받았나. DB 자체가 자기 진행 상태를 안다(D19).
  -- 별도 체크포인트 파일을 두면 DB 와 어긋나는 세 번째 상태가 생기고, 어긋났을 때 어느 쪽이 맞는지 아무도 모른다
  자료종류     TEXT NOT NULL,
