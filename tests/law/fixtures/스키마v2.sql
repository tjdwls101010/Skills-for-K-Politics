CREATE TABLE IF NOT EXISTS 법령 (
  -- 한 법령의 '버전' 하나가 한 행이다. 개인정보 보호법은 현행 1 + 시행예정 2 = 3행이다.
  법령일련번호 TEXT PRIMARY KEY,  -- 원천 MST. 개정마다 새로 발급된다. 본문 조회 키가 이것이다
  법령ID       TEXT NOT NULL,     -- 법 자체의 식별자. 개정돼도 안 바뀐다. 판례의 참조를 잇는 쪽은 이쪽
  법령명       TEXT NOT NULL,
  법령약칭     TEXT,              -- 없으면 빈 문자열로 온다. 있는 법이 소수다
  법종구분     TEXT NOT NULL,     -- '법률' '대통령령' '국토교통부령' … 실측 42종
     -- ⚠ 코드(`법종구분코드`)는 담지 않는다. 42종:43코드로 1:1 이 아니라 조인이 조용히
     --   틀리고, 이 표는 매일 원천에서 다시 만들어져 정규화의 근거인 갱신 이상이 없다(D28)
  소관부처     TEXT,
  소관부처코드 TEXT,              -- law&org= 필터에 쓰는 값. 개인정보보호위원회=1790365
     -- ⚠ 한 부처 이름에 코드가 둘인 일이 있다(행정안전부 = 1311000 3건 + 1741000 483건).
     --   이름으로 세면 맞고 코드로 세면 갈린다
  공포일자     TEXT,              -- 'YYYY-MM-DD'. ⚠ 아래 시행일자 주석을 봐라
  공포번호     TEXT,              -- 앞자리 0 이 유효하다('02358'). 정수로 바꾸지 마라
  시행일자     TEXT,
     -- ⚠ **저장 형식이 'YYYY-MM-DD' 다. 'YYYYMMDD' 로 조건을 걸면 0건이 나온다** —
     --   `시행일자 >= '20200101'` 은 `'2020-04-16' < '20200101'` 이라 전 행 거짓이고,
     --   0건은 "그런 법이 없다"로 읽힌다. 이 DB 의 모든 날짜 컬럼이 같은 형식이다.
     -- ⚠ 만료 없음을 '9999-01-01' 로 주는 행이 있다. 최댓값을 실제 시행일로 읽지 마라
  제개정구분   TEXT,              -- '제정' '일부개정' '전부개정' '타법개정'
  현행연혁코드 TEXT NOT NULL,     -- '현행' | '시행예정'. 연혁은 담지 않는다(D3)
                                  -- ⚠ 이 컬럼을 안 걸면 아직 시행 안 된 조문을 현행으로 답한다
  개정문       TEXT,
  제개정이유   TEXT,              -- 입법 취지를 원문으로 주는 유일한 필드. 대개 짧다(수백 자)
  수집일시     TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_법령_법령ID   ON 법령(법령ID, 현행연혁코드);
CREATE INDEX IF NOT EXISTS idx_법령_명       ON 법령(법령명);
CREATE INDEX IF NOT EXISTS idx_법령_부처     ON 법령(소관부처코드);
CREATE INDEX IF NOT EXISTS idx_법령_시행일   ON 법령(시행일자);

CREATE TABLE IF NOT EXISTS 조문 (
  법령일련번호 TEXT NOT NULL REFERENCES 법령(법령일련번호) ON DELETE CASCADE,
  조문키       TEXT NOT NULL,
     -- 원천 '0015001'. ⚠ **법령 안에서 유일하지 않다.**
     --   편·장·절 제목 행(조문여부='전문')은 뒤따르는 조의 키를 000 으로 끝나게 공유하는데,
     --   한 조 앞에 장과 절이 연달아 오면 두 행이 같은 키를 갖는다 — 개인정보 보호법의
     --   '0015000' 이 '제3장 개인정보의 처리' 와 '제1절 개인정보의 수집, 이용, 제공 등' 둘이다.
     --   이걸 PK 로 삼으면 INSERT OR REPLACE 가 한 행을 조용히 먹는다(실측 140 → 139).
     --   그래서 PK 는 순서이고, 조문요소도 조문키가 아니라 순서로 잇는다
  조문번호     INTEGER NOT NULL,  -- 15
  조문가지번호 INTEGER NOT NULL DEFAULT 0,
     -- ⚠ 제7조와 제7조의2 는 둘 다 조문번호=7 이고 이 컬럼으로만 갈린다.
     --   조문번호만으로 조를 식별하면 서로 다른 조가 하나로 합쳐진다.
     --   원천은 가지번호가 없을 때 키 자체를 안 준다 → 0 으로 채운다
  조문제목     TEXT,              -- 제목 없는 조가 있다(조문여부='전문' 등)
  조문내용     TEXT NOT NULL,
     -- ⚠ 원천 그대로다. 항이 있는 조에서는 '제15조(개인정보의 수집ㆍ이용)' 제목뿐이다.
     --   개인정보 보호법 조문 126개 중 109개에 항이 있고 그중 97개가 이 상태다.
     --   이 컬럼으로 검색하면 본문의 93%(68,416자 중 63,835자)가 사라진다. 검색은 전문 컬럼으로 한다
  전문         TEXT NOT NULL,
     -- 조문내용 + 모든 항·호·목을 순서대로 펼쳐 이어 붙인 것. 검색과 열람의 단위다.
     --   조문요소에서 재조립할 수 있지만 저장한다 — 조회마다 group_concat 을 정확히 쓰게 하는 쪽이 더 위험하다.
     --   실측 크기(개인정보 보호법 126개 조): 최소 17 · 중앙 440 · 최대 3,408 · 합 69,261자
  조문시행일자 TEXT,              -- 'YYYY-MM-DD'
     -- ⚠ 법령 단위 시행일자와 다를 수 있다. 한 법 안에서 조마다 시행일이 갈리는 일이 실재한다.
     -- ⚠ **조 단위 해상도뿐이다.** 조 안의 항·호·단서만 유예되는 것은 이 컬럼에 안 남고
     --   부칙 본문에만 있다. 실측: 개인정보 보호법 시행예정 버전(283839)은 조문 127개가
     --   전부 '2026-09-11' 인데, 부칙은 '제32조의2제1항 단서 및 제75조제2항제15호의
     --   개정규정은 2027년 7월 1일부터 시행한다' 고 한다.
     --   **시행일을 답하기 전에 그 버전의 마지막 부칙 제1조를 읽어라**
  조문변경여부 TEXT,              -- 'Y'|'N'
  조문여부     TEXT NOT NULL,     -- '조문' | '전문'
     -- ⚠ '전문'은 편·장·절 제목 행이다(개인정보 보호법 140개 중 14개).
     --   조 개수를 셀 때 이걸 빼지 않으면 과대 집계된다.
     -- ⚠ 더 나쁜 것: 전문 행도 조문번호를 갖고 그 값이 실제 조와 겹친다.
     --   개인정보 보호법에서 조문번호='15' 인 행이 둘인데 하나는 '제3장 개인정보의 처리'다.
     --   WHERE 조문번호=15 만 걸면 장 제목이 함께 나온다 — 에러 없이
  순서         INTEGER NOT NULL,  -- 원천 배열 순서. 편·장 구조를 복원하는 유일한 단서
  PRIMARY KEY (법령일련번호, 순서)
);
CREATE INDEX IF NOT EXISTS idx_조문_번호 ON 조문(법령일련번호, 조문번호, 조문가지번호);
CREATE INDEX IF NOT EXISTS idx_조문_키   ON 조문(법령일련번호, 조문키);

CREATE TABLE IF NOT EXISTS 조문요소 (
  -- 항·호·목 하나가 한 행이다. 판례가 '제15조 제1항 제4호'까지 가리키므로 조인 대상이 이 깊이로 필요하다.
  -- 실측 계층은 조 → 항 → 호 → 목 4단이고 목도 실재한다(12개 법령 표본에서 항 688·호 671·목 84).
  법령일련번호 TEXT NOT NULL,
  조문순서     INTEGER NOT NULL,
     -- ⚠ 조문키가 아니라 조문.순서 로 잇는다. 조문키가 법령 안에서 유일하지 않기 때문이다
     --   (조문 테이블 첫 주석 참조). 조문키로 조인하면 편·장 제목이 겹치는 자리에서
     --   한 조의 항·호가 다른 조에 붙는다
  항번호       INTEGER,           -- 원천은 '①' 로 준다. 정수로 정규화한다
     -- ⚠ NULL 인 것이 정상이다. 항 없이 조 아래 호가 바로 오는 조가 실재한다
     --   (개인정보 보호법 126개 중 12개). 원천은 그때도 '항' 객체를 주는데 항번호·항내용이 없다
  호번호       INTEGER,           -- 원천은 '1.' 로 준다
  호가지번호   INTEGER DEFAULT 0,
     -- ⚠ 조문가지번호와 같은 함정이 한 단계 아래에도 있다. 제1호와 제1호의2 는
     --   둘 다 호번호=1 이고 이 컬럼으로만 갈린다. 없으면 서로 다른 호가 한 행으로 합쳐진다.
     --   원천은 가지번호가 없을 때 키 자체를 안 준다 → 0 으로 채운다
  목번호       TEXT,              -- '가' '나' … 문자라 TEXT
  깊이         INTEGER NOT NULL,  -- 1=항 2=호 3=목. NULL 세 개를 매번 세지 않기 위한 것
  내용         TEXT NOT NULL,
  순서         INTEGER NOT NULL,  -- 조 안에서의 순서. 항·호·목이 원문 순서로 섞여 있다
  PRIMARY KEY (법령일련번호, 조문순서, 순서),
  FOREIGN KEY (법령일련번호, 조문순서) REFERENCES 조문(법령일련번호, 순서) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_조문요소_주소 ON 조문요소(법령일련번호, 조문순서, 항번호, 호번호, 호가지번호, 목번호);

CREATE TABLE IF NOT EXISTS 부칙 (
  -- 시행일과 경과조치가 여기 있다. 경과조치는 맹점의 단골 자리라 본문과 같은 비중으로 담는다.
  법령일련번호 TEXT NOT NULL REFERENCES 법령(법령일련번호) ON DELETE CASCADE,
  순서         INTEGER NOT NULL,
  부칙공포일자 TEXT,
  부칙공포번호 TEXT,
  내용         TEXT NOT NULL,
  PRIMARY KEY (법령일련번호, 순서)
);

CREATE TABLE IF NOT EXISTS 위임 (
  -- 이 법의 어느 조가 무엇에 위임했는가. 원천 lsDelegated 가 조문 단위로 준다.
  --
  -- ⚠ **이 DB 에서 규범과 규범을 잇는 유일한 테이블이다.** 여기가 없던 동안
  --   개인정보 보호법(011357)과 그 시행령(011468)은 스키마상 아무 관계도 아니었다.
  -- ⚠ **의율조문과 방향이 반대다.** 의율조문은 '판단 → 조문', 이쪽은 '조문 → 하위 규범'이다.
  --   섞으면 "이 조를 인용한 것"과 "이 조가 위임한 것"이 한 덩어리가 된다.
  법령일련번호 TEXT NOT NULL REFERENCES 법령(법령일련번호) ON DELETE CASCADE,
     -- ⚠ 법령ID(법 자체)가 아니라 버전이다. 위임은 그 버전 본문의 성질이라 개정되면 달라진다.
     --   현행 조회에는 법령 쪽에 현행연혁코드='현행' 을 걸어라
  순서         INTEGER NOT NULL,
     -- ⚠ 원천에 순서 필드가 없다. 응답 순서로 매긴 것이라 **안정 식별자가 아니다** —
     --   재수집하면 값이 바뀐다. 밖에서 이 값을 붙들지 마라
  조문번호     INTEGER NOT NULL,  -- 위임한 쪽(이 법의 조)
  조문가지번호 INTEGER NOT NULL DEFAULT 0,
  위임한자리   TEXT,
     -- 원천 '조항호목'. '제2조제6호나목' 처럼 항·호·목까지 온다.
     -- ⚠ 조문번호보다 깊지만 **문자열이다.** 조인은 조 단위로 하고 이 값은 읽거나 LIKE 로 좁힐 때 쓴다
  위임구분     TEXT,
     -- '시행령'|'시행규칙'|'인용법령'|'위임행정규칙'|'위임규정'|'위임자치법규'
     -- ⚠ **'인용법령'은 위임이 아니다** — 다른 법을 끌어 쓴 것이고 **이 테이블에서 가장 많다**
     --   (표본 400개 법령 12,661행 중 84%). 위임만 세려면 반드시 걸러라.
     --   지금 분포는 `감사.py` R14 가 낸다 — 여기 박아 두면 낡는다
     -- ⚠ 원천이 이 값을 안 주는 행이 있다 → NULL
  대상제목     TEXT,
     -- ⚠ **원천의 제목을 그대로 쓰지 않은 행이 있다.** 원천은 위임 한 덩어리에 제목
     --   하나만 붙이는데 그 아래 잎이 다른 규범을 가리키는 일이 있어서다(실측 3,344잎 중
     --   81잎 = 2.4%) — `관세법` 아래의 「조세범처벌법」, `헌법재판소 개인정보 보호 규칙`
     --   아래의 대법원규칙·중앙선거관리위원회규칙. 그때는 **잎의 근거문구가 말하는 규범**을
     --   담고 일련번호는 비운다. 제목을 그대로 붙이면 실재하는 다른 규범의 실재하는
     --   조문을 가리키는 행이 되고 **조인마저 성공한다**
  대상일련번호 TEXT,
     -- ⚠ **위임구분에 따라 가리키는 테이블이 다르다.** '위임행정규칙'이면
     --   행정규칙.행정규칙일련번호(13자리), 그 밖이면 법령.법령일련번호(6자리)다.
     --   자리 수가 달라 잘못 조인해도 0건이 나오는데, **0건이 "없다"로 읽힌다.**
     --   조인에는 언제나 위임구분을 함께 걸어라
     -- ⚠ 원천이 준 MST 그대로다. **우리 법령에 없는 일이 잦다** — 옛 버전을 가리킨다.
     --   지금 해결률은 `감사.py` R15 가 낸다(대상법령ID 쪽이 늘 높다).
     --   NULL 은 "대상을 이름으로만 알아냈다"는 뜻이다. 그때도 대상법령ID 는 채워질 수 있다
  대상법령ID   TEXT,
     -- 대상제목을 현행 법령명에 맞춰 본 결과(참조파서.법령사전 재사용, 표본 86%).
     -- ⚠ **조문 본문에 닿는 경로는 이쪽이다.** 대상일련번호는 옛 버전을 가리키는 일이 잦다.
     --   행정규칙 위임에는 NULL 이다(법령이 아니다)
  대상조문번호 INTEGER,
     -- ⚠ NULL 이 정상이다. '위임행정규칙'은 원천이 대상 조를 아예 안 준다(규칙 ID 만 준다).
     --   '인용법령'에서는 원천이 0 을 주는 일이 잦다(표본 278/1,939) → NULL 로 담는다
  대상조문가지번호 INTEGER DEFAULT 0,
  근거문구     TEXT,              -- 원천 '라인텍스트'. '대통령령으로 정하는'
     -- ⚠ **대상을 되찾은 근거가 여기다.** 원천이 제목·일련번호를 배열로 주면서
