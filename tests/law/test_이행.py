def _주석만바꾼SCHEMA() -> str:
    """구조는 그대로 두고 법령 테이블 주석만 바꾼다 — `migrate()` 가 갈아 끼울 일이 생긴다.

    ⚠️ 앵커는 **주석 문장**이라 그 문장을 손댄 날 `.replace()` 가 아무것도 안 바꾸고
       테스트가 조용히 무의미해진다. 그래서 아래에서 바뀌었는지 단언한다.
    """
    새 = 스키마.SCHEMA.replace(
        "-- 한 법령의 '버전' 하나가 한 행이다.",
        "-- 문을 재는 주석. 한 법령의 '버전' 하나가 한 행이다.",
    )
    assert 새 != 스키마.SCHEMA, "앵커 주석이 사라졌다 — 이 테스트는 지금 아무것도 안 잰다"
    return 새


