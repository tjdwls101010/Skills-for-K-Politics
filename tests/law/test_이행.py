def _구조스냅샷(conn) -> dict:
    """값을 뺀 모양만. 테이블·컬럼·인덱스·뷰 넷이 갈릴 수 있는 전부다."""
    표 = sorted(
        r[0]
        for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")
        if not r[0].startswith("sqlite_")
    )
    return {
        "테이블": 표,
        "컬럼": {t: [c[1] for c in conn.execute(f"PRAGMA table_info({t})")] for t in 표},
        "인덱스": sorted(
            r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='index'")
            if not r[0].startswith("sqlite_")
        ),
        # ⚠️ 뷰를 빼면 안 된다 — 뷰가 통째로 안 만들어져도 나머지가 전부 같아서 통과한다
        "뷰": sorted(
            (r[0], r[1]) for r in conn.execute(
                "SELECT name, sql FROM sqlite_master WHERE type='view'")
        ),
    }


# 이행이 찍는 벽시계 값. **멱등성의 관찰 대상이 아니다** — 두 DB 를 1초 사이로 만들면
# 그것만으로 달라지고, 그러면 "중간에 죽어도 따라잡는다"가 시계에 따라 빨개진다.
# 실측: 로컬에서 6회 중 1회, CI 에서 처음 돌자마자 `마지막수집일시` 가 1초 어긋났다.
벽시계메타 = ("최초수집일시", "마지막수집일시")


def _스냅샷(conn) -> dict:
    """구조 + 값. 멱등성 판정의 관찰 지점이다."""
    표 = _구조스냅샷(conn)["테이블"]

    def 행들(t):
        나온것 = [tuple(r) for r in conn.execute(f"SELECT * FROM {t}").fetchall()]
        if t != "메타":
            return 나온것
        return [(k, "<벽시계>" if k in 벽시계메타 else v) for k, v in 나온것]

    return {**_구조스냅샷(conn), "행": {t: 행들(t) for t in 표}}


