class Test조가_하나도_없는_법령:
    """⚠️ **한 문장이 법의 전부인 법이 실재한다**(실측 26건) — `경상북도와 대구광역시 간
    관할구역 변경에 관한 법률` 의 본문은 "경상북도 군위군을 … 대구광역시의 관할구역에
    편입한다." 한 줄이고, 원천은 그 문장을 **조가 아닌 행**으로 준다.

    제목으로만 접으면 그 법의 본문이 통째로 사라진다 — 조문 0행이라 검색에도 안 걸리고,
    법령 행은 멀쩡히 남아 "본문이 없는 법"처럼 보이지도 않는다. 감사가 조문 0행인 법령을
    세는 이유가 이것이고, 그 게이트가 실측에서 이 26건을 잡았다.
    """

    def test_그_문장이_조_0_으로_담긴다(self):
        행들 = 법령.조문들풀기(_몸통([
            _제목("경상북도 군위군을 대구광역시의 관할구역에 편입한다."),
        ]))
        assert [(r["조"], r["가지"]) for r in 행들] == [(0, 0)]
        assert 행들[0]["전문"] == "경상북도 군위군을 대구광역시의 관할구역에 편입한다."
        assert 행들[0]["편장절"] is None, "접을 상위 구조가 없다 — 자기 자신이 본문이다"

    def test_문장이_여럿이면_이어_붙인다(self):
        행들 = 법령.조문들풀기(_몸통([_제목("첫 문장이다."), _제목("둘째 문장이다.")]))
        assert len(행들) == 1
        assert 행들[0]["전문"] == "첫 문장이다.\n둘째 문장이다."

    def test_조가_하나라도_있으면_제목은_제목이다(self):
        """⚠️ 되돌리면 안 되는 쪽이다 — 편·장·절 제목이 조 0 으로 담기면 **모든 법에
        가짜 제0조**가 생기고 목차가 통째로 어긋난다."""
        행들 = 법령.조문들풀기(_몸통([_제목("제1장 총칙"), _조(1)]))
        assert [r["조"] for r in 행들] == [1]
        assert 행들[0]["편장절"] == "제1장 총칙"

    def test_아무_내용도_없으면_빈_목록이다(self):
        assert 법령.조문들풀기(_몸통([])) == []


