class Test시행예정_목록의_행키:
    """⚠️ **`eflaw&nw=2` 는 한 버전을 시행일마다 한 행씩 준다.** 행 키가
    `법령일련번호` 하나라고 보면 실측 1,020행이 고유 937 로 세어져 **영원히
    불완결**이 되고, 그러면 `목록받기` 가 `완결=False` 를 돌려줘 **정리·승격이
    통째로 건너뛰어진다.** 그 상태는 조용하다 — 수집은 성공하고 감사만 빨갛다.

    `현행`(law) 목록은 법 하나당 한 행이라 기본 행키가 맞다. 둘을 같은 규칙으로
    다루면 안 된다는 것이 요점이다.
    """

    class 가짜:
        def __init__(self):
            self.호출 = []

        def 목록전량(self, 종류, **kw):
            self.호출.append(kw)
            if kw.get("target") == "eflaw":
                return [{"법령일련번호": "1", "시행일자": "2032-03-01"},
                        {"법령일련번호": "1", "시행일자": "2028-03-01"}], True
            return [{"법령일련번호": "9"}], True

    def test_시행예정에만_시행일자를_행키로_준다(self):
        c = self.가짜()
        법령.목록받기(c)
        현행, 예정 = c.호출
        assert "행키" not in 현행, "현행 목록은 법 하나당 한 행이라 기본값이 맞다"
        assert 예정["행키"] == ("법령일련번호", "시행일자")

    def test_한_버전이_여러_시행일로_와도_한_번만_담는다(self):
        """목록은 dict 라 마지막 것이 남는다 — 본문 조회 대상은 MST 하나뿐이다."""
