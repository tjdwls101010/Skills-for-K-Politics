class Test목록받기:
    """⚠️ **`eflaw&nw=2` 는 한 판본을 시행일마다 한 행씩 준다.** 행 키가 `법령일련번호`
    하나라고 보면 실측 1,020행이 고유 937 로 세어져 **영원히 불완결**이 되고, 그러면
    정리가 통째로 건너뛰어진다. 그 상태는 조용하다 — 수집은 성공하고 감사만 빨갛다.

    `현행`(law) 목록은 법 하나당 한 행이라 기본 행키가 맞다. 둘을 같은 규칙으로 다루면
    안 된다는 것이 요점이다.
    """

    class 가짜:
        def __init__(self):
            self.호출 = []

        def 목록전량(self, 종류, **kw):
            self.호출.append(kw)
            if kw.get("target") == "eflaw":
                return [{"법령일련번호": "1", "법령ID": "A", "시행일자": "2032-03-01"},
                        {"법령일련번호": "1", "법령ID": "A", "시행일자": "2028-03-01"}], True
            return [{"법령일련번호": "9", "법령ID": "B", "시행일자": "2020-01-01"}], True

    def test_시행예정에만_시행일자를_행키로_준다(self):
        c = self.가짜()
        법령.목록받기(c)
        현행, 예정 = c.호출
        assert "행키" not in 현행, "현행 목록은 법 하나당 한 행이라 기본값이 맞다"
        assert 예정["행키"] == ("법령일련번호", "시행일자")

    def test_목록의_키가_법령ID_다(self):
        """본문 요청의 손잡이는 MST 지만 우리 표의 키는 법령ID 다. 목록을 MST 로 들고
        있으면 정리가 판본 교체를 소멸로 세고 멀쩡한 법을 지운다."""
        목록, 현행수, 완결 = 법령.목록받기(self.가짜())
        assert 완결 and 현행수 == 1
        assert sorted(목록) == ["A", "B"]
        assert 목록["B"]["법령일련번호"] == "9"


class Test적재:
    def test_같은_조_좌표는_한_행뿐이다(self, conn):
        """⚠️ `(법령ID, 조, 가지)` 가 UNIQUE 다. 겹치면 조 조회가 같은 조를 두 번 준다."""
        import sqlite3

        저장.저장(conn, "법령", _법령행(), {"조문": [_조문행(0, 15)]})
        with pytest.raises(sqlite3.IntegrityError):
            conn.execute(
                "INSERT INTO 조문 (법령ID, 순서, 조, 가지, 전문) VALUES ('011357', 1, 15, 0, 'x')")

    def test_다시_저장하면_옛_조문이_남지_않는다(self, conn):
        """⚠️ 개정으로 조문이 통째로 갈릴 수 있다. 부분 갱신은 없는 조문을 검색에 남긴다."""
        저장.저장(conn, "법령", _법령행(), {"조문": [_조문행(0, 15), _조문행(1, 16)]})
        저장.저장(conn, "법령", _법령행(), {"조문": [_조문행(0, 15, "개정된 제15조")]})
        행 = conn.execute("SELECT 조, 전문 FROM 조문").fetchall()
        assert [r[0] for r in 행] == [15]
        assert 행[0][1] == "개정된 제15조"

    def test_판본이_갈리면_위임이_함께_비워진다(self, conn):
        """⚠️ 위임 관계는 그 판본 본문의 성질이다. 남기면 없는 관계가 조회에 계속 걸리고,
        `위임수집판본` 이 NULL 로 돌아가야 다음 실행이 다시 받는다."""
        저장.저장(conn, "법령", {**_법령행(), "위임수집판본": "270351"}, {"조문": [_조문행(0, 15)]})
        conn.execute("INSERT INTO 위임 (법령ID, 순서, 조, 위임구분, 대상제목)"
                     " VALUES ('011357', 0, 8, '시행령', '개인정보 보호법 시행령')")
        저장.저장(conn, "법령", {**_법령행(mst="283839")}, {"조문": [_조문행(0, 15)]})
        assert conn.execute("SELECT COUNT(*) FROM 위임").fetchone()[0] == 0
        assert conn.execute("SELECT 위임수집판본 FROM 법령").fetchone()[0] is None


