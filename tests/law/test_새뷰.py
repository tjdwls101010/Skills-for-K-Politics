# 현행행정규칙 · 현행법령부칙 — 지시형 주석을 뷰로 (2026-09-11 주석 감사)
# ═══════════════════════════════════════════════════════════════

def 규칙(conn, 일련번호, ID, 이름, 현행="Y"):
    conn.execute(
        "INSERT INTO 행정규칙 (행정규칙일련번호,행정규칙ID,행정규칙명,행정규칙종류,현행여부,수집일시)"
        " VALUES (?,?,?,'고시',?,'2026-09-11 00:00:00')", (일련번호, ID, 이름, 현행))


def 부칙(conn, mst, 순서, 내용, 공포일자="2020-01-01", 공포번호="1"):
    conn.execute(
        "INSERT INTO 부칙 (법령일련번호,순서,부칙공포일자,부칙공포번호,내용) VALUES (?,?,?,?,?)",
        (mst, 순서, 공포일자, 공포번호, 내용))


class Test현행행정규칙:
    """「`현행여부='Y'` 를 걸어라」는 지시를 뷰가 대신 진다 — 현행 조회의 손이 가는 자리를 하나로."""

    def test_현행만_온다(self, conn):
        규칙(conn, "2100000000001", "10", "살아있는 고시")
        규칙(conn, "2100000000002", "11", "폐지된 고시", 현행="N")
        assert [r[0] for r in conn.execute("SELECT 행정규칙명 FROM 현행행정규칙")] == ["살아있는 고시"]

    def test_컬럼은_행정규칙과_같다(self, conn):
        원 = [r[1] for r in conn.execute("PRAGMA table_info(행정규칙)")]
        assert [r[1] for r in conn.execute("PRAGMA table_info(현행행정규칙)")] == 원


class Test현행법령부칙:
    """「시행일은 `순서 DESC LIMIT 1` 을 읽어라」— 현행 판본마다 마지막 부칙과 부칙 수를 뷰가 준다."""

    def test_현행_판본마다_마지막_부칙_한_행이다(self, conn):
        법령(conn, "100", "L1", "테스트법")
        법령(conn, "101", "L1", "테스트법", 연혁="시행예정", 시행일자=미래)
        for i in range(3):
            부칙(conn, "100", i, f"부칙 {i}호 제1조(시행일)", 공포번호=str(i))
        부칙(conn, "101", 0, "예정 판본 부칙")
        행 = conn.execute(
            "SELECT 법령일련번호, 부칙수, 내용, 부칙공포번호 FROM 현행법령부칙").fetchall()
        assert len(행) == 1
        assert tuple(행[0]) == ("100", 3, "부칙 2호 제1조(시행일)", "2")

    def test_부칙이_없는_현행_법령은_안_온다(self, conn):
        법령(conn, "100", "L1", "테스트법")
        assert conn.execute("SELECT COUNT(*) FROM 현행법령부칙").fetchone()[0] == 0
