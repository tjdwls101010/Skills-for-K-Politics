class Test조문판단수:
    def test_한_판단이_쟁점별로_여러_번_가리켜도_한_건이다(self, 판단):
        """`의율조문` 을 그대로 세면 제1조가 3건이 된다 — 그게 지금의 오답이다."""
        assert 판단.execute(
            "SELECT 참조수 FROM 조문판단수 WHERE 조문번호=1").fetchone()[0] == 2

    def test_자료종류별로_갈라_준다(self, 판단):
        행 = 판단.execute(
            "SELECT 판례수, 헌재수, 행심수, 해석수 FROM 조문판단수 WHERE 조문번호=2"
        ).fetchone()
        assert tuple(행) == (0, 1, 0, 0)

    def test_한_번도_판단받지_않은_조문이_0으로_온다(self, 판단):
        """이 뷰가 있는 이유. `NOT EXISTS` 를 손으로 쓰면 `NOT IN` 으로 미끄러진다."""
        assert [r[0] for r in 판단.execute(
            "SELECT 조문번호 FROM 조문판단수 WHERE 참조수=0")] == [3]

    def test_부칙_조문은_본칙에_섞이지_않는다(self, 판단):
        """부칙 제1조와 본칙 제1조는 전혀 다른 조다."""
        의율(판단, "판례", "P9", "L1", 1, 부칙=1)
        assert 판단.execute(
            "SELECT 참조수 FROM 조문판단수 WHERE 조문번호=1").fetchone()[0] == 2

    def test_편장절_제목_행은_조로_세지_않는다(self, 판단):
        조문(판단, "100", 3, 1, 제목="제1장 총칙", 여부="전문")
        assert 판단.execute(
            "SELECT COUNT(*) FROM 조문판단수").fetchone()[0] == 3

    def test_한_법령ID_에_현행이_둘이면_법령일련번호별로_온다(self, 판단):
        """⚠ 원천이 새 판본 시행 전 얼마간 둘 다 '현행'으로 준다. 접으면 그 창이 사라진다."""
        법령(판단, "101", "L1", "테스트법", 시행일자=미래)
        조문(판단, "101", 0, 1, 제목="목적")
        assert sorted(r[0] for r in 판단.execute(
            "SELECT 법령일련번호 FROM 조문판단수 WHERE 조문번호=1")) == ["100", "101"]

    def test_법령ID_필터가_뷰_안으로_밀려_들어간다(self, 판단):
        """⚠️ **이 뷰의 형태 자체가 성능이다.** 집계 뷰의 `WHERE` 는 `GROUP BY` 목록에
        있는 컬럼일 때만 안으로 밀린다 — `법령ID` 를 빼먹었더니 SQLite 가 **현행 조문
        전량을 집계한 뒤에** 걸렀고, 실측 2.4초였다(넣으면 0.002초). 에러가 아니라
        조회를 포기하게 만드는 침묵이라 여기서 형태를 잠근다.
        """
        줄들 = [r[3] for r in 판단.execute(
            "EXPLAIN QUERY PLAN SELECT * FROM 조문판단수 WHERE 법령ID='L1'")]
        계획 = "\n".join(줄들)
        assert "idx_법령_법령ID" in 계획, f"법령을 전량 훑는다:\n{계획}"
        # 뷰 자신을 훑는 마지막 `SCAN 조문판단수` 는 정상이다 — 재는 것은 **뷰 안**이다.
        스캔 = [l for l in 줄들
               if l.startswith("SCAN ") and not l.startswith("SCAN 조문판단수")]
        assert not 스캔, f"뷰 안에서 전량 스캔한다 — 술어가 집계 밖에 남았다:\n{계획}"
        assert "idx_의율_조문" in 계획, f"의율조문을 전량 스캔한다:\n{계획}"

    def test_GROUP_BY_에_법령ID_가_있다(self):
        """위 계획 검사가 왜 통과하는지의 근거. 빈 DB 에서는 통계가 없어 계획이
        흔들릴 수 있으므로, **원인 자체**도 함께 못박는다."""
        본문 = 스키마.SCHEMA[스키마.SCHEMA.index("CREATE VIEW 조문판단수"):]
        본문 = 본문[:본문.index(";")]
        assert "GROUP BY c.법령ID," in 본문

    def test_의율판단_뷰를_경유하지_않는다(self):
        """상관 서브쿼리 넷이 붙은 뷰 위에 집계를 얹으면 그 넷이 행마다 돈다.

        주석은 걷어내고 **SQL 만** 본다 — 주석에는 "인용 직전에는 `의율판단`" 처럼
        그 뷰를 **가리키는** 문장이 정당하게 들어 있다.
        """
        본문 = 스키마.SCHEMA[스키마.SCHEMA.index("CREATE VIEW 조문판단수"):]
        본문 = 본문[:본문.index(";")]
        SQL만 = "\n".join(
            줄.split("--")[0] for 줄 in 본문.splitlines())
        assert "의율판단" not in SQL만


