@pytest.fixture
def 판단(conn):
    """조 3개짜리 법 하나 · 제1조에 판례 둘(한쪽은 쟁점 둘) · 제2조에 헌재 하나."""
    법령(conn, "L1", "테스트법")
    조문(conn, "L1", 0, 1, 제목="목적")
    조문(conn, "L1", 1, 2, 제목="정의")
    조문(conn, "L1", 2, 3, 제목="아무도 안 다툰 조")
    판례(conn, "P1", "2024다1", 판시="첫째 쟁점")
    판례(conn, "P2", "2024다2", 법원="서울고등법원", 선고일="2023-05-05")
    conn.execute(
        "INSERT INTO 헌재결정례 (헌재결정례ID,사건번호,종국일자,판시사항,수집일시)"
        " VALUES ('D1','2020헌바1','2022-06-30','위헌 여부','2026-09-12 00:00:00')")
    conn.execute(
        "INSERT INTO 법령해석례 (법령해석례ID,안건번호,안건명,해석일자,회답,수집일시)"
        " VALUES ('H1','20-0370','질의','2021-01-01','그렇다','2026-09-12 00:00:00')")
    # 같은 판단이 같은 조를 쟁점 둘로 두 번 가리킨다 — 접히지 않으면 두 건으로 센다.
    의율(conn, "판례", "P1", "L1", 1, 쟁점=1)
    의율(conn, "판례", "P1", "L1", 1, 쟁점=2)
    의율(conn, "판례", "P2", "L1", 1)
    의율(conn, "헌재결정례", "D1", "L1", 2, 출처="심판대상조문")
    의율(conn, "법령해석례", "H1", "L1", 2, 출처="안건명")
    return conn


class Test조문판단:
    def test_세_자료종류를_한_모양으로_붙인다(self, 판단):
        """판례·헌재결정·법제처해석이 번호·기관·일자·요지 네 칸에 같은 뜻으로 들어온다 —
        그래야 "이 조를 다룬 판단"이 한 질의로 끝난다."""
        행 = 판단.execute(
            "SELECT 자료종류, 번호, 기관, 일자 FROM 조문판단"
            " WHERE 법령ID='L1' ORDER BY 일자").fetchall()
        assert [tuple(r) for r in 행] == [
            ("법령해석례", "20-0370", "법제처", "2021-01-01"),
            ("헌재결정례", "2020헌바1", "헌법재판소", "2022-06-30"),
            ("판례", "2024다2", "서울고등법원", "2023-05-05"),
            ("판례", "2024다1", "대법원", "2024-01-01"),
        ]

    def test_한_판단이_쟁점별로_여러_번_가리켜도_한_행이다(self, 판단):
        """⚠️ 안 접으면 판례 하나가 "두 번 다퉈진 것"으로 세어져 집계가 부푼다."""
        assert 판단.execute(
            "SELECT COUNT(*) FROM 조문판단 WHERE 자료종류='판례' AND 자료ID='P1'"
        ).fetchone()[0] == 1

    def test_부칙_참조는_본칙에_섞이지_않는다(self, 판단):
        """부칙은 담지 않으므로 `조문` 과 이을 자리가 없다. 섞이면 본칙 제1조를 다툰
        판례로 보인다 — 조인은 성공하고 답만 거짓이다."""
        의율(판단, "판례", "P2", "L1", 1, 부칙=1)
        assert 판단.execute(
            "SELECT COUNT(*) FROM 조문판단 WHERE 법령ID='L1' AND 조=1").fetchone()[0] == 2

    def test_법령ID_나_조를_못_푼_참조는_안_온다(self, 판단):
        """구법 표기라 못 푼 참조를 조 좌표 없이 내보내면 아무 조에나 붙는다."""
        의율(판단, "판례", "P2", None, 9)
        의율(판단, "판례", "P2", "L1", None)
        assert 판단.execute("SELECT COUNT(*) FROM 조문판단").fetchone()[0] == 4

    def test_법령ID_와_조로_좁히면_인덱스를_탄다(self, 판단):
        """⚠️ **성능이 이 뷰의 정확성의 일부다.** 전 표 훑기로 떨어지면 실측에서 초 단위가
        되고, 초 단위는 에러가 아니라 조회를 포기하게 만드는 침묵이다."""
        계획 = " ".join(r[3] for r in 판단.execute(
            "EXPLAIN QUERY PLAN SELECT * FROM 조문판단 WHERE 법령ID=? AND 조=?", ("L1", 1)))
        assert 계획.count("idx_의율_조문") == 3, 계획


class Test조문판단수:
    def test_자료종류별로_갈라_센다(self, 판단):
        행 = 판단.execute(
            "SELECT 조, 판례수, 헌재수, 해석수 FROM 조문판단수"
            " WHERE 법령ID='L1' ORDER BY 순서").fetchall()
        assert [tuple(r) for r in 행] == [(1, 2, 0, 0), (2, 0, 1, 1), (3, 0, 0, 0)]

    def test_한_번도_판단받지_않은_조가_0_으로_온다(self, 판단):
        """⚠️ **`NOT IN` 으로는 이 답을 못 얻는다** — 안 다툰 조는 `의율조문` 에 행이 아예
        없어서 미끄러진다. 0 이 행으로 와야 "이 조는 아직 판단이 없다"를 말할 수 있다."""
        assert 판단.execute(
            "SELECT 제목 FROM 조문판단수 WHERE 법령ID='L1' AND 판례수+헌재수+해석수=0"
        ).fetchone()[0] == "아무도 안 다툰 조"

    def test_목록과_수가_갈리지_않는다(self, 판단):
        """⚠️ `조문판단` 이 아니라 `의율조문` 위에서 세면 쟁점 중복이 수에만 남아, 목록을
        펴 보면 2건인데 수는 3 이라고 말한다."""
        for 조, 기대 in ((1, 2), (2, 2)):
            목록 = 판단.execute(
                "SELECT COUNT(*) FROM 조문판단 WHERE 법령ID='L1' AND 조=?", (조,)).fetchone()[0]
            수 = 판단.execute(
                "SELECT 판례수+헌재수+해석수 FROM 조문판단수 WHERE 법령ID='L1' AND 조=?",
                (조,)).fetchone()[0]
            assert 목록 == 수 == 기대

    def test_가지가_다른_조는_따로_센다(self, 판단):
        """제7조와 제7조의2 는 조=7 을 공유한다. 합치면 두 조의 판단이 한 줄이 된다."""
        조문(판단, "L1", 3, 7)
        조문(판단, "L1", 4, 7, 가지=2)
        의율(판단, "판례", "P1", "L1", 7, 가지=2)
        행 = 판단.execute(
            "SELECT 가지, 판례수 FROM 조문판단수 WHERE 법령ID='L1' AND 조=7"
            " ORDER BY 가지").fetchall()
        assert [tuple(r) for r in 행] == [(0, 0), (2, 1)]

    def test_법령명을_붙여_준다(self, 판단):
        """조 번호만 있는 결과는 여러 법을 한 화면에 놓았을 때 읽을 수 없다."""
        assert 판단.execute(
            "SELECT DISTINCT 법령명 FROM 조문판단수").fetchone()[0] == "테스트법"


