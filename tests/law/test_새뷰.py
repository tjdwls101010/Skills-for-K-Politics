from __future__ import annotations

import pytest


def 법령(conn, 법령ID, 이름, mst=None, 시행예정=None):
    conn.execute(
        "INSERT INTO 법령 (법령ID,법령일련번호,법령명,법종구분,시행일자,수집일시,"
        "시행예정일련번호,시행예정일) VALUES (?,?,?,'법률','2020-01-01',"
        "'2026-09-12 00:00:00',?,?)",
        (법령ID, mst or f"MST{법령ID}", 이름, 시행예정, "2099-01-01" if 시행예정 else None))


def 조문(conn, 법령ID, 순서, 조, 가지=0, 제목=None, 전문=None, 편장절=None):
    conn.execute(
        "INSERT INTO 조문 (법령ID,순서,조,가지,편장절,제목,전문)"
        " VALUES (?,?,?,?,?,?,?)",
        (법령ID, 순서, 조, 가지, 편장절, 제목, 전문 or f"제{조}조 본문"))


def 의율(conn, 종류, 자료ID, 법령ID, 조, 가지=0, 부칙=0, 쟁점=None, 출처="참조조문"):
    conn.execute(
        "INSERT INTO 의율조문 (자료종류,자료ID,출처,쟁점번호,법령명원문,법령ID,"
        "부칙여부,조,가지,원문조각) VALUES (?,?,?,?,'테스트법',?,?,?,?,'조각')",
        (종류, 자료ID, 출처, 쟁점, 법령ID, 부칙, 조, 가지))


def 판례(conn, 판례ID, 사건번호, 법원="대법원", 선고일="2024-01-01", 판시="쟁점 요약"):
    conn.execute(
        "INSERT INTO 판례 (판례ID,사건번호,법원명,선고일자,판시사항,수집일시)"
        " VALUES (?,?,?,?,?,'2026-09-12 00:00:00')",
        (판례ID, 사건번호, 법원, 선고일, 판시))


