class Test판본이_갈리면_다시_받는다:
    """⚠️ **`저장()` 이 `INSERT OR REPLACE` 라 부모 행을 한 번 지운다.** 그러면
    `위임` 의 `ON DELETE CASCADE` 가 함께 터져 그 법의 위임이 통째로 사라진다.
    조문은 `저장()` 이 자식으로 같이 다시 넣지만 **위임은 별도 API 호출이라 다시 넣을
    것이 없다.** `collect.py --자료 법령 --전량` 한 번이면 벌어진다.

    받은 **시각**을 적으면 판본이 갈렸는지를 사후에 판별할 수 없다. 그래서 적는 것은
    **받은 시점의 MST** 이고, 재개 판정은 그것이 지금의 `법령일련번호` 와 같은가다.
    """

    def test_받으면_그_판본이_표지로_남는다(self, conn):
        _법령(conn)
        위임._완료(conn, "011357", "270351", [{"순서": 0, "조": 1, "위임구분": "시행령"}])
        assert conn.execute("SELECT 위임수집판본 FROM 법령").fetchone()[0] == "270351"
        assert 위임.받을대상(conn) == []

    def test_판본이_갈리면_위임이_사라지고_다시_받을_대상이_된다(self, conn):
        _법령(conn)
        위임._완료(conn, "011357", "270351", [{"순서": 0, "조": 1, "위임구분": "시행령"}])
        _법령(conn, mst="283839")          # 개정 판본을 받았다
        assert conn.execute("SELECT COUNT(*) FROM 위임").fetchone()[0] == 0
        assert 위임.받을대상(conn) == [("011357", "283839")]

    def test_위임이_원래_0행이어도_표지로_완료를_안다(self, conn):
        """⚠️ 실측 표본 61건 중 12건(20%)이 위임 0행이다. 행 수로 완료를 판정하면
        매일 그 20%를 헛되이 다시 두드린다."""
        _법령(conn)
        위임._완료(conn, "011357", "270351", [])
        assert 위임.받을대상(conn) == []

    def test_받는_사이에_판본이_갈리면_표지를_안_쓴다(self, conn):
        """⚠️ 위임을 받는 동안 법령 행이 새 판본으로 갈렸으면 이 응답은 옛 판본의 것이다 —
        완료로 적으면 **새 판본의 위임이 영영 안 받아진다.**"""
        _법령(conn, mst="283839")
        위임._완료(conn, "011357", "270351", [])     # 옛 판본의 응답이 늦게 도착했다
        assert conn.execute("SELECT 위임수집판본 FROM 법령").fetchone()[0] is None
        assert 위임.받을대상(conn) == [("011357", "283839")]

    def test_사라진_법령의_실패_원장을_치운다(self, conn):
        """⚠️ 안 치우면 그 행이 영영 재시도도 완료도 안 되고, 재시도 잔존 게이트가
        고칠 수 없는 빨간불로 굳는다."""
        저장.record_failure(conn, "위임", "없는법", "재시도", "타임아웃")
        수치 = 위임.수집(conn, None, 로그=lambda *_: None)
        assert 수치["정리"] == 1
        assert conn.execute("SELECT COUNT(*) FROM 수집실패").fetchone()[0] == 0


class Test봉투가_바뀌면_완료로_찍지_않는다:
    """⚠️ **`파싱()` 은 모르는 응답에 `[]` 를 준다** — 위임 없는 법이 흔해서 그렇게 만들었다.
    그 관용이 **원천이 봉투를 바꾼 날 전량을 조용히 '위임 없음'으로 확정한다.**
    빈 결과와 못 알아본 응답을 가르는 것은 봉투 검사뿐이다.
    """

    class 가짜:
        def __init__(self, payload):
            self.payload = payload

        def _json(self, url, params):
            return self.payload

    @pytest.mark.parametrize(
        "payload",
        [{"lsDelegated": {"법령": []}}, {"lsDelegated": []}, {"다른봉투": {}}],
    )
    def test_모양이_바뀌면_터진다(self, payload):
        with pytest.raises(원천.API오류, match="봉투가 없다"):
            위임.받는다(self.가짜(payload), "1")

    def test_빈_응답은_위임_없음이다(self):
        """⚠️ 키가 하나도 없는 `{}` 는 형식 변경이 아니라 '여기 아무것도 없다'다.
        실측 6,411건 중 2건이고 재시도해도 같았다 — 실패로 적으면 매일 두드린다."""
        assert 위임.받는다(self.가짜({}), "1") == {"lsDelegated": {"법령": {}}}

    def test_봉투는_있고_위임만_없으면_빈_결과다(self):
        payload = {"lsDelegated": {"법령": {"법령정보": {"법령명": "x"}}}}
        assert 위임.받는다(self.가짜(payload), "1") == payload
        assert 위임.파싱(payload) == []


class Test404_는_일시적이다:
    """⚠️ **이 엔드포인트의 404 를 '위임 없음'으로 확정하면 안 된다.**

    전량 수집에서 93건이 404 로 실패했는데 **재시도하니 91건이 데이터를 돌려줬다**
    (7,804행). 그때 완료로 찍었다면 그 7,804행이 영영 사라진다.

    `source.py` 의 규율("본문의 4xx 는 원천의 답이지 일시적 오류가 아니다")은 판례 본문에서
    참인 것이고 여기서는 **실측이 반대**다. 위임 없음의 신호는 404 가 아니라
    **봉투는 멀쩡한데 `위임조문정보` 가 없는 응답**뿐이다.
    """

    class 사백사:
        워커 = 1

        def _json(self, url, params):
            raise 원천.원천에없음(f"{url}: HTTP 404")

    def test_실패로_적고_다음_실행이_다시_받는다(self, conn):
        _법령(conn)
        수치 = 위임.수집(conn, self.사백사(), 로그=lambda *_: None)
        assert 수치["실패"] == 1 and 수치["받음"] == 0
        assert 위임.받을대상(conn) == [("011357", "270351")], \
            "다시 받을 대상에서 빠지면 그 법은 영영 빈다"
        assert conn.execute(
            "SELECT 실패종류 FROM 수집실패 WHERE 자료종류='위임'").fetchone()[0] == "재시도"

    def test_실패_원장의_키도_법령ID_다(self, conn):
        """⚠️ MST 로 적으면 판본이 갈릴 때마다 원장에 새 행이 쌓이고, 어느 것이 지금
        유효한 실패인지 알 수 없다. 어느 판본이 실패했는지는 메시지가 진다."""
        _법령(conn)
        위임.수집(conn, self.사백사(), 로그=lambda *_: None)
        자료ID, 메시지 = conn.execute(
            "SELECT 자료ID, 메시지 FROM 수집실패 WHERE 자료종류='위임'").fetchone()
        assert 자료ID == "011357" and "270351" in 메시지


