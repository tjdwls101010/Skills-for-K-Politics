"""법률안 → 대상 법령 매칭.

**케이스는 전부 실 DB 에서 뽑은 실물 의안명이다**(CONGRESS.db 22대 법률안 20,723건, 2026-09-12).
지어낸 이름으로 재면 실제로 부딪히는 표기 차이를 못 만난다 — 공백을 다 뗀 공포법률명,
`ㆍ`와 `·`가 섞인 가운뎃점, 정식 이름 안의 괄호가 그것들이다.
"""

import sqlite3

import pytest

import snapshot


class Test법령명추출:
    @pytest.mark.parametrize("의안명, 기대", [
        # ── 일부개정: 접미를 떼면 법 이름이 남는다
        ("공직선거법 일부개정법률안", "공직선거법"),
        ("개인정보 보호법 일부개정법률안", "개인정보보호법"),
        ("각급 법원의 설치와 관할구역에 관한 법률 일부개정법률안", "각급법원의설치와관할구역에관한법률"),
        # ── (대안) 표지는 끝에서만 뗀다
        ("농어촌특별세법 일부개정법률안(대안)", "농어촌특별세법"),
        ("성폭력방지 및 피해자보호 등에 관한 법률 일부개정법률안(대안)",
         "성폭력방지및피해자보호등에관한법률"),
        # ── 전부개정·폐지
        ("사면법 전부개정법률안", "사면법"),
        ("민사소송비용법 폐지법률안", "민사소송비용법"),
        # ── 제정: '법안'·'법률안' 이 이름의 끝을 이룬다
        ("군무원복지기본법안", "군무원복지기본법"),
        ("교도관 직무집행법안", "교도관직무집행법"),
        ("청사의 관리에 관한 법률안", "청사의관리에관한법률"),
        ("대형산불 피해복구 및 지역재건을 위한 특별법안", "대형산불피해복구및지역재건을위한특별법"),
        # ── 가운뎃점 통일: 원천에 U+318D 와 U+00B7 가 섞여 온다
        ("기후위기 대응을 위한 탄소중립ㆍ녹색성장 기본법 일부개정법률안",
         "기후위기대응을위한탄소중립·녹색성장기본법"),
        ("초·중등교육법 일부개정법률안", "초·중등교육법"),
        ("공익목적회사 설립ㆍ운영에 관한 법률안", "공익목적회사설립·운영에관한법률"),
        # ── 공백 제거: 공포법률명이 이 모양으로 온다
        ("성폭력방지및피해자보호등에관한법률", "성폭력방지및피해자보호등에관한법률"),
        ("자동차관리법", "자동차관리법"),
        # ── 한자 공포법률명은 그대로 남는다 — 매칭에 실패하고 의안명으로 떨어지는 것이 정상이다
        ("行政訴訟法", "行政訴訟法"),
        # ── 일괄개정: 이름이 하나가 아니라 못 뽑는다(미매칭으로 남는다)
        ("폐기물관리법 등 8개 법률 일부개정법률안", "폐기물관리법등8개법률"),
        # ── 빈 입력
        ("", None),
    ])
    def test_정규형을_뽑는다(self, 의안명, 기대):
        assert snapshot.법령명추출(의안명) == 기대

    def test_None_은_None_이다(self):
        assert snapshot.법령명추출(None) is None

    def test_정식_이름_안의_괄호는_안_지운다(self):
        """`이스포츠(전자스포츠) 진흥에 관한 법률` 처럼 괄호가 이름의 일부인 법이 있다.
        괄호를 통째로 지우면 그 법이 영영 안 잡힌다."""
        assert snapshot.법령명추출("이스포츠(전자스포츠) 진흥에 관한 법률 일부개정법률안") == \
            "이스포츠(전자스포츠)진흥에관한법률"

    def test_접미는_긴_것부터_본다(self):
        """`법률안` 은 `일부개정법률안` 의 접미다. 짧은 것부터 보면 '○○법 일부개정' 이 남는다."""
        assert snapshot.법령명추출("도로법 일부개정법률안") == "도로법"


@pytest.fixture
def 사전(원천법령):
    conn = sqlite3.connect(f"file:{원천법령}?mode=ro", uri=True)
    d = snapshot.법령사전(conn)
    conn.close()
    return d


class Test사전:
    def test_법률만_담는다(self, 사전):
        """법률안이 대통령령·부령에 붙을 여지를 없앤다. 실측에서 좁혀도 매칭 결과는 안 바뀌고
        사전만 8,213 → 2,823 키로 줄었다."""
        assert "개인정보보호법시행령" not in 사전
        assert "개인정보보호법" in 사전

    def test_시행예정_법령도_담는다(self, 사전):
        """공포됐지만 아직 시행 전인 법을 고치는 법률안이 실재한다(실측 105건).
        '대상 법령' 은 현행 여부와 무관하다."""
        assert "국제물류진흥지역지정및육성에관한특별법" in 사전
        assert 사전["국제물류진흥지역지정및육성에관한특별법"][0] == "011333"

    def test_법령ID_로_접힌다(self, 사전):
        assert 사전["개인정보보호법"] == ("011111", "개인정보 보호법")


class Test매칭:
    def test_공포법률명을_먼저_본다(self, 사전):
        """공포된 법안만 갖는 필드라 법제처 표기에 맞춰 온다 — 더 믿을 만하다."""
        assert snapshot.매칭("도로법 일부개정법률안(대안)", "도로법", 사전) == \
            ("011222", "도로법", "공포법률명")

    def test_공포법률명이_안_맞으면_의안명으로_떨어진다(self, 사전):
        """공포법률명이 한자(`行政訴訟法`)로 온 실측 사례가 있다."""
        assert snapshot.매칭("도로법 일부개정법률안", "道路法", 사전) == \
            ("011222", "도로법", "의안명")

    def test_제정안은_미매칭이다(self, 사전):
        """고칠 현행법이 애초에 없다. **미매칭 ≠ 법이 없다** 가 아니라 여기서는 정말로 없다."""
        assert snapshot.매칭("우주항공진흥법안", None, 사전) == (None, None, "미매칭")

    def test_일괄개정은_미매칭으로_남는다(self, 사전):
        """`등 N개 법률` 은 이름이 하나가 아니다. 실 DB 에 54건뿐이라 본문 파싱은 붙이지 않았다."""
        assert snapshot.매칭("도로법 등 8개 법률 일부개정법률안", None, 사전)[2] == "미매칭"


class Test표에들어간다:
    def test_법률안마다_한_행_이상_있다(self, 빌드):
        _, conn, _ = 빌드
        assert conn.execute("SELECT COUNT(DISTINCT 의안번호) FROM 법률안대상법령").fetchone()[0] == 3

    def test_미매칭도_행으로_남는다(self, 빌드):
        """행이 없으면 "아직 계산 안 했다"와 "맞는 법이 없다"가 구별되지 않는다."""
        _, conn, _ = 빌드
        assert conn.execute(
            "SELECT 법령ID, 법령명, 매칭근거 FROM 법률안대상법령 WHERE 의안번호='2200003'"
        ).fetchone() == (None, None, "미매칭")

    def test_비법률안은_안_들어간다(self, 빌드):
        _, conn, _ = 빌드
        종류 = {r[0] for r in conn.execute(
            "SELECT b.의안종류 FROM 법률안대상법령 t JOIN 의안 b USING (의안번호)")}
        assert 종류 == {"법률안"}

    def test_매칭근거별_건수가_결과에_남는다(self, 빌드):
        결과, _, _ = 빌드
        assert 결과["매칭"] == {"공포법률명": 1, "의안명": 1, "미매칭": 1, "법률안": 3}
