"""`신선도` 뷰 — "이 답은 언제 기준인가"가 한 질의로 끝난다.

스킬은 로드할 때 이 뷰 하나를 박스로 주입한다. 그래서 **빈 DB 에서도 한 행이어야 한다** —
0행이면 주입 줄이 빈 박스를 내고, 읽는 쪽은 "신선도를 못 읽었다"와 "DB 가 비었다"를 구별할
수단이 없다. 값이 전부 NULL 인 한 행이 그 구별을 진다.
"""

from congress import db


def 신선도(conn):
    행들 = conn.execute("SELECT * FROM 신선도").fetchall()
    assert len(행들) == 1, f"{len(행들)}행이다 — 신선도는 항상 한 행이다"
    return 행들[0]


def test_빈_DB_에서도_한_행이고_값은_전부_NULL(conn):
    행 = 신선도(conn)
    assert tuple(행) == (None, None, None, None, None)


def test_적재기준시각은_의안의_마지막_수집시각이다(conn):
    db.upsert_위원회(conn, "정무위원회")
    conn.executemany("INSERT INTO 의안 (의안번호,의안ID,의안명,수집시각) VALUES (?,?,?,?)",
                     [("2200001", "X", "가", "2026-09-04 06:44:19"),
                      ("2200002", "Y", "나", "2026-09-11 06:41:02")])
    assert 신선도(conn)["적재기준시각"] == "2026-09-11 06:41:02"


def test_위반이_남은_감사는_감사통과_0_과_상세를_준다(conn):
    conn.execute("INSERT INTO 수집상태 (대상,키,상태,건수,상세,갱신일시) "
                 "VALUES ('감사','전체','완료',1,'A11=1','2026-09-04 06:45:59')")
    행 = 신선도(conn)
    assert 행["감사통과"] == 0
    assert 행["감사상세"] == "A11=1"
    assert 행["감사시각"] == "2026-09-04 06:45:59"


def test_건수가_0_인_완료는_감사통과_1_이고_상세가_없다(conn):
    conn.execute("INSERT INTO 수집상태 (대상,키,상태,건수,상세,갱신일시) "
                 "VALUES ('감사','전체','완료',0,NULL,'2026-09-12 06:45:59')")
    행 = 신선도(conn)
    assert 행["감사통과"] == 1
    assert 행["감사상세"] is None


def test_건너뛴_대상이_있으면_경고가_그_이름을_말한다(conn):
    """건너뜀은 실패가 아니라 "오늘은 안 물었다"이다 — 그 대상의 값만 옛것이고 나머지는 아니다."""
    conn.execute("INSERT INTO 수집상태 (대상,키,상태,갱신일시) VALUES ('의원현직','전체','건너뜀','2026-09-12 06:40:00')")
    경고 = 신선도(conn)["경고"]
    assert "의원현직" in 경고
    assert "발의·표결·발언 이력은 영향받지 않는다" in 경고
