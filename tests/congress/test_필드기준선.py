"""원천의 **필드 집합**이 그대로인가 — 개별 필드 규칙을 늘리는 대신 축을 하나 둔다.

⚠️ **"필드는 남았는데 의미가 바뀐" 변화는 값 검사로 못 잡는다.** 잡을 수 있는 것은
집합의 변화다 — 쓰던 필드가 사라졌거나, 없던 필드가 생겼거나. 필드마다 규칙을 하나씩
다는 것은 rail 이고, 다음 필드가 생기면 또 달아야 한다.

⚠️ **두 방향의 처분이 다르다.** verify 가 빨가면 그날 수집이 통째로 건너뛰어진다
(`collect.yml`). 그러니 **사라진 필드만 게이트**다 — 우리가 그걸 읽고 있을 수 있어
멈추는 것이 맞다. **새 필드는 보고값**이다: 늘어난 것은 우리 코드를 깨지 않는데,
그것 때문에 수집을 멈추면 원천이 필드 하나 늘린 날 코퍼스가 하루 낡는다.
"""

import json
import re
from pathlib import Path

import pytest

import verify

수집기 = Path(verify.__file__).resolve().parent


def 수집기가쓰는API() -> set[str]:
    """수집 스크립트가 실제로 부르는 OpenAPI 이름들.

    ⚠️ **손으로 관리하는 목록을 두지 않는다.** 목록과 코드가 갈리는 순간 이 테스트는
    "다 있다"고 말하면서 아무것도 안 지킨다. 수집기가 `<쓸모>_API = "이름"` 상수로 스스로
    선언하고 있으므로 그것을 읽는다 — 새 API 를 쓰기 시작하면 상수도 함께 생긴다.
    """
    본다 = re.compile(r"""^\w*_API\s*=\s*["']([A-Za-z][A-Za-z0-9_]+)["']""", re.M)
    이름 = set()
    for f in ("bills.py", "members.py", "meetings.py", "collect.py"):
        이름 |= set(본다.findall((수집기 / f).read_text(encoding="utf-8")))
    return 이름


class Test필드모음:
    def test_항상_있는_것과_가끔_있는_것을_가른다(self):
        """⚠️ **원천은 값이 NULL 인 필드를 행에서 통째로 뺀다.** 그래서 합집합만 재면
        표본이 바뀌는 날 희소 필드가 "사라졌다"로 읽히고, **원천이 안 바뀌었는데 수집이
        멈춘다.** 전 행에 있던 것만 게이트로 삼고 나머지는 그 밖에 둔다."""
        본것 = verify.필드모음([{"A": 1, "B": 2}, {"A": 3, "C": 4}])
        assert 본것 == {"항상": ["A"], "가끔": ["B", "C"]}

    def test_한_행뿐이면_전부_항상이_아니다(self):
        """⚠️ **표본 1행에서는 '전 행에 있다'가 아무것도 뜻하지 않는다.** 그걸 항상으로
        읽으면 그 한 행의 희소 필드가 전부 게이트가 되어 4번 함정으로 되돌아간다."""
        본것 = verify.필드모음([{"A": 1, "희소": 2}])
        assert 본것 == {"항상": [], "가끔": ["A", "희소"]}

    def test_빈_응답은_아예_안_잰다(self):
        """⚠️ **0행을 "필드가 전부 사라졌다"로 읽으면 안 된다.** 빈 응답은 다른 게이트가
        잡는 사고이고, 여기서까지 빨개지면 같은 사고를 두 번 세면서 원인을 흐린다."""
        assert verify.필드모음([]) is None


def _잼(항상=(), 가끔=()):
    return {"항상": sorted(항상), "가끔": sorted(가끔)}


class Test필드대조:
    기준 = {"의안": _잼(["BILL_NO", "BILL_NM"], ["약칭"]), "회의": _잼(["CONF_ID"])}

    def test_그대로면_아무것도_안_난다(self):
        사라짐, 새것 = verify.필드대조(self.기준, {"의안": _잼(["BILL_NM", "BILL_NO"], ["약칭"])})
        assert 사라짐 == {} and 새것 == {}

    def test_사라진_필드를_이름으로_짚는다(self):
        사라짐, _ = verify.필드대조(self.기준, {"의안": _잼(["BILL_NO"])})
        assert 사라짐 == {"의안": ["BILL_NM"]}

    def test_희소_필드가_이번_표본에_안_와도_안_잡는다(self):
        """⚠️ **이게 4번 함정이다.** 기준선 뜨던 날 표본에만 있던 희소 필드가 오늘 표본에
        없다고 빨개지면, 원천이 그대로인데 그날 수집이 통째로 건너뛰어진다."""
        사라짐, _ = verify.필드대조(self.기준, {"의안": _잼(["BILL_NO", "BILL_NM"])})
        assert 사라짐 == {}

    def test_희소로_내려앉은_필드도_사라진_게_아니다(self):
        사라짐, _ = verify.필드대조(self.기준, {"의안": _잼(["BILL_NO"], ["BILL_NM"])})
        assert 사라짐 == {}

    def test_새_필드도_짚는다(self):
        _, 새것 = verify.필드대조(self.기준, {"의안": _잼(["BILL_NO", "BILL_NM"], ["AI요약"])})
        assert 새것 == {"의안": ["AI요약"]}

    def test_이번에_안_잰_것은_비교하지_않는다(self):
        """⚠️ **안 잰 것과 사라진 것은 다르다.** 이번 실행이 그 API 에 안 갔다는 이유로
        전 필드를 빨갛게 만들면, 다음 사람은 표를 통째로 무시하게 된다."""
        사라짐, 새것 = verify.필드대조(self.기준, {"의안": _잼(["BILL_NO", "BILL_NM"], ["약칭"])})
        assert 사라짐 == {} and 새것 == {}

    def test_기준선에_없는_이름은_전부_새것이_아니다(self):
        """처음 재 보는 API 는 '전 필드가 새로 생겼다'가 아니라 **아직 기준선이 없는 것**이다."""
        사라짐, 새것 = verify.필드대조(self.기준, {"표결": _잼(["MEMBER_NO"])})
        assert 사라짐 == {} and 새것 == {}


class Test기준선파일:
    def test_레포에_담겨_있고_읽힌다(self):
        """⚠️ **기준선은 커밋된 파일이라야 한다.** 실행 때마다 새로 만들면 비교 대상이
        자기 자신이 되어 어떤 변화도 안 잡힌다 — 그게 이 축이 고치려는 결함이다."""
        기준 = verify.필드기준선()
        assert 기준, "원천필드.json 이 비었다"
        assert all(set(v) == {"항상", "가끔"} for v in 기준.values())

    def test_기준선이_정렬돼_있다(self):
        """diff 가 읽히려면 순서가 안정적이어야 한다 — 순서만 뒤집힌 diff 는 아무도 안 본다."""
        기준 = verify.필드기준선()
        assert all(칸 == sorted(칸) for v in 기준.values() for 칸 in v.values())

    def test_수집기가_쓰는_API_가_전부_기준선에_있다(self):
        """⚠️ **이 축이 지키는 것은 기준선에 든 API 뿐이다.** 수집기가 쓰는데 여기 없는
        API 는 필드가 사라져도 V23 이 초록이고, 그 값이 게이트가 아니라 보고값이면
        **DB 훼손까지 조용하다**(실측 지적: `ALLNAMEMBER.PLPT_NM` 이 사라지면 의원 전량
        upsert 가 정당을 NULL 로 덮는데 감사는 R3 보고값일 뿐이다).

        그래서 목록을 손으로 관리하지 않는다 — 수집기 소스에서 뽑아 대조한다. 새 API 를
        쓰기 시작하면 **재기 전까지 이 테스트가 빨갛다.**
        """
        쓰는것 = 수집기가쓰는API()
        빠진것 = sorted(쓰는것 - {이름.split()[0] for 이름 in verify.필드기준선()})
        assert not 빠진것, (
            "수집기가 쓰는데 필드 기준선에 없는 API — verify.py 에서 재고 "
            "`--기준선갱신` 해라: " + ", ".join(빠진것)
        )

    def test_검사_자신이_동작한다(self):
        """⚠️ 정규식이 안 맞으면 0개를 돌려주고, 0개는 '전부 있다'와 구별되지 않는다."""
        쓰는것 = 수집기가쓰는API()
        assert len(쓰는것) >= 10, f"수집기 API 를 {len(쓰는것)}개밖에 못 찾았다 — 추출이 깨졌다"

    def test_파일이_없으면_빈_기준선이다(self, tmp_path, monkeypatch):
        """⚠️ 없는 파일에 예외를 내면 **처음 돌리는 사람이 아무 진단도 못 받는다.**"""
        monkeypatch.setattr(verify, "필드기준선경로", tmp_path / "없다.json")
        assert verify.필드기준선() == {}
