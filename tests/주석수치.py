"""스키마 주석에 **실측 건수·비율**이 다시 들어오면 실패한다.

건수는 이 DB 에서 **쓰는 순간부터 낡는다** — 수집이 하루 1회 돌기 때문이다. 재작성 직전
(2026-08-22) 재조회해 보니 수치가 든 주석은 예외 없이 틀려 있었다: 원안가결 980→1,031 ·
인용법령 84%→63.7% · 조문형식여부 16.7%→30.9% · 행정규칙 "폐지된 것은 없다"→1,578행.

**식별자는 걸지 않는다.** 의안번호 `2208496`·법령ID `011357` 은 안 낡는다 — 낡는 것은
"몇 건이냐"이지 "어느 것이냐"가 아니다. 그래서 세는 말(건·행·개·명…)이 붙었거나
천 단위로 끊었거나 백분율인 것만 잡는다.

값 대신 조회를 시켜라. `SELECT DISTINCT …` 한 줄이 짧으면서 동시에 더 정확하다.
"""

import re

_세는말 = "건|행|개|명|종|잎|쪽|자|배|페이지|요청"
_수치 = re.compile(
    r"\b\d{1,3}(?:,\d{3})+\b"          # 천 단위로 끊은 수 — 세려고 쓴 것이다
    r"|\b\d+(?:\.\d+)?\s*%"            # 백분율
    rf"|(?<![\d,])\d[\d,]{{2,}}\s*(?:{_세는말})\b"   # 세는 말이 붙은 세 자리 이상
)
_예외 = re.compile(r"\d{4}-\d{2}-\d{2}|\d{4}년")


def 주석수치(schema: str) -> list[tuple[str, str]]:
    나온것 = []
    for 줄 in schema.splitlines():
        if "--" not in 줄:
            continue
        본문 = _예외.sub(" ", 줄[줄.index("--"):])
        나온것 += [(m.group(0).strip(), 줄.strip()) for m in _수치.finditer(본문)]
    return 나온것


def 검사(schema: str, 이름: str, 허용: dict[str, str]) -> None:
    남은 = [(v, l) for v, l in 주석수치(schema) if v not in 허용]
    assert not 남은, (
        f"{이름}.SCHEMA 주석에 실측 건수·비율 {len(남은)}개가 있다. **조회로 대체하거나**"
        f" 안 낡는 이유를 붙여 `허용` 에 올려라:\n"
        + "\n".join(f"  {v!r}  ←  {l[:88]}" for v, l in 남은[:15])
    )


def 지면수치(본문: str) -> list[tuple[str, str]]:
    """같은 규칙을 **지면 전체**에 건다 — 마크다운에는 `--` 접두가 없다.

    스키마 쪽과 규칙이 같아야 하는 이유가 여기 있다. 수치를 스키마에서 몰아내도
    SKILL.md 가 그 사본을 들고 있으면 **낡는 자리가 옮겨갔을 뿐**이고, 실제로 그랬다 —
    `tests/주석수치.py` 가 금지한 건수가 SKILL.md 에는 그대로 살아 있었다.
    """
    나온것 = []
    for 줄 in 본문.splitlines():
        본 = _예외.sub(" ", 줄)
        나온것 += [(m.group(0).strip(), 줄.strip()) for m in _수치.finditer(본)]
    return 나온것


def 지면검사(본문: str, 이름: str, 허용: dict[str, str]) -> None:
    남은 = [(v, l) for v, l in 지면수치(본문) if v not in 허용]
    assert not 남은, (
        f"{이름} 에 실측 건수·비율 {len(남은)}개가 있다. **조회로 대체하거나**"
        f" 안 낡는 이유를 붙여 `허용` 에 올려라:\n"
        + "\n".join(f"  {v!r}  ←  {l[:88]}" for v, l in 남은[:15])
    )
